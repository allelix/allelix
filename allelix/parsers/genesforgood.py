"""Parser for Genes for Good 23andMe-style text downloads.

Genes for Good (a University of Michigan study, now closed) gave each
participant a zip of their measured and imputed genotypes as VCF and as a
"23andMe-style" text file. The text file's rows are 23andMe's (4 tab
columns, concatenated genotype, ``D``/``I`` indel calls, one letter for
haploid calls), so the 23andMe row reader is reused. What differs is the
comment block, which PLINK wrote:

    # Genes for Good v1.2: ..., genotype calls. For more information, ...
    # This data file generated by PLINK on: ...
    # ...
    # Human genome reference ...: GRCh37/...
    #
    # rsid	chromosome	position	genotype

Specifics:
    - Detection key: the first non-blank line starts ``# Genes for Good v``.
      The 23andMe parser does not claim these files (no 23andMe banner).
    - The imputed file says ``imputed genotype calls`` on that first line;
      its metadata ``method`` is ``array-imputed`` so every report says the
      genotypes are imputed. The measured file has no ``method``.
    - Uncalled sites are left out of the file rather than written as ``--``.
    - The build comes from the header line through ``read_header_build``,
      and is checked by the known-SNP positions like any other label.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, ClassVar

from allelix.parsers._helpers import DamagedFileError, first_nonblank_line, open_genotype_text
from allelix.parsers.base import GenotypeMetadata, read_header_build
from allelix.parsers.twentythreeandme import TwentyThreeAndMeParser

if TYPE_CHECKING:
    from pathlib import Path

BANNER_PREFIX = "# Genes for Good v"
IMPUTED_MARKER = "imputed genotype calls"
# The ``method`` value for the imputed download (see ``allelix.reports``).
METHOD_ARRAY_IMPUTED = "array-imputed"
_SNIFF_LINES = 20


class GenesForGoodParser(TwentyThreeAndMeParser):
    """Parser for Genes for Good 23andMe-style text files (measured or imputed)."""

    name: ClassVar[str] = "genesforgood"
    display_name: ClassVar[str] = "Genes for Good"
    file_extensions: ClassVar[list[str]] = [".txt"]
    url: ClassVar[str] = "https://genesforgood.sph.umich.edu"

    def can_parse(self, file_path: Path) -> bool:
        """Recognize the file by its first line, ``# Genes for Good v...``."""
        return _banner(file_path).startswith(BANNER_PREFIX)

    def get_metadata(self, file_path: Path) -> GenotypeMetadata:
        """The header's build line, and ``method`` for the imputed download."""
        meta = GenotypeMetadata(
            format=self.name,
            sample_id="",
            build=read_header_build(file_path),
        )
        if IMPUTED_MARKER in _banner(file_path).lower():
            meta["method"] = METHOD_ARRAY_IMPUTED
        return meta


def _banner(file_path: Path) -> str:
    """The file's first non-blank line, or "" when it cannot be read."""
    try:
        with open_genotype_text(file_path) as fh:
            return first_nonblank_line(fh, _SNIFF_LINES)
    except (OSError, UnicodeDecodeError, DamagedFileError):
        return ""
