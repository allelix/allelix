"""Ordinary CLI builds expose diagnostics without caller-installed logging handlers."""

import hashlib
import os
import shutil
import time

import pytest
from click.testing import CliRunner
from test_clinvar_build_diagnostics import _metric, _sources

from allelix.annotators import clinvar as module
from allelix.annotators.clinvar import ClinVarAnnotator, clinvar_db_filename, clinvar_record_name
from allelix.cli import _helpers, main
from allelix.databases import manager


@pytest.mark.parametrize("build", ["GRCh37", "GRCh38"])
@pytest.mark.parametrize("outcome", ["success", "floor"])
@pytest.mark.parametrize("command", ["db-update", "automatic-refresh"])
def test_cli_build_keeps_evidence_without_logging_configuration(
    tmp_path, monkeypatch, build, outcome, command
):
    import importlib

    db_module = importlib.import_module("allelix.cli.db")
    sources = tmp_path / "sources"
    sources.mkdir()
    vs, ss = _sources(sources, build, True)
    digests = {
        p.name: hashlib.md5(p.read_bytes(), usedforsecurity=False).hexdigest() for p in (vs, ss)
    }
    data = tmp_path / "data"
    data.mkdir()
    owned = []

    def download(url, destination):
        shutil.copyfile(vs if "variant_summary" in url else ss, destination)
        owned.append(destination)

    def registry(path, **kwargs):
        return [ClinVarAnnotator(path, builds=(build,))]

    monkeypatch.setattr(module, "download", download)
    monkeypatch.setattr(module, "_fetch_checksum", lambda url: digests[vs.name])
    monkeypatch.setattr(
        ClinVarAnnotator,
        "_fetch_remote_signal_for_tsv",
        staticmethod(lambda: "md5:" + digests[ss.name]),
    )
    monkeypatch.setattr(db_module, "get_annotators", registry)
    monkeypatch.setattr(_helpers, "get_annotators", registry)
    monkeypatch.setitem(manager.CLINVAR_MIN_ROWS, build, 3 if outcome == "floor" else 2)
    if command == "automatic-refresh":
        cache = data / clinvar_db_filename(build)
        manager.load_clinvar_tsv(
            vs, ss, cache, build, remote_signal="old", record_name=clinvar_record_name(build)
        )
        # The setup build is outside the command being checked.
        for old_log in data.rglob("*.log"):
            old_log.unlink()
        old = time.time() - 90 * 86400
        os.utime(cache, (old, old))
        source = tmp_path / "input.txt"
        source.write_text(
            "# This data file generated by 23andMe\n# rsid chromosome position genotype\n"
            "rs900253001\t1\t1000\tAG\n"
        )
        args = ["analyze", str(source), "--build", build.lower(), "--data-dir", str(data)]
    else:
        args = [
            "db",
            "update",
            "--only",
            "clinvar",
            "--build",
            build.lower(),
            "--data-dir",
            str(data),
        ]
    result = CliRunner().invoke(main, args)
    assert len(owned) == 2, (result.output, result.exception)
    assert all(not path.exists() for path in owned)
    assert result.exit_code == (1 if command == "db-update" and outcome == "floor" else 0), (
        result.output,
        result.exception,
    )
    # Accept captured command output or a persistent build log in its data directory.
    text = result.output + "\n".join(p.read_text() for p in data.rglob("*.log"))
    for path in (vs, ss):
        assert digests[path.name] in text, text
        assert path.name in text, text
        assert str(path.stat().st_size) in text.replace(",", ""), text
    for label, value in (
        ("variant rows accepted", 2),
        ("submission rows accepted", 3),
        ("join hits", 1),
        ("join misses", 1),
        ("records yielded", 2),
        ("rows inserted", 2),
        ("final count", 2),
    ):
        _metric(text, (label,), value)
