@pytest.mark.parametrize("evidence", ["unmatched", "matched", "uninspected"])
def test_indexed_extract_uses_the_same_warning_contract(tmp_path, monkeypatch, evidence):
    import pysam

    from allelix.cli import utility
    from allelix.databases._versions import GNOMAD_SCHEMA_VERSION
    from allelix.databases.schema import GNOMAD_SCHEMA

    data = _data(tmp_path / "data")
    source = _input(tmp_path, "vcf", "GRCh38", 4)
    lines = source.read_text().splitlines()
    header = [line for line in lines if line.startswith("#")]
    records = [line.split("\t") for line in lines if not line.startswith("#")]
    ids = [row[2] for row in records]
    if evidence == "unmatched":
        # Keep records in the indexed seed windows, but rotate the seed IDs so no vote matches.
        for row, rsid in zip(records, ids[1:] + ids[:1], strict=True):
            row[2] = rsid
            assert (row[0], int(row[1])) not in KNOWN_SNP_POSITIONS[rsid].values()
    elif evidence == "uninspected":
        for row in records:
            row[1] = str(int(row[1]) + 1)
    source.write_text("\n".join(header + ["\t".join(row) for row in records]) + "\n")
    target = next(row for row in records if row[2] == "rs1801133")
    with contextlib.closing(sqlite3.connect(data / "gnomad.sqlite")) as conn:
        conn.executescript(GNOMAD_SCHEMA)
        conn.execute(
            "INSERT INTO gnomad_frequencies (chrom,pos,ref,alt,rsid,af) VALUES (?,?,?,?,?,?)",
            (target[0], int(target[1]), "A", "G", target[2], 0.1),
        )
        conn.execute(
            "INSERT INTO database_versions VALUES "
            "('gnomad','test://synthetic','synthetic','2001-01-01',1,NULL,?)",
            (f"sv:{GNOMAD_SCHEMA_VERSION}",),
        )
        conn.commit()
    compressed = source.with_suffix(".vcf.gz")
    pysam.tabix_compress(str(source), str(compressed), force=True)
    pysam.tabix_index(str(compressed), preset="vcf", force=True)

    def no_sequential_fallback(*args, **kwargs):
        pytest.fail("The indexed fixture unexpectedly fell back to sequential extraction")

    monkeypatch.setattr(utility, "_sequential_extract", no_sequential_fallback)
    result, _ = _run(tmp_path, "extract", compressed, data, "GRCh38")
    assert result.exit_code == 0, (result.output, result.exception)
    assert "rs1801133" in result.output
    if evidence == "unmatched":
        assert _has_evidence(result.output, 4), result.output
    else:
        assert "Build warning" not in result.output
