COMMANDS = ("analyze", "methylation", "pharmacogenomics", "stats", "extract", "plink", "compare")
REPORT_COMMANDS = COMMANDS[:3]


def _data(path):
    path.mkdir()
    for build in ("GRCh37", "GRCh38"):
        with contextlib.closing(sqlite3.connect(path / clinvar_db_filename(build))) as conn:
            conn.executescript(CLINVAR_SCHEMA)
            conn.execute(
                "INSERT INTO clinvar_variants (rsid, chromosome, position, ref, alt, "
                "clinical_significance, condition, gene, review_status) VALUES "
                "('rs900252601', '1', 1000, 'A', 'G', 'Pathogenic', 'Synthetic condition', "
                "'MTHFR', 'criteria provided, single submitter')"
            )
            conn.execute(
                "INSERT INTO database_versions (name, source_url, version, downloaded_at, "
                "record_count, local_version_tag) VALUES (?, 'test://synthetic', 'synthetic', "
                "'2001-01-01', 1, ?)",
                (clinvar_record_name(build), f"iv:{CLINVAR_INTERPRETER_VERSION}"),
            )
            conn.commit()
    return path


def _input(tmp_path, kind, build, count, *, misplaced=False):
    rows = []
    for rsid, placements in list(KNOWN_SNP_POSITIONS.items())[:count]:
        chrom, pos = placements[build]
        if misplaced:
            pos += 1
            assert (chrom, pos) not in placements.values()
        rows.append((rsid, chrom, pos))
    if not count:
        rows = [("rs900252601", "1", 1000)]
    if kind == "chip":
        path = tmp_path / "input.txt"
        path.write_text(
            "# This data file generated by 23andMe\n# rsid\tchromosome\tposition\tgenotype\n"
            + "".join(f"{rsid}\t{chrom}\t{pos}\tAG\n" for rsid, chrom, pos in rows)
        )
    else:
        path = tmp_path / "input.vcf"
        lengths = ""
        if kind == "vcf-lengths":
            length = 249250621 if build == "GRCh37" else 248956422
            lengths = f"##contig=<ID=1,length={length}>\n"
        path.write_text(
            "##fileformat=VCFv4.2\n"
            + lengths
            + '##FORMAT=<ID=GT,Number=1,Type=String,Description="Genotype">\n'
            + "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tSAMPLE\n"
            + "".join(
                f"{chrom}\t{pos}\t{rsid}\tA\tG\t.\tPASS\t.\tGT\t0/1\n"
                for rsid, chrom, pos in sorted(rows, key=lambda row: (int(row[1]), row[2]))
            )
        )
    return path


def _run(tmp_path, command, source, data, override, *, report_format="json"):
    output = tmp_path / f"report.{report_format}"
    if command == "compare":
        args = ["compare", str(source), str(source)]
        if override:
            args += ["--build1", override.lower(), "--build2", override.lower()]
    else:
        args = (["export", "plink"] if command == "plink" else [command]) + [str(source)]
        args += ["--data-dir", str(data)]
        if override:
            args += ["--build", override.lower()]
        if command in REPORT_COMMANDS:
            args += ["--no-update", "--output", str(output), "--report-format", report_format]
        elif command == "extract":
            args += ["--snps", "rs1801133"]
        elif command == "plink":
            args += ["--output-prefix", str(tmp_path / "plink")]
    result = CliRunner(env={"COLUMNS": "400"}).invoke(main, args)
    return result, output


def _has_evidence(text, count):
    text = " ".join(text.lower().split())
    return (
        ("seed" in text or "known-snp" in text)
        and re.search(rf"\b0\s*(?:/|of|out of)\s*{count}\b", text) is not None
        and ("warning" in text or "warn" in text)
    )


@pytest.mark.parametrize("command", COMMANDS)
@pytest.mark.parametrize("build", ["GRCh37", "GRCh38"])
@pytest.mark.parametrize("kind", ["chip", "vcf", "vcf-lengths"])
def test_forced_no_match_warns_on_every_command(tmp_path, command, build, kind):
    data = _data(tmp_path / "data")
    source = _input(tmp_path, kind, build, 4, misplaced=True)
    result, _ = _run(tmp_path, command, source, data, build)
    assert result.exit_code == 0, result.output
    assert _has_evidence(result.output, 4), result.output


@pytest.mark.parametrize("command", REPORT_COMMANDS)
@pytest.mark.parametrize("build", ["GRCh37", "GRCh38"])
@pytest.mark.parametrize("kind,count", [("chip", 10), ("vcf", 4), ("vcf-lengths", 4)])
def test_forced_no_match_is_a_persisted_report_warning(tmp_path, command, build, kind, count):
    data = _data(tmp_path / "data")
    result, output = _run(
        tmp_path, command, _input(tmp_path, kind, build, count, misplaced=True), data, build
    )
    assert result.exit_code == 0, result.output
    report = json.loads(output.read_text())
    evidence = report["input"]["build_evidence"]
    assert evidence["seeds_matched"] == 0 and evidence["seeds_inspected"] == count
    warnings = report["report_warnings"]
    assert any(_has_evidence("warning " + w["message"], count) for w in warnings), warnings


@pytest.mark.parametrize("build", ["GRCh37", "GRCh38"])
def test_html_explains_the_forced_no_match(tmp_path, build):
    data = _data(tmp_path / "data")
    result, output = _run(
        tmp_path,
        "analyze",
        _input(tmp_path, "chip", build, 4, misplaced=True),
        data,
        build,
        report_format="html",
    )
    assert result.exit_code == 0, result.output
    visible = re.sub(r"<[^>]+>", " ", output.read_text())
    assert _has_evidence(visible, 4)


