def _source_with_gfg(path, reader, rows):
    if reader != "genesforgood":
        return _source(path, reader, rows)
    _source(path, "23andme", rows)
    path.write_text(
        path.read_text().replace(
            "# This data file generated by 23andMe at: synthetic",
            "# Genes for Good v1.2: measured genotype calls",
            1,
        )
    )
    return path


def _breakdown(output, command):
    """Read just the chromosome table, without assuming border visibility."""
    marker = "Per-Chromosome Breakdown" if command == "compare" else "Chromosome"
    # stats has a two-column Chromosome / Count table; compare has six columns.
    found = {}
    in_table = False
    for line in output.splitlines():
        if marker in line:
            in_table = True
        if not in_table or "│" not in line:
            continue
        cells = [part.strip() for part in line.strip().strip("│").split("│")]
        if len(cells) == (6 if command == "compare" else 2) and cells[1].isdigit():
            found[cells[0]] = int(cells[1])
            if command == "compare":
                assert cells[2:] == ["0"] * 4, output
    return found


@pytest.mark.parametrize("reader", [*READERS, "genesforgood"])
@pytest.mark.parametrize("build", ["grch37", "grch38"])
@pytest.mark.parametrize("command", ["stats", "compare"])
def test_summaries_preserve_unknown_names_but_merge_recognized_codes(
    tmp_path, monkeypatch, reader, build, command
):
    monkeypatch.setattr(utility, "console", Console(width=200))
    codes = [*UNKNOWN, *(code for code, _ in STANDARD)]
    rows = [(f"rs9002631{i:03d}", code, POS_X + i, "GA") for i, code in enumerate(codes)]
    source = _source_with_gfg(tmp_path / "input.txt", reader, rows)
    parsed = list(detect_parser(source).parse(source))
    assert len(parsed) == len(rows)
    data = tmp_path / "data"
    _config(data, set())
    args = (
        ["stats", str(source), "--build", build, "--data-dir", str(data)]
        if command == "stats"
        else ["compare", str(source), str(source), "--build1", build, "--build2", build]
    )
    result = CliRunner().invoke(main, args)
    assert result.exit_code == 0, (result.output, result.exception)
    actual = _breakdown(result.output, command)
    recognized = Counter(canonical for _, canonical in STANDARD)
    expected = Counter(_legacy_id_chrom(reader, code) for code in UNKNOWN)
    assert {name: actual.get(name) for name in expected} == expected, result.output
    # Preserving every raw name is not a fix: standard aliases must still merge.
    assert {name: actual.get(name) for name in recognized} == recognized, result.output
    expected.update(recognized)
    assert actual == expected, result.output


@pytest.mark.parametrize(
    "code,canonical",
    [
        ("23", "X"),
        ("chrX", "X"),
        ("x", "X"),
        ("25", "X"),
        ("XY", "X"),
        ("24", "Y"),
        ("y", "Y"),
        ("26", "MT"),
        ("M", "MT"),
        ("chr1", "1"),
    ],
)
@pytest.mark.parametrize("state", ["usable", "no-call", "wrong-position", "later-ranked"])
def test_settled_uses_canonical_placement_without_weakening_early_stop(code, canonical, state):
    variant = Variant(
        RS_X,
        code,
        POS_X + (state == "wrong-position"),
        "-" if state == "no-call" else "G",
        "-" if state == "no-call" else "A",
    )
    placements = {RS_X: {(canonical, POS_X): "G"}}
    rank = {canonical: 0}
    if state == "later-ranked":
        placements[RS_X][("2", POS_X)] = "G"
        rank = {"2": 0, canonical: 1}
    actual = _settled(RS_X, {RS_X: [variant]}, SimpleNamespace(), placements, rank)
    assert actual is (state == "usable")


def test_settled_still_requires_rank_and_keeps_mito_exclusion_and_padding():
    parser = SimpleNamespace()
    padded = Variant(
        RS_X, "X", POS_X - 1, "CG", "CA", ref="CG", input_alt="CA", ref_from_input=True
    )
    streamed = {RS_X: [padded]}
    placements = {RS_X: {("X", POS_X): "G"}}
    assert _settled(RS_X, streamed, parser, placements, {"X": 0})
    assert not _settled(RS_X, streamed, parser, placements, {})
    mt = {RS_X: [Variant(RS_X, "MT", POS_X, "G", "A")]}
    mt_places = {RS_X: {("MT", POS_X): "G"}}
    assert _settled(RS_X, mt, parser, mt_places, {"MT": 0})
    assert not _settled(RS_X, mt, parser, mt_places, {"MT": 0}, skip_mt=True)


@pytest.mark.parametrize(
    "state", ["concordant", "strand_flip_match", "discordant", "strand_ambiguous", "no_call"]
)
def test_compare_unknown_breakdown_keeps_all_outcome_categories(state):
    alleles = {
        "concordant": ("GA", "GA"),
        "strand_flip_match": ("GA", "CT"),
        "discordant": ("GG", "AA"),
        "strand_ambiguous": ("AA", "TT"),
        "no_call": ("--", "GA"),
    }
    first, second = alleles[state]
    chroms = ["0", "chr0", "GL000192.1", "chrGL000192.1"]
    a = [Variant(f"rs9002632{i}", c, POS_X + i, *first) for i, c in enumerate(chroms)]
    b = [Variant(f"rs9002632{i}", c, POS_X + i, *second) for i, c in enumerate(chroms)]
    result = compare_variants(a, b, build1="GRCh38", build2="GRCh38")
    assert result.shared == 4
    assert result.chromosome_counts == {c: Counter({state: 1}) for c in chroms}
