BUILDS = ("GRCh37", "GRCh38")
SOURCES = ("clinvar", "pharmgkb", "snpedia", "gwas", "gnomad", "alphamissense", "cadd",
           "rsid_identity")  # fmt: skip


def _clinvar(data: Path, build: str, rows) -> None:
    """Rows: rsid, chrom, pos, ref, alt, gene, classification, aggregate."""
    data.mkdir(parents=True, exist_ok=True)
    with contextlib.closing(sqlite3.connect(data / clinvar_db_filename(build))) as conn:
        conn.executescript(CLINVAR_SCHEMA)
        conn.executemany(
            "INSERT INTO clinvar_variants (rsid,chromosome,position,ref,alt,gene,"
            "clinical_significance,condition,review_status,allele_id,aggregate,"
            "submitters_same,submitters_total) VALUES (?,?,?,?,?,?,?,'Synthetic condition',"
            "'criteria provided, single submitter',?,?,1,1)",
            [
                (rsid, chrom, pos, ref, alt, gene, sig, 900262000 + i, aggregate)
                for i, (rsid, chrom, pos, ref, alt, gene, sig, aggregate) in enumerate(rows)
            ],
        )
        conn.execute(
            "INSERT INTO database_versions (name,source_url,version,downloaded_at,"
            "record_count,local_version_tag) VALUES (?, 'test://synthetic', 'synthetic', "
            "'2001-01-01', ?, ?)",
            (clinvar_record_name(build), len(rows), f"iv:{CLINVAR_INTERPRETER_VERSION}"),
        )
        conn.commit()


def _identity(data: Path, rows) -> None:
    data.mkdir(parents=True, exist_ok=True)
    write_identity_db(
        rows,
        data / RSID_IDENTITY_DB_FILENAME,
        version="synthetic",
        source_url="test://identity",
        downloaded_at="2001-01-01",
    )


def _config(data: Path) -> None:
    data.mkdir(parents=True, exist_ok=True)
    on = {"clinvar", "rsid_identity"}
    (data / "config.toml").write_text(
        "[sources]\n" + "".join(f"{s} = {'true' if s in on else 'false'}\n" for s in SOURCES)
    )


def _chip(path: Path, calls, *, build: str) -> Path:
    path.write_text(
        "# This data file generated by 23andMe at: synthetic\n"
        f"# Reference human assembly {build}\n"
        "# rsid\tchromosome\tposition\tgenotype\n"
        + "".join(f"{rsid}\t{chrom}\t{pos}\t{gt}\n" for rsid, chrom, pos, gt in calls)
    )
    return path


def _analyze(tmp_path: Path, data: Path, source: Path, build: str):
    out = tmp_path / "report.json"
    result = CliRunner(env={"COLUMNS": "500"}).invoke(
        main,
        ["analyze", str(source), "--build", build.lower(), "--data-dir", str(data),
         "--no-update", "--output", str(out)],
    )  # fmt: skip
    assert result.exit_code == 0, (result.output, result.exception)
    return json.loads(out.read_text()), result.output


# ── R2-01 (P2, new in RC2): a vendor probe's D/I call is named by a P/LP ──
# ── insertion that does not reach its position (span taken from ALT length) ──

INS, BEN = "rs3999262101", "rs3999262102"
POS_I = 2000000
PROBE = "i3999262100"


@pytest.mark.parametrize("build", BUILDS)
@pytest.mark.parametrize("offset", [60, 104])
def test_r2_01_probe_named_by_an_insertion_it_is_not_inside(tmp_path, build, offset):
    """A 100-base Pathogenic insertion at POS (between POS and POS+1; it covers no
    reference base after POS). A 23andMe ``i`` probe ``DI`` call at POS+offset+1 sits
    on another variant, which ClinVar classifies Benign. RC2's span is
    ``row_pos + max(len(REF), len(ALT))``, so the insertion "covers" ~100 bases and
    the probe is named as an unchecked call at a Pathogenic site, under the
    insertion's gene. Fails on RC2; passes on RC1 and 2.6.0 (exact-position naming
    or none).
    """
    data = tmp_path / "data"
    _config(data)
    _clinvar(
        data,
        build,
        [
            (INS, "13", POS_I, "G", "G" + "T" * 100, "GENEI", "Pathogenic", "Pathogenic"),
            (BEN, "13", POS_I + offset, "CA", "C", "GENEB", "Benign", "Benign"),
        ],
    )
    _identity(data, [(BEN, "13", POS_I + offset, "CA", "C", POS_I + offset, "CA", "C", 0)])
    source = _chip(tmp_path / "chip.txt", [(PROBE, "13", POS_I + offset + 1, "DI")], build=build)
    report, output = _analyze(tmp_path, data, source, build)
    named = [(e["rsid"], e["reason"], e["gene"]) for e in report.get("high_value_unchecked") or []]
    assert not [n for n in named if n[0] == PROBE], (named, output)


# ── R2-02 (minor, performance, new in RC2): probe naming work grows with the ──
# ── longest indel anywhere in the build's cache ─────────────────────────────


def _probe_naming_vm_steps(tmp_path: Path, longest: int) -> int:
    """SQLite VM steps for batch-annotating 50 probe D/I calls in a dense chr13 window."""
    data = tmp_path / f"data_{longest}"
    rows = [
        (f"rs39992622{i:05d}", "13", 32890000 + (i * 7) % 85000, "G", "A", "BRCA2",
         "Uncertain significance", "Uncertain significance")
        for i in range(20000)
    ]  # fmt: skip
    # The only thing that differs: one deletion on another chromosome.
    rows.append(("rs3999262999", "2", 5000000, "A" * longest, "A", "GENEL", "Pathogenic",
                 "Pathogenic"))  # fmt: skip
    _clinvar(data, "GRCh37", rows)
    probes = [
        Variant(f"i39992623{i:02d}", "13", 32890500 + i * 1500, "D", "I", build="GRCh37")
        for i in range(50)
    ]
    steps = [0]

    def tick() -> int:
        steps[0] += 1
        return 0

    with ClinVarAnnotator(data, builds=("GRCh37",)) as clinvar:
        conn = clinvar._connection("GRCh37")
        assert conn is not None
        conn.set_progress_handler(tick, 100)
        list(clinvar.batch_annotate(probes))
        conn.set_progress_handler(None, 0)
    return steps[0]


def test_r2_02_probe_naming_work_depends_on_an_unrelated_long_indel(tmp_path):
    """The same 50 probe D/I calls on chr13, against two caches that differ only in
    the length of one deletion on chr2 (10 vs 100,000 bases). RC2 looks back from
    each probe by the longest indel in the whole build, so the chr13 work grows with
    the chr2 deletion (measured end to end: 0.3 s on RC1; on RC2 2.7 s with a 10 kb
    indel and 12.4 s with a 200 kb one, for 3,300 probe calls, out/scratch/perf_*).
    Fails on RC2; passes on RC1 and 2.6.0.
    """
    short = _probe_naming_vm_steps(tmp_path, 10)
    long = _probe_naming_vm_steps(tmp_path, 100_000)
    assert long <= 2 * max(short, 1), (short, long)


# ── R2-03 (P2, pre-existing; R1-03/R1-04 fixes incomplete for their class): a ──
# ── D/I call under an rsID ClinVar does not hold, at a P/LP indel, is not named ──

BRCA2_6174 = ("rs80359550", "13", 32914437, "AT", "A")
UNKNOWN_DI = "rs3999262201"


@pytest.mark.parametrize("build", BUILDS)
@pytest.mark.parametrize("chip_pos", [32914437, 32914438], ids=["anchor", "chip-coordinate"])
def test_r2_03_di_call_under_an_unknown_rsid_at_a_plp_indel_is_not_named(tmp_path, build, chip_pos):
    """At BRCA2 6174delT, RC2 names an ``i`` probe's ``DI`` call (R1-04 fix) and an
    unknown rsID's base call (R1-03 fix, ``unknown_alleles``), but not a ``DI``
    call written under an rsID ClinVar does not hold (a merged or outdated indel
    rsID): ``_count_di_calls_at_plp`` looks D/I calls up by rsID only,
    ``_name_probe_di_calls`` skips rs IDs, and ``_annotations_for`` returns at the
    D/I check before the unknown-rsID naming. Fails on RC2, RC1 and 2.6.0.
    """
    rsid, chrom, pos, ref, alt = BRCA2_6174
    data = tmp_path / "data"
    _config(data)
    _clinvar(data, build, [(rsid, chrom, pos, ref, alt, "BRCA2", "Pathogenic", "Pathogenic")])
    _identity(data, [(rsid, chrom, pos, ref, alt, pos, ref, alt, 0)])
    source = _chip(
        tmp_path / "chip.txt",
        [(UNKNOWN_DI, chrom, chip_pos, "DI"), ("i3999262202", chrom, chip_pos, "DI")],
        build=build,
    )
    report, output = _analyze(tmp_path, data, source, build)
    named = {e["rsid"] for e in report.get("high_value_unchecked") or []}
    assert UNKNOWN_DI in named, (named, output)
