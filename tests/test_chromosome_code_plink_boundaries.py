"""PLINK allele lookups and PAR provenance follow the canonical locus together."""

import sqlite3
from contextlib import closing

import pytest
from click.testing import CliRunner
from test_annotation_parity_and_named_disclosures import _gnomad_site, _identity
from test_chromosome_code_commands import CONFIG, POS, RSID, _data

from allelix.cli import main
from allelix.parsers import detect_parser

ALIASES = [("23", "X"), ("24", "Y"), ("25", "X"), ("26", "MT"), ("XY", "X")]


def _source(path, reader, rows):
    if reader == "myhappygenes":
        text = "# MyHappyGenes\nSNP Name\tChr\tPosition\tAllele1 - Forward\tAllele2 - Forward\n"
        text += "".join(
            f"{rsid}\t{chrom}\t{pos}\t{gt[0]}\t{gt[1]}\n" for rsid, chrom, pos, gt in rows
        )
    elif reader == "23andme":
        text = (
            "# This data file generated by 23andMe at: synthetic\n"
            "# rsid\tchromosome\tposition\tgenotype\n"
        )
        text += "".join(f"{rsid}\t{chrom}\t{pos}\t{gt}\n" for rsid, chrom, pos, gt in rows)
    else:
        assert reader == "ftdna-illumina"
        text = "RSID\tCHROMOSOME\tPOSITION\tRESULT\n"
        text += "".join(f"{rsid}\t{chrom}\t{pos}\t{gt}\n" for rsid, chrom, pos, gt in rows)
    path.write_text(text)
    return path


def _export(data, path, prefix, build):
    result = CliRunner().invoke(
        main,
        [
            "export",
            "plink",
            str(path),
            "--data-dir",
            str(data),
            "--build",
            build.lower(),
            "--output-prefix",
            str(prefix),
        ],
    )
    assert result.exit_code == 0, (result.output, result.exception)
    return prefix.with_suffix(".bim").read_bytes(), prefix.with_suffix(".bed").read_bytes()


def _cache(tmp_path, chrom, build):
    data = _data(tmp_path, chrom)
    # The matching G/T pair is deliberately at another position/chromosome
    # of the same rsID. Another rsID also holds G/T at the queried locus.
    # Neither may rescue a call at this rsID's G>A locus.
    rows = [
        (RSID, chrom, POS, "G", "A", POS, "G", "A", 0),
        (RSID, chrom, POS + 7, "G", "T", POS + 7, "G", "T", 0),
        (RSID, "2", POS, "G", "T", POS, "G", "T", 0),
        ("rs9000000092", chrom, POS, "G", "T", POS, "G", "T", 0),
    ]
    _identity(data, rows)
    if build == "GRCh38":
        _gnomad_site(data, RSID, chrom, POS, "G", "A", 0.1)
        with closing(sqlite3.connect(data / "gnomad.sqlite")) as conn, conn:
            conn.executemany(
                "INSERT INTO gnomad_frequencies (chrom,pos,ref,alt,rsid,af) VALUES (?,?,?,?,?,?)",
                [(c, pos, ref, alt, rsid, 0.1) for rsid, c, pos, ref, alt, *_ in rows[1:]],
            )
        (data / "config.toml").write_text(CONFIG.replace("gnomad = false", "gnomad = true"))
    return data


@pytest.mark.parametrize(("code", "canonical"), [*ALIASES, ("chrX", "X"), ("chrM", "MT")])
@pytest.mark.parametrize("build", ["GRCh37", "GRCh38"])
@pytest.mark.parametrize("reader", ["myhappygenes", "23andme"])
@pytest.mark.parametrize(("gt", "bed_code"), [("AA", 3), ("CC", 0), ("GT", 1)])
def test_raw_chip_plink_uses_the_same_pair_and_coding(
    tmp_path, code, canonical, build, reader, gt, bed_code
):
    data = _cache(tmp_path, canonical, build)
    outputs = []
    for label, chrom in [("control", canonical), ("coded", code)]:
        source = _source(tmp_path / f"{label}.txt", reader, [(RSID, chrom, POS, gt)])
        assert len(list(detect_parser(source).parse(source))) == 1
        outputs.append(_export(data, source, tmp_path / label, build))
    control_bim, control_bed = outputs[0]
    fields = control_bim.decode().split()
    assert fields[-2:] == ["G", "A"]
    assert control_bed == b"\x6c\x1b\x01" + bytes([bed_code])
    if code in {"25", "XY"}:
        chrom, sep, rest = control_bim.partition(b"\t")
        assert chrom == b"23" and sep
        control_bim = b"25" + sep + rest
    assert outputs[1] == (control_bim, control_bed)


@pytest.mark.parametrize("build", ["GRCh37", "GRCh38"])
@pytest.mark.parametrize("code", ["25", "XY", "chr25", "chrxy"])
def test_illumina_par_survives_normalization_and_export(tmp_path, build, code):
    data = _cache(tmp_path, "X", build)
    source = _source(tmp_path / "illumina.txt", "ftdna-illumina", [(RSID, code, POS, "GA")])
    parser = detect_parser(source)
    assert parser.name == "ftdna_illumina"
    (call,) = parser.parse(source)
    assert call.chromosome == "X"
    bim, bed = _export(data, source, tmp_path / "out", build)
    assert bim.decode().split() == ["25", RSID, "0", str(POS), "G", "A"]
    assert bed == b"\x6c\x1b\x01\x02"


@pytest.mark.parametrize("build", ["GRCh37", "GRCh38"])
def test_mixed_aliases_sort_into_contiguous_written_plink_blocks(tmp_path, build):
    data = tmp_path / "data"
    data.mkdir()
    (data / "config.toml").write_text(CONFIG.replace("= true", "= false"))
    chroms = ["X", "25", "Y", "23", "XY", "24", "MT", "26", "1", "0"]
    rows = [(f"rs90000000{i + 10}", chrom, 1000 - i, "GA") for i, chrom in enumerate(chroms)]
    source = _source(tmp_path / "mixed.txt", "myhappygenes", rows)
    bim, bed = _export(data, source, tmp_path / "out", build)
    fields = [row.split() for row in bim.decode().splitlines()]
    assert [(row[0], int(row[3])) for row in fields] == [
        ("1", 992),
        ("23", 997),
        ("23", 1000),
        ("24", 995),
        ("24", 998),
        ("25", 996),
        ("25", 999),
        ("26", 993),
        ("26", 994),
        ("0", 991),
    ]
    assert len(fields) == len(rows)
    assert bed == b"\x6c\x1b\x01" + b"\x02" * len(rows)


@pytest.mark.parametrize("build", ["GRCh37", "GRCh38"])
@pytest.mark.parametrize("chrom", ["0", "GL00023.1", "chrUn_SYNTH", "CHRGL00023.1"])
def test_plink_unknown_contigs_keep_existing_raw_reader_output(tmp_path, build, chrom):
    data = tmp_path / "data"
    data.mkdir()
    (data / "config.toml").write_text(CONFIG.replace("= true", "= false"))
    source = _source(tmp_path / "unknown.txt", "myhappygenes", [(RSID, chrom, POS, "GA")])
    (call,) = detect_parser(source).parse(source)
    assert call.chromosome == chrom
    bim, bed = _export(data, source, tmp_path / "out", build)
    assert bim.decode().split()[0] == chrom
    assert bed == b"\x6c\x1b\x01\x02"
