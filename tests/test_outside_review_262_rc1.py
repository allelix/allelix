BUILDS = ("GRCh37", "GRCh38")
REPO = Path(allelix.__file__).resolve().parents[1]
CONFIG = (
    "[sources]\nclinvar = true\npharmgkb = false\nsnpedia = false\ngwas = false\n"
    "gnomad = true\nalphamissense = false\ncadd = true\nrsid_identity = true\n"
)
P = 3_000_000


@pytest.fixture(autouse=True)
def fresh_console(monkeypatch):
    # A wide console without colour, as rc1's own tests use, so lines do not wrap.
    monkeypatch.setattr(helpers, "console", Console(width=2000, color_system=None, emoji=False))


def _chip(path, calls, build):
    path.write_text(
        "# This data file generated by 23andMe at: synthetic\n"
        f"# Reference human assembly {build}\n"
        "# rsid\tchromosome\tposition\tgenotype\n"
        + "".join(f"{rsid}\t{chrom}\t{pos}\t{call}\n" for rsid, chrom, pos, call in calls)
    )
    return path


def _analyze(tmp_path, data, source, build, surface, *extra, command="analyze"):
    """Run in-process; returns (parsed report or console text, console text)."""
    out = tmp_path / f"{source.stem}-{build}-{command}.{surface}"
    args = [command, str(source), "--data-dir", str(data), "--no-update", "--build", build.lower()]
    if surface != "terminal":
        args += ["--output", str(out)]
    result = CliRunner(env={"COLUMNS": "2000"}).invoke(main, [*args, *extra])
    assert result.exit_code == 0, (result.output, result.exception)
    if surface == "json":
        return json.loads(out.read_text()), result.output
    if surface == "html":
        return out.read_text(encoding="utf-8"), result.output
    return result.output, result.output


def _flat(text):
    return " ".join(text.split())


# ---------------------------------------------------------------------------------------
# B-01 (P3, new in 2.6.2): a roll-up line says "N call(s)" but N counts distinct IDs.
# ---------------------------------------------------------------------------------------


@pytest.mark.parametrize("build", BUILDS)
def test_b01_rollup_count_lines_count_sites_as_they_say(tmp_path, build):
    """Two D/I calls at one own-P/LP rsID and two base calls at one vendor probe are
    one site each: the count lines say "1 site(s)" and add up to the header's counted
    sites, while the Note lines of the same console (input.probe_classes) count 2 calls.
    """
    data = tmp_path / "data"
    data.mkdir()
    (data / "config.toml").write_text(
        CONFIG.replace("gnomad = true", "gnomad = false").replace("cadd = true", "cadd = false")
    )
    rows = [
        ("rs3999101000", "1", P, "G", "GA", "OWNPLP", "Pathogenic", "Pathogenic", 1, 1),
        ("rs3999201003", "1", P + 300, "G", "A", "PROBEB", "Pathogenic", "Pathogenic", 1, 1),
    ]
    for b in BUILDS:
        _clinvar(data, b, rows)
    # one unrelated row keeps the identity table ready
    _identity(data, [("rs3999199999", "5", 1000, "G", "A", 1000, "G", "A", 0)])
    calls = [
        ("rs3999101000", "1", P, "DI"),
        ("rs3999101000", "1", P, "DD"),
        ("i3999101003", "1", P + 300, "AG"),
        ("i3999101003", "1", P + 300, "AA"),
        ("rs6025", "1", P + 700, "DI"),  # a high-value site, so one site is named
    ]
    source = _chip(tmp_path / "dup.txt", calls, build)
    report, console = _analyze(tmp_path, data, source, build, "json")
    classes = report["input"]["probe_classes"]
    assert classes["di_calls_at_plp_rsids"] == 2
    assert classes["i_probes_at_plp_loci"] == 2
    flat = _flat(console)
    assert "2 of them at rsIDs ClinVar classifies as Pathogenic or Likely pathogenic" in flat
    assert "call(s) at rsIDs ClinVar classifies Pathogenic" not in flat
    assert "base call(s) at vendor probes" not in flat
    di_lines = re.findall(
        r"(\d[\d,]*) site\(s\) at rsIDs ClinVar classifies Pathogenic or Likely pathogenic "
        r"with a call written as D or I",
        flat,
    )
    probe_lines = re.findall(
        r"(\d[\d,]*) site\(s\) at vendor probes without an rsID with a base call", flat
    )
    assert di_lines == ["1"], flat
    assert probe_lines == ["1"], flat
    header = re.search(r"(\d[\d,]*) named here, (\d[\d,]*) counted by reason", flat)
    assert header is not None, flat
    lines = re.findall(r"⚠ (\d[\d,]*) site\(s\) ", flat)
    assert sum(int(n.replace(",", "")) for n in lines) == int(header.group(2)), flat


# ---------------------------------------------------------------------------
# A-06 (P3, new in 2.6.2, wording): with one site the HTML roll-up banner read
# "1 clinically important sites ... 0 are named here and the rest are counted".
# ---------------------------------------------------------------------------
def test_a06_html_rollup_banner_wording_for_one_site():
    from allelix.reports.html import _hv_unchecked_banner

    banner = _hv_unchecked_banner(
        ["SYNTH (i4000001): called A/G at a vendor probe without an rsID."],
        [],
        ["1 base call(s) at vendor probes without an rsID, at a P/LP position."],
    )
    assert "1 clinically important sites" not in banner, banner[:200]


# ---------------------------------------------------------------------------
# A-07 (P3, new in 2.6.2, documentation): docs/adr/README.md lists every
# earlier amendment of ADR-0050, ADR-0051 and ADR-0070 by release ("amended in
# 2.6.1: ..."), but not their 2.6.2 amendments.
# ---------------------------------------------------------------------------
@pytest.mark.parametrize("adr", ["ADR-0050", "ADR-0051", "ADR-0070"])
def test_a07_adr_index_names_the_262_amendments(adr):
    index = (REPO / "docs" / "adr" / "README.md").read_text(encoding="utf-8")
    line = next(line for line in index.splitlines() if line.startswith(f"- [{adr}:"))
    assert "2.6.2" in line, line[:200]
