"""The report names every unchecked call at a high-value or ClinVar P/LP site.

Counts said how many calls could not be checked, not which. Each such call at
a high-value rsID, or where ClinVar classifies the variant as Pathogenic or
Likely pathogenic, is now named in ``high_value_unchecked`` (JSON), the
console and the HTML report, with why it was not checked:

- ``unplaced``: a row of an rsID and genotype list placement could not place;
- ``di_call``: a D/I call, now also at a 23andMe ``i`` probe (by locus);
- ``identity_locus_conflict``: a call at a position the identity table does
  not give for its rsID;
- ``foreign_alleles``: a chip call naming a base its own rsID does not have
  there.

The counts are unchanged. A call that is checked, or is at neither kind of
site, is not named.
"""

from __future__ import annotations

import html
import json
import re

import pytest
from click.testing import CliRunner
from test_annotation_parity_and_named_disclosures import _clinvar, _identity

from allelix.cli import main

CONFIG = (
    "[sources]\nclinvar = true\npharmgkb = false\nsnpedia = false\ngwas = false\n"
    "gnomad = false\nalphamissense = false\ncadd = false\nrsid_identity = true\n"
)
BUILDS = ("GRCh37", "GRCh38")
PLP = "rs3999980701"  # ClinVar Pathogenic, GENEP
OTHER = "rs3999980702"  # ClinVar Benign only
POS = 1000701
F5 = "rs6025"  # built-in high-value rsID, no ClinVar row here


def _data(tmp_path, clinvar_rows, identity_rows):
    data = tmp_path / "data"
    data.mkdir()
    (data / "config.toml").write_text(CONFIG)
    for build in BUILDS:
        _clinvar(data, build, clinvar_rows)
    _identity(data, identity_rows)
    return data


def _run(tmp_path, data, source, build, surface, *, show_unchecked=False):
    out = tmp_path / f"report.{surface}"
    args = ["analyze", str(source), "--data-dir", str(data), "--no-update"]
    if build is not None:
        args += ["--build", build.lower()]
    if surface != "terminal":
        args += ["--output", str(out)]
    if show_unchecked:
        args.append("--show-unchecked")
    result = CliRunner(env={"COLUMNS": "500"}).invoke(main, args)
    assert result.exit_code == 0, (result.output, result.exception)
    if surface == "json":
        return json.loads(out.read_text()), result.output
    if surface == "html":
        visible = re.sub(r"<(script|style)\b[^>]*>.*?</\1>", "", out.read_text(), flags=re.S)
        return html.unescape(re.sub(r"<[^>]+>", " ", visible)), result.output
    return result.output, result.output


def _named(report):
    return {(e["rsid"], e["reason"], e["call"]) for e in report.get("high_value_unchecked") or []}


def _chip(tmp_path, rows, build="GRCh37"):
    path = tmp_path / "chip.txt"
    path.write_text(
        "# This data file generated by 23andMe at: synthetic\n"
        f"# Reference human assembly {build}\n"
        "# rsid\tchromosome\tposition\tgenotype\n"
        + "".join(f"{rsid}\t1\t{pos}\t{call}\n" for rsid, pos, call in rows)
    )
    return path


# --- unplaced rows of an rsID and genotype list ---------------------------------------


def _list_data(tmp_path):
    # PLP is an A/T site (palindromic: a call cannot be placed); OTHER fits.
    clinvar = [
        (PLP, "1", POS, "A", "T", "GENEP", "Pathogenic", "Pathogenic", 1, 1),
        (OTHER, "1", POS + 1, "C", "T", "GENEO", "Benign", "Benign", 1, 1),
    ]
    identity = [
        (PLP, "1", POS, "A", "T", POS, "A", "T", 0),
        (OTHER, "1", POS + 1, "C", "T", POS + 1, "C", "T", 0),
        (F5, "1", POS + 2, "C", "T", POS + 2, "C", "T", 0),
    ]
    return _data(tmp_path, clinvar, identity)


def _rsid_list(tmp_path, rows):
    path = tmp_path / "list.txt"
    path.write_text("".join(f"{rsid}\t{call}\n" for rsid, call in rows))
    return path


@pytest.mark.parametrize("surface", ["json", "terminal", "html"])
def test_unplaced_row_at_a_plp_rsid_is_named(tmp_path, surface):
    data = _list_data(tmp_path)
    rows = [(PLP, "AT"), (OTHER, "CT"), ("rs3999980709", "AG")]
    report, output = _run(tmp_path, data, _rsid_list(tmp_path, rows), None, surface)
    if surface == "json":
        assert _named(report) == {(PLP, "unplaced", "A/T")}, output
        assert report["input"]["placement"]["unplaced"]["palindromic"] == 1
    else:
        assert PLP in report and "could not be placed" in report, report


def test_unplaced_row_at_a_high_value_rsid_is_named(tmp_path):
    # F5 has no ClinVar row here; it is named because it is high-value. A/C
    # fits neither reading of its C/T site.
    data = _list_data(tmp_path)
    report, output = _run(
        tmp_path,
        data,
        _rsid_list(tmp_path, [(F5, "AC"), (OTHER, "CT"), ("rs3999980709", "AG")]),
        None,
        "json",
    )
    assert _named(report) == {(F5, "unplaced", "A/C")}, output


def test_placed_rows_are_not_named(tmp_path):
    data = _list_data(tmp_path)
    report, output = _run(
        tmp_path,
        data,
        _rsid_list(tmp_path, [(OTHER, "CT"), (F5, "CT"), ("rs3999980709", "AG")]),
        None,
        "json",
    )
    assert _named(report) == set(), output


# --- identity locus conflicts ------------------------------------------------------------


@pytest.mark.parametrize("build", BUILDS)
@pytest.mark.parametrize("surface", ["json", "terminal", "html"])
def test_identity_conflict_at_a_plp_rsid_is_named(tmp_path, build, surface):
    # The chip puts PLP at POS + 50; the identity table gives POS.
    clinvar = [(PLP, "1", POS, "G", "A", "GENEP", "Pathogenic", "Pathogenic", 1, 1)]
    identity = [(PLP, "1", POS, "G", "A", POS, "G", "A", 0)]
    data = _data(tmp_path, clinvar, identity)
    source = _chip(tmp_path, [(PLP, POS + 50, "AG")], build)
    report, output = _run(tmp_path, data, source, build, surface)
    if surface == "json":
        assert _named(report) == {(PLP, "identity_locus_conflict", "A/G")}, output
        codes = {w["code"]: w["count"] for w in report["report_warnings"]}
        assert codes["identity_locus_conflict"] == 1
    else:
        assert PLP in report and "identity table" in report, report


@pytest.mark.parametrize("build", BUILDS)
def test_identity_conflict_at_neither_kind_of_site_is_not_named(tmp_path, build):
    clinvar = [(OTHER, "1", POS, "G", "A", "GENEO", "Benign", "Benign", 1, 1)]
    identity = [(OTHER, "1", POS, "G", "A", POS, "G", "A", 0)]
    data = _data(tmp_path, clinvar, identity)
    report, output = _run(
        tmp_path, data, _chip(tmp_path, [(OTHER, POS + 50, "AG")], build), build, "json"
    )
    assert _named(report) == set(), output


# --- foreign alleles --------------------------------------------------------------


@pytest.mark.parametrize("build", BUILDS)
@pytest.mark.parametrize("surface", ["json", "terminal", "html"])
def test_foreign_allele_call_at_a_plp_locus_is_named(tmp_path, build, surface):
    clinvar = [
        (OTHER, "1", POS, "G", "A", "GENEO", "Benign", "Benign", 1, 1),
        (PLP, "1", POS, "G", "C", "GENEP", "Pathogenic", "Pathogenic", 1, 1),
    ]
    identity = [
        (OTHER, "1", POS, "G", "A", POS, "G", "A", 0),
        (PLP, "1", POS, "G", "C", POS, "G", "C", 1),
    ]
    data = _data(tmp_path, clinvar, identity)
    report, output = _run(
        tmp_path,
        data,
        _chip(tmp_path, [(OTHER, POS, "CC")], build),
        build,
        surface,
        show_unchecked=surface == "terminal",
    )
    if surface == "json":
        assert _named(report) == {(OTHER, "foreign_alleles", "C/C")}, output
        assert report["input"]["probe_classes"]["foreign_allele_calls_at_plp_loci"] == 1
        (entry,) = report["high_value_unchecked"]
        assert entry["gene"] == "GENEP"
    else:
        assert OTHER in report and "not one of its own rsID" in report, report


# --- D/I calls at 23andMe i probes -------------------------------------------------------


@pytest.mark.parametrize("build", BUILDS)
@pytest.mark.parametrize("surface", ["json", "terminal", "html"])
def test_di_call_at_an_i_probe_on_a_plp_locus_is_named(tmp_path, build, surface):
    clinvar = [(PLP, "1", POS, "CTT", "C", "GENEP", "Pathogenic", "Pathogenic", 1, 1)]
    identity = [(PLP, "1", POS, "CTT", "C", POS, "CTT", "C", 0)]
    data = _data(tmp_path, clinvar, identity)
    source = _chip(tmp_path, [("i3999980703", POS, "DI"), ("i3999980704", POS + 90, "DI")], build)
    report, output = _run(
        tmp_path, data, source, build, surface, show_unchecked=surface == "terminal"
    )
    if surface == "json":
        assert _named(report) == {("i3999980703", "di_call", "D/I")}, output
        (entry,) = report["high_value_unchecked"]
        assert entry["gene"] == "GENEP"
        assert report["input"]["array_quality"]["di_calls"] == 2
    else:
        assert "i3999980703" in report and "i3999980704" not in report, report


@pytest.mark.parametrize("build", BUILDS)
def test_di_call_at_a_plp_rsid_is_still_named_once(tmp_path, build):
    clinvar = [(PLP, "1", POS, "CTT", "C", "GENEP", "Pathogenic", "Pathogenic", 1, 1)]
    identity = [(PLP, "1", POS, "CTT", "C", POS, "CTT", "C", 0)]
    data = _data(tmp_path, clinvar, identity)
    report, output = _run(
        tmp_path, data, _chip(tmp_path, [(PLP, POS, "DI")], build), build, "json"
    )
    assert _named(report) == {(PLP, "di_call", "D/I")}, output
    assert report["input"]["probe_classes"]["di_calls_at_plp_rsids"] == 1
