"""PLINK reads a VCF call as written: only a chip call is read by its complement.

ADR-0066's complement reading is for chip probes, whose strand is not known.
A VCF call is on the forward strand already, so a call that does not fit its
site's pair as written is written missing and counted, never coded as the
complemented alleles.
"""

import contextlib
import sqlite3
from collections import Counter

import pytest
from click.testing import CliRunner
from test_annotation_parity_and_named_disclosures import _identity
from test_plink_record_coding import _decode_one_sample_bed, create_cache

from allelix.cli import main
from allelix.exporters.plink import export_plink, plink_record_key
from allelix.models import Variant

# One site, pair A>G on both builds. The VCF record carries another ALT (T),
# so the call T/T does not fit the pair as written; only its complement A/A does.
RSID = "rs3999980301"
POS = 1000301


def _data(tmp_path):
    data = tmp_path / "data"
    cache = create_cache(data)
    _identity(data, [(RSID, "1", POS, "A", "G", POS, "A", "G", 0)])
    with contextlib.closing(sqlite3.connect(cache)) as conn:
        conn.execute("DELETE FROM gnomad_frequencies")
        conn.execute(
            "INSERT INTO gnomad_frequencies (chrom,pos,ref,alt,rsid,af) VALUES (?,?,?,?,?,?)",
            ("1", POS, "A", "G", RSID, 0.2),
        )
        conn.commit()
    return data


def _vcf(tmp_path, gt, alt="T"):
    path = tmp_path / "sample.vcf"
    path.write_text(
        "##fileformat=VCFv4.2\n"
        '##FORMAT=<ID=GT,Number=1,Type=String,Description="Genotype">\n'
        "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tS1\n"
        f"1\t{POS}\t{RSID}\tA\t{alt}\t.\tPASS\t.\tGT\t{gt}\n"
    )
    return path


def _chip(tmp_path, build):
    path = tmp_path / "chip.txt"
    path.write_text(
        "# This data file generated by 23andMe\n"
        f"# Reference human assembly {build}\n"
        "# rsid\tchromosome\tposition\tgenotype\n"
        f"{RSID}\t1\t{POS}\tTT\n"
    )
    return path


def _export(tmp_path, source, build):
    prefix = tmp_path / "out"
    result = CliRunner().invoke(
        main,
        [
            "export",
            "plink",
            str(source),
            "--build",
            build.lower(),
            "--data-dir",
            str(tmp_path / "data"),
            "--output-prefix",
            str(prefix),
        ],
    )
    assert result.exit_code == 0, result.output
    return prefix, result.output


@pytest.mark.parametrize("build", ("GRCh37", "GRCh38"))
@pytest.mark.parametrize("gt", ("1/1", "1|1"))
def test_vcf_call_that_fits_only_the_complement_is_written_missing(tmp_path, build, gt):
    _data(tmp_path)
    prefix, output = _export(tmp_path, _vcf(tmp_path, gt), build)
    assert _decode_one_sample_bed(prefix) == Counter({(".", "."): 1}), output
    assert "fit neither" in output, output
    assert "complement" not in output, output


@pytest.mark.parametrize("build", ("GRCh37", "GRCh38"))
def test_vcf_heterozygous_call_with_a_foreign_allele_is_written_missing(tmp_path, build):
    # 0/1 at A>T is A/T: A fits the pair, T does not, and no reading fits both.
    _data(tmp_path)
    prefix, output = _export(tmp_path, _vcf(tmp_path, "0/1"), build)
    assert _decode_one_sample_bed(prefix) == Counter({(".", "."): 1}), output


@pytest.mark.parametrize("build", ("GRCh37", "GRCh38"))
def test_vcf_call_that_fits_as_written_is_coded(tmp_path, build):
    _data(tmp_path)
    prefix, output = _export(tmp_path, _vcf(tmp_path, "1/1", alt="G"), build)
    assert _decode_one_sample_bed(prefix) == Counter({("G", "G"): 1}), output
    assert "fit neither" not in output, output


@pytest.mark.parametrize("build", ("GRCh37", "GRCh38"))
def test_chip_call_keeps_the_complement_reading(tmp_path, build):
    # Control: the same call from a chip probe is coded by its complement.
    _data(tmp_path)
    prefix, output = _export(tmp_path, _chip(tmp_path, build), build)
    assert _decode_one_sample_bed(prefix) == Counter({("A", "A"): 1}), output
    assert "complement" in output, output


@pytest.mark.parametrize("forward_strand_calls", (False, True))
def test_writer_reads_the_complement_only_for_calls_of_unknown_strand(
    tmp_path, forward_strand_calls
):
    variant = Variant(RSID, "1", POS, "T", "T", build="GRCh38")
    prefix = tmp_path / "api"
    counts = export_plink(
        iter([variant]),
        prefix,
        "GRCh38",
        record_alleles={plink_record_key(variant): ("A", "G")},
        forward_strand_calls=forward_strand_calls,
    )
    expected = (".", ".") if forward_strand_calls else ("A", "A")
    assert _decode_one_sample_bed(prefix) == Counter({expected: 1})
    assert counts.complemented == int(not forward_strand_calls)
    assert counts.allele_mismatches == int(forward_strand_calls)
