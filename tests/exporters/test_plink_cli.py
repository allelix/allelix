def test_grch38_export_is_unchanged(tmp_path: Path) -> None:
    """(f) GRCh38 keeps gnomAD's coding: palindromic falls back, a misfit is missing."""
    calls, output = _coding(
        tmp_path,
        None,
        [
            ("2", 2100, "G", "A", "rs900999021"),
            ("2", 2200, "A", "T", "rs900999022"),
            ("2", 2300, "C", "T", "rs900999023"),
        ],
        "rs900999021\t2\t2100\tGA\nrs900999022\t2\t2200\tAA\nrs900999023\t2\t2300\tGA\n",
        build="grch38",
    )
    assert calls == [
        ("rs900999021", "G/A", "GA"),
        ("rs900999022", "A/0", "AA"),
        ("rs900999023", "C/T", "missing"),
    ]
    assert "1 call(s) fit neither gnomAD allele" in output
    assert "Allele coding:" not in output


@pytest.mark.parametrize("with_gnomad", [False, True])
def test_misfit_at_a_palindromic_identity_pair_counts_as_identity(
    tmp_path: Path, with_gnomad: bool
) -> None:
    """A call that does not fit a C/G identity pair is written missing against it, not fallback."""
    calls, output = _coding(
        tmp_path,
        [("rs900999031", "2", 3100, "C", "G", 103100, "C", "G", 0)],
        [("2", 103100, "A", "G", "rs900999031")] if with_gnomad else None,
        "rs900999031\t2\t3100\tAA\n",
    )
    assert calls == [("rs900999031", "C/G", "missing")]
    assert "1 call(s) fit neither rsID identity table allele" in output
    assert "1 site(s) from the rsID identity table, 0 from gnomAD, 0 with fallback" in output


