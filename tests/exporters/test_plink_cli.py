VCF_HEADER = (
    "##fileformat=VCFv4.2\n"
    "##contig=<ID=2,length=243199373>\n"
    '##FORMAT=<ID=GT,Number=1,Type=String,Description="Genotype">\n'
    "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tS1\n"
)
ARRAY_HEADER = (
    "# This data file generated by 23andMe at: Mon Jan 01 00:00:00 2001\n"
    "# rsid\tchromosome\tposition\tgenotype\n"
)


def _vcf(path: Path, rows: list[str]) -> Path:
    path.write_text(VCF_HEADER + "".join(f"{row}\n" for row in rows))
    return path


def _export(src: Path, prefix: Path | None, data: Path, *extra: str):
    args = ["export", "plink", str(src), "--data-dir", str(data), *extra]
    if prefix is not None:
        args += ["--output-prefix", str(prefix)]
    result = CliRunner().invoke(main, args)
    assert result.exit_code == 0, result.output
    return result


def _decode(prefix: Path) -> list[tuple[str, str, str]]:
    """Each BIM row's ID with the genotype its BED code stands for (one sample)."""
    bim = [line.split("\t") for line in plink_paths(prefix)[".bim"].read_text().splitlines()]
    bed = plink_paths(prefix)[".bed"].read_bytes()
    assert bed[:3] == bytes([0x6C, 0x1B, 0x01])
    assert len(bed) == 3 + len(bim)
    calls = []
    for row, code in zip(bim, bed[3:], strict=True):
        assert len(row) == 6 and all(row), row
        a1, a2 = row[4], row[5]
        genotype = {0b00: a1 + a1, 0b10: a1 + a2, 0b11: a2 + a2, 0b01: "missing"}[code & 0b11]
        calls.append((row[1], f"{a1}/{a2}", genotype))
    return calls


def _identity(data: Path, rows: list[tuple]) -> None:
    write_identity_db(
        rows,
        data / RSID_IDENTITY_DB_FILENAME,
        version="synthetic",
        source_url="test://",
        downloaded_at="2001-01-01",
    )


def _gnomad(data: Path, rows: list[tuple[str, int, str, str, str]]) -> None:
    with contextlib.closing(sqlite3.connect(data / "gnomad.sqlite")) as conn:
        conn.executescript(GNOMAD_SCHEMA)
        conn.executemany(
            "INSERT INTO gnomad_frequencies (chrom,pos,ref,alt,rsid,af) VALUES (?,?,?,?,?,0.1)",
            rows,
        )
        conn.execute(
            "INSERT INTO database_versions "
            "(name,source_url,version,downloaded_at,record_count,local_version_tag) "
            "VALUES ('gnomad','test://','synthetic','2001-01-01',?,?)",
            (len(rows), f"sv:{GNOMAD_SCHEMA_VERSION}"),
        )
        conn.commit()


@pytest.fixture
def empty_data(tmp_path: Path) -> Path:
    data = tmp_path / "data"
