"""The freshness helpers never raise, whatever the network replies (ADR-0012).

A reply cut inside a chunked body (``http.client.IncompleteRead``) or with a
malformed status line (``BadStatusLine``) is an ``http.client.HTTPException``,
not an ``OSError``: it crashed `analyze` and `db update`. The two
``test_r04_*`` tests and their fixtures are reviewer C's (outside review of
2.6.0 RC4, finding R4-04), unchanged but for line wrapping. Every reply is
served by a 127.0.0.1 server; nothing else reaches the network.
"""

