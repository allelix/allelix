def test_cpic_data_fetch_retries_a_cut_reply_then_raises_it(local_server, monkeypatch):
    """The CPIC data download (not a probe) retries a cut reply like a transport
    error, then raises it for setup() to report, as it does for URLError."""
    base, replies = local_server
    replies.append(_CUT_CHUNKED)
    monkeypatch.setattr(cpic_loader, "CPIC_RETRY_BACKOFF_SECONDS", (0, 0, 0, 0, 0))
    attempts = []
    real = urllib.request.urlopen

    def counting(*args, **kwargs):
        attempts.append(1)
        return real(*args, **kwargs)

    monkeypatch.setattr(urllib.request, "urlopen", counting)
    with pytest.raises(http.client.HTTPException):
        cpic_loader._http_get_json(base + "/allele")
    assert len(attempts) == cpic_loader.CPIC_RETRY_ATTEMPTS
