"""Explicit named reference calls retain their identity through reconstruction."""

import html
import json
import re

import pytest
from click.testing import CliRunner
from test_annotation_parity_and_named_disclosures import _clinvar, _identity, _pharm

from allelix.cli import main

BUILDS = ("GRCh37", "GRCh38")
LENGTHS = {"GRCh37": 249250621, "GRCh38": 248956422}
OWN, TARGET = "rs900222001", "rs900222002"
POS, ELSEWHERE = 1000000, 2000000


def _data(path, *, identity="absent", rid=OWN, important=True, pharm=False):
    path.mkdir()
    sig = "Pathogenic" if important else "Benign"
    rows = [
        (rid, "1", ELSEWHERE, "C", "T", "OWNGENE", sig, sig, 1, 1),
        (TARGET, "1", POS, "G", "G", "TARGETGENE", "risk factor", "risk factor", 1, 1),
    ]
    for build in BUILDS:
        _clinvar(path, build, rows)
    if identity != "absent":
        where = ELSEWHERE if identity == "elsewhere" else POS
        _identity(path, [(rid, "1", where, "G", "A", where, "G", "A", 0)])
    if pharm:
        _pharm(path, rid, "OWNGENE", ["GG"])
    enabled = {"clinvar", *(["pharmgkb"] if pharm else [])}
    if identity in {"here", "elsewhere"}:
        enabled.add("rsid_identity")
    names = (
        "clinvar",
        "pharmgkb",
        "snpedia",
        "gwas",
        "gnomad",
        "cadd",
        "alphamissense",
        "rsid_identity",
    )
    (path / "config.toml").write_text(
        "[sources]\n" + "".join(f"{n}={str(n in enabled).lower()}\n" for n in names)
    )
    return path


def _source(path, build, gt, rid=OWN, *, companion=None):
    if gt == "chip":
        path = path.with_suffix(".txt")
        path.write_text(
            "# This data file generated by 23andMe\n"
            "# rsid\tchromosome\tposition\tgenotype\n"
            f"{rid}\t1\t{POS}\tGG\n"
        )
        return path
    rows = [(rid, gt)]
    if companion == "first":
        rows.insert(0, (TARGET, "0/0"))
    elif companion == "last":
        rows.append((TARGET, "0/0"))
    path.write_text(
        "##fileformat=VCFv4.2\n"
        f"##contig=<ID=1,length={LENGTHS[build]}>\n"
        "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tS\n"
        + "".join(f"1\t{POS}\t{r}\tG\tA\t.\tPASS\t.\tGT\t{g}\n" for r, g in rows)
    )
    return path


def _run(tmp_path, data, source, build, *, auto=False, surface="json", extra=()):
    output = tmp_path / f"report.{surface}"
    args = [
        "analyze",
        str(source),
        "--data-dir",
        str(data),
        "--no-update",
        "--build",
        "auto" if auto else build.lower(),
        "--min-magnitude",
        "0",
    ]
    if surface != "terminal":
        args += ["--output", str(output)]
    run = CliRunner(env={"COLUMNS": "500"}).invoke(main, [*args, *extra])
    assert run.exit_code == 0, (run.output, run.exception)
    if surface == "json":
        return json.loads(output.read_text())
    if surface == "terminal":
        return run.output
    raw = re.sub(r"<(script|style)\b[^>]*>.*?</\1>", "", output.read_text(), flags=re.S | re.I)
    return html.unescape(re.sub(r"<[^>]+>", " ", raw))


def _counts(report):
    return {w["code"]: w["count"] for w in report["report_warnings"] if w.get("count")}


@pytest.mark.parametrize("build", BUILDS)
@pytest.mark.parametrize(
    "gt,auto",
    [("0/0", False), ("0/0", True), ("0", False), ("0", True), ("0/1", False), ("chip", False)],
)
@pytest.mark.parametrize("identity", ["absent", "disabled", "here", "elsewhere"])
def test_explicit_identity_controls_match_count_and_named_disclosure(
    tmp_path, build, gt, auto, identity
):
    data = _data(tmp_path / "data", identity=identity)
    report = _run(tmp_path, data, _source(tmp_path / "in.vcf", build, gt), build, auto=auto)
    assert report["input"]["build"] == build
    assert not report["annotations"], (
        "A named call placed elsewhere must not become the target rsID"
    )
    expected = (
        "identity_locus_conflict" if identity == "elsewhere" else "clinvar_rsid_placed_elsewhere"
    )
    assert _counts(report) == {expected: 1}, (
        "The call is counted once at the guard that rejects it"
    )
    named = report["high_value_unchecked"]
    assert [(n["rsid"], n["reason"]) for n in named] == [
        (OWN, "identity_locus_conflict" if identity == "elsewhere" else "placed_elsewhere")
    ]


@pytest.mark.parametrize("build", BUILDS)
@pytest.mark.parametrize("gt", ["0/0", "0"])
@pytest.mark.parametrize("kind", ["own_plp", "high_value", "ordinary"])
def test_reference_count_and_naming_are_independently_observable(tmp_path, build, gt, kind):
    rid = "rs6025" if kind == "high_value" else OWN
    data = _data(tmp_path / "data", rid=rid, important=kind == "own_plp")
    report = _run(tmp_path, data, _source(tmp_path / "in.vcf", build, gt, rid), build)
    assert _counts(report) == {"clinvar_rsid_placed_elsewhere": 1}
    assert [(n["rsid"], n["reason"]) for n in report.get("high_value_unchecked", [])] == (
        [] if kind == "ordinary" else [(rid, "placed_elsewhere")]
    )


@pytest.mark.parametrize("build", BUILDS)
@pytest.mark.parametrize("surface", ["html", "terminal"])
@pytest.mark.parametrize("gt", ["0/0", "0"])
def test_reference_rejection_has_a_visible_named_line(tmp_path, build, surface, gt):
    data = _data(tmp_path / "data", rid="rs6025")
    text = _run(
        tmp_path, data, _source(tmp_path / "in.vcf", build, gt, "rs6025"), build, surface=surface
    )
    assert "rs6025" in text and "ClinVar" in text and "elsewhere" in text.lower()


@pytest.mark.parametrize("build", BUILDS)
@pytest.mark.parametrize("rid", [TARGET, ".", "rs900222099"])
@pytest.mark.parametrize("gt", ["0/0", "0"])
def test_reference_call_without_a_conflicting_placement_still_matches(tmp_path, build, rid, gt):
    data = _data(tmp_path / "data")
    report = _run(tmp_path, data, _source(tmp_path / "in.vcf", build, gt, rid), build)
    assert [(a["source"], a["rsid"]) for a in report["annotations"]] == [("clinvar", TARGET)]
    assert not _counts(report)


@pytest.mark.parametrize("build", BUILDS)
def test_noncarried_reference_row_is_not_a_placed_elsewhere_match(tmp_path, build):
    data = _data(tmp_path / "data")
    report = _run(tmp_path, data, _source(tmp_path / "in.vcf", build, "1/1"), build)
    assert not report["annotations"] and not _counts(report)


@pytest.mark.parametrize("build", BUILDS)
@pytest.mark.parametrize("order", ["first", "last"])
def test_two_reference_records_do_not_share_the_wrong_record_identity(tmp_path, build, order):
    data = _data(tmp_path / "data")
    report = _run(
        tmp_path, data, _source(tmp_path / "in.vcf", build, "0/0", companion=order), build
    )
    assert [(a["source"], a["rsid"]) for a in report["annotations"]] == [("clinvar", TARGET)]
    assert _counts(report) == {"clinvar_rsid_placed_elsewhere": 1}
    assert [n["rsid"] for n in report["high_value_unchecked"]] == [OWN]


@pytest.mark.parametrize("build", BUILDS)
def test_clinvar_reference_rejection_does_not_rename_other_source_calls(tmp_path, build):
    data = _data(tmp_path / "data", pharm=True)
    report = _run(tmp_path, data, _source(tmp_path / "in.vcf", build, "0/0"), build)
    assert [(a["source"], a["rsid"]) for a in report["annotations"]] == [("pharmgkb", OWN)]
    assert _counts(report) == {"clinvar_rsid_placed_elsewhere": 1}


@pytest.mark.parametrize("build", BUILDS)
@pytest.mark.parametrize("order", ["first", "last"])
def test_reference_finding_is_stamped_only_on_the_nonconflicting_record(tmp_path, build, order):
    data = _data(tmp_path / "data")
    source = _source(tmp_path / "in.vcf", build, "0/0", companion=order)
    output = tmp_path / "annotated.vcf"
    _run(tmp_path, data, source, build, extra=("--vcf-out", str(output)))
    rows = [
        line.split("\t") for line in output.read_text().splitlines() if not line.startswith("#")
    ]
    assert len(rows) == 2
    info = {row[2]: row[7] for row in rows}
    assert "ALLELIX_CLINVAR_REF=" not in info[OWN], "The rejected record owns no ClinVar finding"
    assert info[TARGET].count("ALLELIX_CLINVAR_REF=") == 1, (
        "The legitimate reference record keeps its one reference-carried finding"
    )


@pytest.mark.parametrize("build", BUILDS)
@pytest.mark.parametrize("rid", [OWN, "."])
def test_reference_block_id_does_not_name_every_interior_site(tmp_path, build, rid):
    data = _data(tmp_path / "data")
    source = tmp_path / "block.vcf"
    source.write_text(
        "##fileformat=VCFv4.2\n"
        '##ALT=<ID=NON_REF,Description="Any non-reference allele">\n'
        f"##contig=<ID=1,length={LENGTHS[build]}>\n"
        "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tS\n"
        f"1\t{POS - 10}\t{rid}\tG\t<NON_REF>\t.\tPASS\tEND={POS + 10}\tGT\t0/0\n"
    )
    report = _run(tmp_path, data, source, build)
    assert [(a["source"], a["rsid"]) for a in report["annotations"]] == [("clinvar", TARGET)]
    assert not _counts(report)
