"""Panel coverage in four states through ``analyze --filter-file`` (ADR-0051).

Every requested rsID is annotated, typed with no annotation, a no-call,
or not on the chip ("not in file" for VCF input), and the counts sum to
the number requested. All genotypes and ClinVar rows are synthetic.
"""

from __future__ import annotations

import contextlib
import json
import sqlite3
from typing import TYPE_CHECKING

import pytest
from click.testing import CliRunner

from allelix.annotators.clinvar import clinvar_db_filename, clinvar_record_name
from allelix.cli import main
from allelix.databases._versions import CLINVAR_INTERPRETER_VERSION
from allelix.databases.schema import CLINVAR_SCHEMA

if TYPE_CHECKING:
    from pathlib import Path

_SINGLE = "criteria_provided,_single_submitter"

# (rsid, chrom, pos, ref, alt); rsIDs in the unused 900952xxx range.
_ROWS = [
    ("rs900952001", "2", 1000, "G", "A"),
    ("rs900952002", "2", 2000, "G", "A"),
    ("rs900952003", "2", 3000, "G", "A"),
    ("rs900952004", "2", 4000, "G", "A"),
]

_PANEL = ["rs900952001", "rs900952002", "rs900952003", "rs900952004", "rs900952099"]


def _clinvar(data: Path) -> None:
    for build in ("GRCh37", "GRCh38"):
        with contextlib.closing(sqlite3.connect(data / clinvar_db_filename(build))) as conn:
            conn.executescript(CLINVAR_SCHEMA)
            conn.executemany(
                "INSERT INTO clinvar_variants (rsid, chromosome, position, ref, alt, "
                "clinical_significance, condition, gene, review_status, allele_id, aggregate, "
                "submitters_same, submitters_total) "
                "VALUES (?, ?, ?, ?, ?, 'Pathogenic', 'Test condition', 'GENE1', ?, ?, "
                "'Pathogenic', 1, 1)",
                [
                    (rsid, chrom, pos, ref, alt, _SINGLE, i)
                    for i, (rsid, chrom, pos, ref, alt) in enumerate(_ROWS, 1)
                ],
            )
            conn.execute(
                "INSERT INTO database_versions VALUES (?, 'test://', '1', '2026-10-10', ?, "
                "NULL, ?)",
                (clinvar_record_name(build), len(_ROWS), f"iv:{CLINVAR_INTERPRETER_VERSION}"),
            )
            conn.commit()


@pytest.fixture
def data(tmp_path: Path) -> Path:
    d = tmp_path / "data"
    d.mkdir()
    _clinvar(d)
    return d


@pytest.fixture
def panel(tmp_path: Path) -> Path:
    path = tmp_path / "panel.txt"
    path.write_text("\n".join(_PANEL) + "\n")
    return path


def _analyze(data: Path, panel: Path, input_path: Path, out: Path | None, *extra: str) -> str:
    """Run analyze; with no ``out`` the report goes to the terminal."""
    result = CliRunner(env={"COLUMNS": "300"}).invoke(
        main,
        [
            "analyze",
            str(input_path),
            "--build",
            "grch37",
            "--no-update",
            "--data-dir",
            str(data),
            "--filter-file",
            str(panel),
            *(["--output", str(out)] if out is not None else []),
            *extra,
        ],
    )
    assert result.exit_code == 0, result.output
    return result.output


def _array(tmp_path: Path) -> Path:
    path = tmp_path / "a.txt"
    calls = [
        ("rs900952001", "2", 1000, "AG"),  # carries the ALT: annotated
        ("rs900952002", "2", 2000, "GG"),  # reference: typed, no annotation
        ("rs900952003", "2", 3000, "--"),  # no-call
        ("rs900952004", "2", 4000, "A-"),  # one allele missing: a no-call too
    ]
    # A 23andMe banner, so --format 23andme is a choice, not a forced mismatch.
    lines = [
        "# This data file generated by 23andMe at: Mon Jan 01 00:00:00 2001",
        "# rsid\tchromosome\tposition\tgenotype",
    ]
    lines += [f"{rsid}\t{chrom}\t{pos}\t{gt}" for rsid, chrom, pos, gt in calls]
    path.write_text("\n".join(lines) + "\n")
    return path


def test_array_json_has_all_four_states(tmp_path: Path, data: Path, panel: Path) -> None:
    out = tmp_path / "r.json"
    _analyze(data, panel, _array(tmp_path), out, "--format", "23andme")
    cov = json.loads(out.read_text())["panel_coverage"]
    assert cov["requested"] == 5
    assert cov["counts"] == {
        "annotated": 1,
        "typed_no_annotation": 1,
        "no_call": 2,
        "not_on_chip": 1,
    }
    assert cov["variants"] == [
        {
            "rsid": "rs900952001",
            "gene": "GENE1",
            "state": "annotated",
            "genotype": "A/G",
            "annotation_count": 1,
            "reason": None,
        },
        {
            "rsid": "rs900952002",
            "gene": None,
            "state": "typed_no_annotation",
            "genotype": "G/G",
            "annotation_count": 0,
            "reason": None,
        },
        {
            "rsid": "rs900952003",
            "gene": None,
            "state": "no_call",
            "genotype": "-/-",
            "annotation_count": 0,
            "reason": None,
        },
        {
            "rsid": "rs900952004",
            "gene": None,
            "state": "no_call",
            "genotype": "A/-",
            "annotation_count": 0,
            "reason": None,
        },
        {
            "rsid": "rs900952099",
            "gene": None,
            "state": "not_on_chip",
            "genotype": None,
            "annotation_count": 0,
            "reason": None,
        },
    ]


def test_a_finding_below_the_floor_is_typed_no_annotation(
    tmp_path: Path, data: Path, panel: Path
) -> None:
    out = tmp_path / "r.json"
    _analyze(data, panel, _array(tmp_path), out, "--format", "23andme", "--min-magnitude", "10")
    states = {
        v["rsid"]: v["state"] for v in json.loads(out.read_text())["panel_coverage"]["variants"]
    }
    assert states["rs900952001"] == "typed_no_annotation"


def test_array_console(tmp_path: Path, data: Path, panel: Path) -> None:
    output = _analyze(data, panel, _array(tmp_path), None, "--format", "23andme")
    assert (
        "Panel coverage: 1 annotated / 1 typed (no annotation) / 2 no call / 1 not on chip"
        in output
    )
    assert "⚠ 2 no call: rs900952003, rs900952004" in output
    assert "⚠ 1 not on chip: rs900952099" in output


def test_vcf_half_call_with_a_finding_is_annotated(
    tmp_path: Path, data: Path, panel: Path
) -> None:
    vcf = tmp_path / "s.vcf"
    vcf.write_text(
        "##fileformat=VCFv4.2\n"
        '##FORMAT=<ID=GT,Number=1,Type=String,Description="Genotype">\n'
        "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tS1\n"
        "2\t1000\trs900952001\tG\tA\t50\tPASS\t.\tGT\t./1\n"
        "2\t2000\trs900952002\tG\tA\t50\tPASS\t.\tGT\t./.\n"
    )
    out = tmp_path / "r.json"
    _analyze(data, panel, vcf, out)
    output = _analyze(data, panel, vcf, None)
    cov = json.loads(out.read_text())["panel_coverage"]
    by_rsid = {v["rsid"]: v for v in cov["variants"]}
    # Annotated wins over the no-call, and the genotype is shown as the
    # annotations show a half call.
    assert (by_rsid["rs900952001"]["state"], by_rsid["rs900952001"]["genotype"]) == (
        "annotated",
        "A/.",
    )
    assert by_rsid["rs900952002"]["state"] == "no_call"
    assert cov["counts"]["not_on_chip"] == 3
    # VCF input has no chip.
    assert "3 not in file" in output
    assert "not on chip" not in output


def test_vcf_cli_explicit_reference_and_rejected_rows(
    tmp_path: Path,
    data: Path,
    panel: Path,
) -> None:
    vcf = tmp_path / "coverage.vcf"
    header = (
        "##fileformat=VCFv4.2\n##contig=<ID=2,length=243199373>\n"
        "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tS\n"
    )
    rows = [("0/0", 99, "PASS"), ("0/1", 3, "PASS"), ("0/1", 99, "q10"), ("./.", 99, "PASS")]
    vcf.write_text(
        header
        + "".join(
            f"2\t{i * 1000}\t{_PANEL[i - 1]}\tG\tA\t50\t{filt}\t.\tGT:GQ\t{gt}:{gq}\n"
            for i, (gt, gq, filt) in enumerate(rows, 1)
        )
    )
    out = tmp_path / "coverage.json"
    _analyze(data, panel, vcf, out)
    coverage = json.loads(out.read_text())["panel_coverage"]
    assert coverage["counts"] == {
        "annotated": 0,
        "typed_no_annotation": 1,
        "no_call": 3,
        "not_on_chip": 1,
    }
    assert coverage["variants"][0]["genotype"] == "G/G"
    output = _analyze(data, panel, vcf, None)
    assert "0 annotated / 1 typed (no annotation) / 3 no call / 1 not in file" in output
    assert "Caller FILTER rejected" in output
