"""Outside review of allelix 2.6.1 RC3 (review B, analysis): new reproductions.

Synthetic, offline data only. Each test fails on RC3 for the reason in its
docstring; results on RC2, RC1 and 2.6.0 are stated there.

Run:
    venv-rc3/bin/python -m pytest -c /dev/null -p no:cacheprovider out/test_review_rc3.py
"""

from __future__ import annotations

import contextlib
import json
import sqlite3
from pathlib import Path

from click.testing import CliRunner

from allelix.annotators.clinvar import clinvar_db_filename, clinvar_record_name
from allelix.cli import main
from allelix.databases._versions import CLINVAR_INTERPRETER_VERSION
from allelix.databases.rsid_identity_loader import RSID_IDENTITY_DB_FILENAME, write_identity_db
from allelix.databases.schema import CLINVAR_SCHEMA

SOURCES = ("clinvar", "pharmgkb", "snpedia", "gwas", "gnomad", "alphamissense", "cadd",
           "rsid_identity")  # fmt: skip


def _data(tmp_path: Path, rows) -> Path:
    data = tmp_path / "data"
    data.mkdir()
    on = {"clinvar", "rsid_identity"}
    (data / "config.toml").write_text(
        "[sources]\n" + "".join(f"{s} = {'true' if s in on else 'false'}\n" for s in SOURCES)
    )
    with contextlib.closing(sqlite3.connect(data / clinvar_db_filename("GRCh37"))) as conn:
        conn.executescript(CLINVAR_SCHEMA)
        conn.executemany(
            "INSERT INTO clinvar_variants (rsid,chromosome,position,ref,alt,gene,"
            "clinical_significance,condition,review_status,allele_id,aggregate,"
            "submitters_same,submitters_total) VALUES (?,?,?,?,?,?,?,'Synthetic condition',"
            "'criteria provided, single submitter',?,?,1,1)",
            [
                (rsid, chrom, pos, ref, alt, gene, sig, 900263000 + i, sig)
                for i, (rsid, chrom, pos, ref, alt, gene, sig) in enumerate(rows)
            ],
        )
        conn.execute(
            "INSERT INTO database_versions (name,source_url,version,downloaded_at,"
            "record_count,local_version_tag) VALUES (?, 'test://synthetic', 'synthetic', "
            "'2001-01-01', ?, ?)",
            (clinvar_record_name("GRCh37"), len(rows), f"iv:{CLINVAR_INTERPRETER_VERSION}"),
        )
        conn.commit()
    write_identity_db(
        [("rs3999263999", "1", 5, "A", "G", 5, "A", "G", 0)],
        data / RSID_IDENTITY_DB_FILENAME,
        version="synthetic",
        source_url="test://identity",
        downloaded_at="2001-01-01",
    )
    return data


# ── R3-01 (minor, new in RC3): a D/I call under an rsID ClinVar holds as Benign ──
# ── is named under another variant's gene, with no word of why ──────────────

P0 = 3000000
PLP_DEL, BENIGN_DEL = "rs3999264100", "rs3999264101"


def test_r3_01_benign_rsid_di_call_named_under_the_covering_variants_gene(tmp_path):
    """ClinVar holds rs…101 as a Benign 1-base deletion in GENEB (AT>A at P0+1). A
    Pathogenic deletion of another rsID in GENEP (GAT>G at P0) covers that position.
    RC3 names the ``II`` call at rs…101 by position, as designed, but the entry
    reads "GENEP (rs…101): called I/I, a deletion or insertion code that Allelix
    cannot check against its sources", and JSON gives ``gene: GENEP``. The line
    gives the rsID another variant's gene and does not say it is named because a
    Pathogenic indel covers its position; it reads like the text for a D/I call at
    a Pathogenic rsID. Fails on RC3; earlier versions do not name the call (pass).
    """
    data = _data(
        tmp_path,
        [
            (PLP_DEL, "13", P0, "GAT", "G", "GENEP", "Pathogenic"),
            (BENIGN_DEL, "13", P0 + 1, "AT", "A", "GENEB", "Benign"),
        ],
    )
    chip = tmp_path / "chip.txt"
    chip.write_text(
        "# This data file generated by 23andMe at: synthetic\n"
        "# Reference human assembly GRCh37\n# rsid\tchromosome\tposition\tgenotype\n"
        f"{BENIGN_DEL}\t13\t{P0 + 1}\tII\n"
    )
    out = tmp_path / "report.json"
    result = CliRunner(env={"COLUMNS": "500"}).invoke(
        main,
        ["analyze", str(chip), "--build", "grch37", "--data-dir", str(data), "--no-update",
         "--output", str(out)],
    )  # fmt: skip
    assert result.exit_code == 0, result.output
    entries = [
        e for e in json.loads(out.read_text()).get("high_value_unchecked") or []
        if e["rsid"] == BENIGN_DEL
    ]  # fmt: skip
    for entry in entries:
        assert entry["gene"] == "GENEB" or "Pathogenic" in entry["message"], entry
