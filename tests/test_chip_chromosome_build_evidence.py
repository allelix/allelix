RAW = ("23andme", "ancestrydna", "ftdna", "myheritage", "livingdna", "myhappygenes")
MAPPED = ("decodeme", "ftdna_illumina", "ftdna_famfinder")
BUILDS = ("GRCh37", "GRCh38")
SEEDS = ("rs1801133", "rs1801131", "rs1799853")
HIT = "rs900556001"


def chip(path, reader, rows):
    headers = {
        "23andme": "# This data file generated by 23andMe\n",
        "ancestrydna": "#AncestryDNA raw data download\n"
        "rsid\tchromosome\tposition\tallele1\tallele2\n",
        "ftdna": "RSID,CHROMOSOME,POSITION,RESULT\n",
        "myheritage": "# MyHeritage DNA\nRSID,CHROMOSOME,POSITION,RESULT\n",
        "livingdna": "# Living DNA\n",
        "myhappygenes": "# MyHappyGenes\n"
        "SNP Name\tChr\tPosition\tAllele1 - Forward\tAllele2 - Forward\n",
        "decodeme": "Name,Variation,Chromosome,Position,Strand,YourCode\n",
        "ftdna_illumina": "RSID\tCHROMOSOME\tPOSITION\tRESULT\n",
        "ftdna_famfinder": "# Family Tree DNA - FamFinder\n"
        "RSID\tCHROMOSOME\tPOSITION\tALLELE1\tALLELE2\n",
    }
    text = headers[reader]
    for rsid, chrom, pos, gt in rows:
        if reader in ("ancestrydna", "myhappygenes", "ftdna_famfinder"):
            line = f"{rsid}\t{chrom}\t{pos}\t{gt[0]}\t{gt[1]}"
        elif reader in ("ftdna", "myheritage"):
            line = f"{rsid},{chrom},{pos},{gt}"
        elif reader == "decodeme":
            line = f"{rsid},A/G,{chrom},{pos},+,{gt}"
        else:
            line = f"{rsid}\t{chrom}\t{pos}\t{gt}"
        text += line + "\n"
    path.write_text(text)
    assert detect_parser(path).name == reader, "Synthetic envelope must select its real reader"
    return path


@pytest.mark.parametrize("reader", RAW + MAPPED)
@pytest.mark.parametrize("build", BUILDS)
@pytest.mark.parametrize("prefix", ("", "chr", "CHR", "Chr"))
def test_each_reader_votes_from_real_seed_positions_with_any_chr_prefix(
    tmp_path, reader, build, prefix
):
    rows = [
        (
            rid,
            prefix + bd.KNOWN_SNP_POSITIONS[rid][build][0],
            bd.KNOWN_SNP_POSITIONS[rid][build][1],
            "AA",
        )
        for rid in SEEDS
    ]
    source = chip(tmp_path / "input.txt", reader, rows)
    calls = list(detect_parser(source).parse(source))
    assert len(calls) == 3
    result = bd.detect_build(calls)
    assert (result.build, result.matched, result.inspected, result.is_confident) == (
        build,
        3,
        3,
        True,
    )


