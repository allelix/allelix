"""export plink without -o never replaces an existing file at a default destination.

The default prefix is the input's stem, so ``genome.vcf`` writes ``genome.bed``:
a user's unrelated ``genome.bed`` (an intervals file, say) must not be
replaced. An existing ``.bed``, ``.bim`` or ``.fam`` at a default destination,
or a link there, is refused before any work, named, and left as it was. An
explicit ``--output-prefix`` keeps its documented replace policy.
"""

import os

import pytest
from click.testing import CliRunner

from allelix.cli import main

OLD = b"chr1\t100\t200\tintervals\n"


def _vcf(tmp_path, name="genome.vcf"):
    path = tmp_path / name
    path.write_text(
        "##fileformat=VCFv4.2\n"
        '##FORMAT=<ID=GT,Number=1,Type=String,Description="Genotype">\n'
        "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tS1\n"
        "1\t1000501\trs3999980501\tA\tG\t.\tPASS\t.\tGT\t0/1\n"
    )
    return path


def _chip(tmp_path, name="genome.txt"):
    path = tmp_path / name
    path.write_text(
        "# This data file generated by 23andMe\n"
        "# Reference human assembly GRCh38\n"
        "# rsid\tchromosome\tposition\tgenotype\n"
        "rs3999980501\t1\t1000501\tAG\n"
    )
    return path


def _run(tmp_path, source, *extra):
    return CliRunner().invoke(
        main,
        [
            "export",
            "plink",
            str(source),
            "--build",
            "grch38",
            "--data-dir",
            str(tmp_path / "data"),
            *extra,
        ],
    )


@pytest.mark.parametrize("ending", [".bed", ".bim", ".fam"])
@pytest.mark.parametrize("make_input", [_vcf, _chip], ids=["vcf", "chip"])
def test_existing_default_destination_is_refused_and_kept(tmp_path, ending, make_input):
    source = make_input(tmp_path)
    existing = tmp_path / f"genome{ending}"
    existing.write_bytes(OLD)
    result = _run(tmp_path, source)
    assert result.exit_code != 0, result.output
    assert existing.name in result.output, result.output
    assert "--output-prefix" in result.output, result.output
    assert existing.read_bytes() == OLD
    others = {f"genome{e}" for e in (".bed", ".bim", ".fam")} - {existing.name}
    assert not any((tmp_path / name).exists() for name in others)


@pytest.mark.parametrize("dangling", [False, True])
def test_link_at_a_default_destination_is_refused(tmp_path, dangling):
    source = _vcf(tmp_path)
    target = tmp_path / "elsewhere.bed"
    if not dangling:
        target.write_bytes(OLD)
    link = tmp_path / "genome.bed"
    os.symlink(target, link)
    result = _run(tmp_path, source)
    assert result.exit_code != 0, result.output
    assert "genome.bed" in result.output, result.output
    assert link.is_symlink()
    assert target.exists() == (not dangling)
    if not dangling:
        assert target.read_bytes() == OLD


def test_gzipped_input_default_destination_is_refused(tmp_path):
    import gzip

    plain = _vcf(tmp_path, "sample.vcf")
    source = tmp_path / "genome.vcf.gz"
    source.write_bytes(gzip.compress(plain.read_bytes(), mtime=0))
    plain.unlink()
    existing = tmp_path / "genome.bed"
    existing.write_bytes(OLD)
    result = _run(tmp_path, source)
    assert result.exit_code != 0, result.output
    assert existing.read_bytes() == OLD


def test_default_destination_without_existing_files_is_written(tmp_path):
    result = _run(tmp_path, _vcf(tmp_path))
    assert result.exit_code == 0, result.output
    assert (tmp_path / "genome.bed").read_bytes()[:3] == b"\x6c\x1b\x01"


def test_explicit_prefix_still_replaces_its_files(tmp_path):
    source = _vcf(tmp_path)
    existing = tmp_path / "genome.bed"
    existing.write_bytes(OLD)
    result = _run(tmp_path, source, "--output-prefix", str(tmp_path / "genome"))
    assert result.exit_code == 0, result.output
    assert existing.read_bytes()[:3] == b"\x6c\x1b\x01"
