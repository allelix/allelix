"""Zero is an unplaced array rsID call; VCF coordinates remain strictly positive."""

import pytest
from rc3_verification_helpers import POS, RS, analyze, caches, diploid_sources, findings
from test_chip_chromosome_build_evidence import MAPPED, RAW, SEEDS, chip
from test_position_integer_bounds import _source

from allelix.parsers import detect_parser
from allelix.utils.build_detect import KNOWN_SNP_POSITIONS

ARRAYS = (*RAW, *MAPPED, "genesforgood")


def _array(path, reader, rows):
    chip(path, "23andme" if reader == "genesforgood" else reader, rows)
    if reader == "genesforgood":
        path.write_text(
            path.read_text().replace(
                "# This data file generated by 23andMe", "# Genes for Good v1.2: genotype calls"
            )
        )
    assert detect_parser(path).name == reader
    return path


@pytest.mark.parametrize("reader", ARRAYS)
@pytest.mark.parametrize("chrom", ["1", "0"])
def test_each_array_reader_keeps_an_unplaced_rsid_zero_without_diagnostic(
    tmp_path, caplog, reader, chrom
):
    source = _array(tmp_path / "input.txt", reader, [(RS, chrom, 0, "AG")])
    calls = list(detect_parser(source).parse(source))
    assert len(calls) == 1, "Position zero must retain the rsID call as in 2.7.0"
    call = calls[0]
    assert (call.rsid, call.position) == (RS, 0)
    assert sorted((call.allele1, call.allele2)) == ["A", "G"]
    assert not any("skipping" in r.message.lower() for r in caplog.records)


@pytest.mark.parametrize("reader", ARRAYS)
@pytest.mark.parametrize("position", [-5, 2**63])
def test_array_negative_and_overflow_positions_are_still_malformed(tmp_path, reader, position):
    source = _array(tmp_path / "input.txt", reader, [(RS, "1", position, "AG")])
    assert list(detect_parser(source).parse(source)) == []


@pytest.mark.parametrize("reader", ARRAYS)
@pytest.mark.parametrize("build", ["GRCh37", "GRCh38"])
@pytest.mark.parametrize("auto", [False, True])
def test_unplaced_array_call_reaches_rsid_sources_without_a_position_match(
    tmp_path, reader, build, auto
):
    pairs = [(RS, "A")]
    data = caches(tmp_path / "data", pairs, pairs, pairs, pairs)
    diploid_sources(data, RS)
    rows = [(r, *KNOWN_SNP_POSITIONS[r][build], "AA") for r in SEEDS]
    rows.append((RS, "1", 0, "AG"))
    source = _array(tmp_path / "input.txt", reader, rows)
    report, _ = analyze(data, source, tmp_path / "report.json", "auto" if auto else build)
    assert report["input"]["build"] == build
    assert report["input"]["total_variants"] == len(rows)
    assert report["input"]["skipped_lines"] == 0
    for src in ("gwas", "pharmgkb", "snpedia"):
        assert any(a["rsid"] == RS for a in findings(report, src)), src
    assert not findings(report, "clinvar"), "Zero must not borrow the distant ClinVar position"
    assert not report.get("high_value_unchecked", [])


@pytest.mark.parametrize("build", ["GRCh37", "GRCh38"])
@pytest.mark.parametrize("gt", ["0/0", "0", "./.", "0/1"])
def test_vcf_zero_is_still_skipped_and_counted_not_an_unplaced_call(tmp_path, build, gt):
    source = _source(
        tmp_path / "input.vcf", "vcf", [(RS, 0), ("rs880271999", POS[build])], build, gt
    )
    parser = detect_parser(source)
    calls = list(parser.parse(source))
    assert all(v.rsid != RS for v in calls)
    assert parser.quality_stats.malformed_rows == 1
