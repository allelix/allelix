from __future__ import annotations

import contextlib
import json
import sqlite3
from pathlib import Path

import pytest
from click.testing import CliRunner

from allelix.annotators.clinvar import clinvar_db_filename, clinvar_record_name
from allelix.cli import main
from allelix.databases._versions import CLINVAR_INTERPRETER_VERSION
from allelix.databases.rsid_identity_loader import RSID_IDENTITY_DB_FILENAME, write_identity_db
from allelix.databases.schema import CLINVAR_SCHEMA

SOURCES = ("clinvar", "pharmgkb", "snpedia", "gwas", "gnomad", "alphamissense", "cadd",
           "rsid_identity")  # fmt: skip


def _data(tmp_path: Path, rows) -> Path:
    data = tmp_path / "data"
    data.mkdir()
    on = {"clinvar", "rsid_identity"}
    (data / "config.toml").write_text(
        "[sources]\n" + "".join(f"{s} = {'true' if s in on else 'false'}\n" for s in SOURCES)
    )
    with contextlib.closing(sqlite3.connect(data / clinvar_db_filename("GRCh37"))) as conn:
        conn.executescript(CLINVAR_SCHEMA)
        conn.executemany(
            "INSERT INTO clinvar_variants (rsid,chromosome,position,ref,alt,gene,"
            "clinical_significance,condition,review_status,allele_id,aggregate,"
            "submitters_same,submitters_total) VALUES (?,?,?,?,?,?,?,'Synthetic condition',"
            "'criteria provided, single submitter',?,?,1,1)",
            [
                (rsid, chrom, pos, ref, alt, gene, sig, 900265000 + i, sig)
                for i, (rsid, chrom, pos, ref, alt, gene, sig) in enumerate(rows)
            ],
        )
        conn.execute(
            "INSERT INTO database_versions (name,source_url,version,downloaded_at,"
            "record_count,local_version_tag) VALUES (?, 'test://synthetic', 'synthetic', "
            "'2001-01-01', ?, ?)",
            (clinvar_record_name("GRCh37"), len(rows), f"iv:{CLINVAR_INTERPRETER_VERSION}"),
        )
        conn.commit()
    write_identity_db(
        [("rs3999265999", "1", 5, "A", "G", 5, "A", "G", 0)],
        data / RSID_IDENTITY_DB_FILENAME,
        version="synthetic",
        source_url="test://identity",
        downloaded_at="2001-01-01",
    )
    return data


def _named(tmp_path: Path, data: Path, calls) -> dict[str, dict]:
    chip = tmp_path / "chip.txt"
    chip.write_text(
        "# This data file generated by 23andMe at: synthetic\n"
        "# Reference human assembly GRCh37\n# rsid\tchromosome\tposition\tgenotype\n"
        + "".join(f"{rsid}\t{chrom}\t{pos}\t{gt}\n" for rsid, chrom, pos, gt in calls)
    )
    out = tmp_path / "report.json"
    result = CliRunner(env={"COLUMNS": "500"}).invoke(
        main,
        ["analyze", str(chip), "--build", "grch37", "--data-dir", str(data), "--no-update",
         "--output", str(out)],
    )  # fmt: skip
    assert result.exit_code == 0, result.output
    return {e["rsid"]: e for e in json.loads(out.read_text()).get("high_value_unchecked") or []}


# ── R3b-01 (minor, new in RC3b): the naming line says an indel "covers" a call ──
# ── that stands past the indel's REF span, in the five-base slack ───────────

P0 = 3000000

SLACK_CASES = [
    # (ClinVar P/LP row, D/I call, why the call is outside the REF span)
    pytest.param(
        ("rs80357906", "17", 41209079, "A", "AC", "BRCA1"),
        ("i3999265201", "17", 41209083, "DI"),
        id="5382insC-insertion-anchor-plus-4",  # the repository's own INDELS fixture case
    ),
    pytest.param(
        ("rs3999265100", "13", P0, "GAT", "G", "GENEP"),
        ("i3999265010", "13", P0 + 3, "DD"),
        id="deletion-span-ends-P0+2-probe-at-P0+3",
    ),
    pytest.param(
        ("rs3999265100", "13", P0, "GAT", "G", "GENEP"),
        ("rs3999265102", "13", P0 + 7, "DI"),
        id="deletion-span-ends-P0+2-unheld-rsid-at-P0+7",
    ),
]


@pytest.mark.parametrize("plp,call", SLACK_CASES)
def test_r3b_01_slack_call_is_said_to_be_covered_by_the_indel(tmp_path, plp, call):
    """ClinVar's indel REF span is ``row_pos`` .. ``row_pos + len(REF) - 1``; the call
    stands past it, within the five bases of slack the docs describe ("covers the
    position or ends up to five bases before it"). RC3b names the call (correctly)
    but its line says "named because a Pathogenic or Likely pathogenic indel in <gene>
    covers its position", which is false for these positions. Fails on RC3b; RC3's
    line made no such claim (passes).
    """
    rsid, chrom, pos, ref, alt, gene = plp
    data = _data(tmp_path, [(rsid, chrom, pos, ref, alt, gene, "Pathogenic")])
    named = _named(tmp_path, data, [call])
    assert call[0] in named, named  # control: the call is named, as documented
    message = named[call[0]]["message"]
    assert "covers its position" not in message, message


# ── R3b-02 (minor, new in RC3b): an rsID ClinVar does not hold is told ClinVar ──
# ── "does not classify this rsID itself" ────────────────────────────────────


def test_r3b_02_unheld_rsid_line_speaks_of_clinvars_classification_of_it(tmp_path):
    """rs3999265102 is in no ClinVar row. Its ``DI`` call inside a Pathogenic deletion's
    REF span is named by position (correct), but the line says "ClinVar does not
    classify this rsID itself as Pathogenic or Likely pathogenic", as if ClinVar held
    it. docs/formats.md and ADR-0051 give that sentence to calls under an rsID ClinVar
    holds; an unheld rsID's call is described only as "named under the naming row's
    gene". Fails on RC3b; RC3's line had no such sentence (passes).
    """
    data = _data(tmp_path, [("rs3999265100", "13", P0, "GAT", "G", "GENEP", "Pathogenic")])
    named = _named(tmp_path, data, [("rs3999265102", "13", P0 + 1, "DI")])
    assert "rs3999265102" in named, named  # control
    assert "does not classify this rsID itself" not in named["rs3999265102"]["message"], named
