"""Explicit positions must fit positive SQLite coordinates; unplaced lists remain legal."""

import json
import logging

import pytest
from click.testing import CliRunner
from test_chip_chromosome_build_evidence import MAPPED, RAW, SEEDS, chip
from test_homref_ref_by_locus import _vcf

from allelix.cli import main
from allelix.parsers import detect_parser
from allelix.utils.build_detect import KNOWN_SNP_POSITIONS

BAD = [0, -1, -5, -(2**63), 2**63, 2**63 + 1, 10**80]
RS = "rs900618001"
READERS = (*RAW, *MAPPED, "genesforgood", "vcf")


def _source(path, reader, positions, build="GRCh37", gt="1/1"):
    if reader == "vcf":
        return _vcf(
            path,
            [("1", p, rs, "G", "A", 99, "PASS", ".", "GT:GQ", f"{gt}:99") for rs, p in positions],
            build=build,
        )
    actual = "23andme" if reader == "genesforgood" else reader
    chip(path, actual, [(rs, "1", p, "AA") for rs, p in positions])
    if reader == "genesforgood":
        path.write_text(
            path.read_text().replace(
                "# This data file generated by 23andMe", "# Genes for Good v1.2: genotype calls"
            )
        )
    if reader in ("23andme", "genesforgood"):
        first, rest = path.read_text().split("\n", 1)
        path.write_text(first + f"\n# Reference {build}\n" + rest)
    return path


@pytest.mark.parametrize("reader", READERS)
@pytest.mark.parametrize("position", BAD)
def test_explicit_bad_position_is_skipped_and_diagnosed(tmp_path, caplog, reader, position):
    source = _source(tmp_path / "input.txt", reader, [("rs900618002", 12345), (RS, position)])
    parser = detect_parser(source)
    assert parser.name == reader
    with caplog.at_level(logging.WARNING):
        calls = list(parser.parse(source))
    if position == 0 and reader != "vcf":
        # Arrays retain an unplaced rsID call; VCF still requires POS >= 1.
        assert [(v.rsid, v.position) for v in calls] == [("rs900618002", 12345), (RS, 0)]
        return
    assert [(v.rsid, v.position) for v in calls] == [("rs900618002", 12345)]
    assert any(
        "position" in r.message.lower() or "malformed" in r.message.lower() for r in caplog.records
    ), "Skipped explicit coordinates must be diagnosed"
    if reader == "vcf":
        assert parser.quality_stats.malformed_rows == 1


@pytest.mark.parametrize("reader", READERS)
@pytest.mark.parametrize("position", [1, 2**31, 2**63 - 1])
def test_positive_int64_bounds_are_not_narrowed_to_int32(tmp_path, reader, position):
    source = _source(tmp_path / "input.txt", reader, [(RS, position)])
    calls = list(detect_parser(source).parse(source))
    assert len(calls) == 1 and calls[0].position == position


@pytest.mark.parametrize("position", BAD)
@pytest.mark.parametrize("gt", ["0/0", "0", "./.", "0/.", "1/1"])
def test_vcf_reference_and_no_call_paths_also_count_malformed_positions(tmp_path, position, gt):
    source = _source(tmp_path / "input.vcf", "vcf", [(RS, position)], gt=gt)
    parser = detect_parser(source)
    calls = list(parser.parse(source))
    assert calls == []
    assert parser.quality_stats.malformed_rows == 1


def test_positionless_rsid_list_is_not_an_invalid_coordinate(tmp_path):
    source = tmp_path / "unplaced.txt"
    source.write_text("rs1801133\tAG\nrs1801131\tAA\nrs1799853\tCC\n")
    parser = detect_parser(source)
    assert parser.name == "rsid-genotype"
    calls = list(parser.parse(source))
    assert len(calls) == 3
    assert all(v.position == 0 and not v.chromosome for v in calls)


@pytest.mark.parametrize("position", [12345, 2**63])
@pytest.mark.parametrize("reader", ["vcf", "23andme"])
@pytest.mark.parametrize("build", ["GRCh37", "GRCh38"])
@pytest.mark.parametrize("auto", [False, True])
@pytest.mark.parametrize(
    "command", ["analyze", "pharmacogenomics", "methylation", "extract", "plink"]
)
def test_command_with_valid_neighbors_skips_overflow_offline(
    tmp_path, all_annotators_data_dir, reader, build, auto, command, position
):
    data = all_annotators_data_dir
    # Real shipped build seeds give both readers an independent auto decision.
    rows = [(rs, KNOWN_SNP_POSITIONS[rs][build][1]) for rs in SEEDS[:2]]
    rows.append((RS, position))
    source = _source(tmp_path / "input.txt", reader, rows, build)
    output = tmp_path / "report.json"
    args = ["export", "plink"] if command == "plink" else [command]
    args += [str(source), "--data-dir", str(data), "--build", "auto" if auto else build]
    if command in ("analyze", "pharmacogenomics", "methylation"):
        args += ["--no-update", "--output", str(output)]
    elif command == "extract":
        args += ["--snps", ",".join(SEEDS[:2])]
    else:
        args += ["--output-prefix", str(tmp_path / "plink")]
    result = CliRunner().invoke(main, args)
    assert result.exit_code == 0, (result.output, result.exception)
    assert not isinstance(result.exception, OverflowError)
    if output.exists():
        payload = json.loads(output.read_text())
        assert payload["input"]["total_variants"] == (3 if position == 12345 else 2)
        assert all(a.get("position", 1) != 2**63 for a in payload["annotations"])
    if command == "plink":
        bim = (tmp_path / "plink.bim").read_text()
        assert str(2**63) not in bim
        if position == 2**63:
            assert RS not in bim
