"""Full-size build decision regressions (ADR-0044).

Real exports are sorted by chromosome, so most build-detection seeds sit far
into the file. Up to 2.4.0 the build was looked for only in the first
100,000 rows; past that the file's label (or contig naming, or the format
default) decided, and a wrong or missing label attached the other build's
ClinVar records: real findings were lost and false "pathogenic" ones
appeared.

Every input here is generated in the test at full size with synthetic rows:
two chr1 seeds, then ``_FILLER`` filler rows (vendor-style ``i`` IDs), then
the remaining seeds at their real coordinates for one build. Each ClinVar
cache is synthetic and holds one "true" record (on the input's real build)
and one "harm" record (on the other build) at coordinates the input
carries. The tests use the CLI and the JSON report only.
"""

from __future__ import annotations

import contextlib
import functools
import json
import sqlite3
from typing import TYPE_CHECKING

import pytest
from click.testing import CliRunner

from allelix.annotators.clinvar import clinvar_db_filename, clinvar_record_name
from allelix.cli import main
from allelix.databases._versions import CLINVAR_INTERPRETER_VERSION
from allelix.databases.schema import CLINVAR_SCHEMA
from allelix.utils.build_detect import KNOWN_SNP_POSITIONS

if TYPE_CHECKING:
    from pathlib import Path

GRCH37 = "GRCh37"
GRCH38 = "GRCh38"
_OTHER = {GRCH37: GRCH38, GRCH38: GRCH37}

# More than the 100,000 rows that 2.4.0 inspected before falling back.
_FILLER = 120_000
_FILLER_START = 20_000_000  # chr1, after both chr1 seeds on either build
# The stops do not depend on where the seeds sit, so those tests stay small.
_SMALL = 2_000

_TRUE = ("3", 6_000_000, "G", "A", "TRUEGENE")
_HARM = ("2", 5_000_000, "C", "T", "HARMGENE")

_CHROM_ORDER = {str(n): n for n in range(1, 23)} | {"X": 23, "Y": 24, "MT": 25}

_23ANDME_HEAD = (
    "# This data file generated by 23andMe at: Mon Jun 01 00:00:00 2020\n"
    "#\n"
    "# Below is a textual version of your data. Fields are TAB-separated.\n"
)
_23ANDME_COLUMNS = "# rsid\tchromosome\tposition\tgenotype\n"

_GRCH37_LENGTHS = {"1": 249_250_621, "2": 243_199_373, "3": 198_022_430}
_GRCH38_LENGTHS = {"1": 248_956_422, "2": 242_193_529, "3": 198_295_559}


@functools.cache
def _rows(build: str, filler: int = _FILLER) -> list[tuple[str, str, int, str]]:
    """(id, chrom, pos, genotype), chromosome-sorted, seeds on ``build``."""
    seeds = [
        (rsid, entry[build][0], entry[build][1], "AG")
        for rsid, entry in KNOWN_SNP_POSITIONS.items()
        if build in entry
    ]
    filler_rows = [("i" + str(n), "1", _FILLER_START + 10 * n, "AA") for n in range(filler)]
    findings = [
        # rs-style IDs far above any dbSNP number: matched by position, as
        # an unknown chip rsID is.
        ("rs9900000001", _TRUE[0], _TRUE[1], _TRUE[2] + _TRUE[3]),
        ("rs9900000002", _HARM[0], _HARM[1], _HARM[2] + _HARM[3]),
    ]
    rows = seeds + filler_rows + findings
    rows.sort(key=lambda r: (_CHROM_ORDER[r[1]], r[2]))
    if filler >= _FILLER:
        assert sum(1 for r in rows[:100_000] if r[0] in KNOWN_SNP_POSITIONS) <= 2
    return rows


def _chip(path: Path, positions: str, label: str | None) -> Path:
    line = f"# We are using reference human assembly build {label[-2:]}.\n" if label else ""
    body = "".join(f"{i}\t{c}\t{p}\t{g}\n" for i, c, p, g in _rows(positions))
    path.write_text(_23ANDME_HEAD + line + _23ANDME_COLUMNS + body)
    return path


def _vcf(
    path: Path,
    positions: str,
    *,
    lengths: str | None,
    assembly: str | None = None,
    prefix: str = "",
    filler: int = _FILLER,
) -> Path:
    table = {GRCH37: _GRCH37_LENGTHS, GRCH38: _GRCH38_LENGTHS}
    contigs = ""
    for chrom in ("1", "2", "3", "10", "11", "12", "17", "19", "22"):
        attrs = [f"ID={prefix}{chrom}"]
        if lengths is not None and chrom in table[lengths]:
            attrs.append(f"length={table[lengths][chrom]}")
        if assembly is not None:
            attrs.append(f"assembly={assembly}")
        contigs += f"##contig=<{','.join(attrs)}>\n"
    body = "".join(
        f"{prefix}{c}\t{p}\t.\t{g[0]}\t{g[1] if g[1] != g[0] else 'T'}\t50\tPASS\t.\tGT\t0/1\n"
        for _, c, p, g in _rows(positions, filler)
    )
    path.write_text(
        "##fileformat=VCFv4.2\n"
        + contigs
        + '##FORMAT=<ID=GT,Number=1,Type=String,Description="Genotype">\n'
        + "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tS1\n"
        + body
    )
    return path


def _clinvar_cache(data: Path, build: str, record: tuple) -> None:
    chrom, pos, ref, alt, gene = record
    rows = [
        (
            f"rs{9_100_000_000 + pos}",
            chrom,
            pos,
            ref,
            alt,
            "Pathogenic",
            f"{gene}_disorder",
            gene,
            "criteria_provided,_multiple_submitters,_no_conflicts",
            pos,
        )
    ]
    with contextlib.closing(sqlite3.connect(data / clinvar_db_filename(build))) as conn:
        conn.executescript(CLINVAR_SCHEMA)
        conn.executemany(
            "INSERT INTO clinvar_variants (rsid, chromosome, position, ref, alt, "
            "clinical_significance, condition, gene, review_status, allele_id) "
            "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
            rows,
        )
        conn.execute(
            "INSERT INTO database_versions (name, source_url, version, downloaded_at, "
            "record_count, remote_signal, local_version_tag) "
            "VALUES (?, 'test://full-size', '20260101', '2026-10-12', 1, NULL, ?)",
            (clinvar_record_name(build), f"iv:{CLINVAR_INTERPRETER_VERSION}"),
        )
        conn.commit()


@pytest.fixture
def data_for(tmp_path: Path):
    """A data dir whose ``true_build`` cache holds TRUE and the other holds HARM."""

    def make(true_build: str) -> Path:
        data = tmp_path / f"data-{true_build}"
        data.mkdir()
        _clinvar_cache(data, true_build, _TRUE)
        _clinvar_cache(data, _OTHER[true_build], _HARM)
        return data

    return make


def _invoke(*args: str):
    return CliRunner(env={"COLUMNS": "200"}).invoke(main, list(args))


def _analyze_json(path: Path, data: Path, out: Path, *extra: str):
    result = _invoke("analyze", str(path), "--data-dir", str(data), "--no-update",
                     "--output", str(out), *extra)  # fmt: skip
    return result


def _genes(out: Path) -> set[str]:
    return {a.get("gene") for a in json.loads(out.read_text())["annotations"]}


# ── The build resolves correctly; no false finding ─────────────────


@pytest.mark.parametrize(
    ("name", "positions", "label"),
    [
        ("label37_positions38", GRCH38, GRCH37),
        ("label38_positions37", GRCH37, GRCH38),
        ("unlabelled_positions38", GRCH38, None),
    ],
)
def test_full_size_chip_resolves_from_positions(
    tmp_path: Path, data_for, name: str, positions: str, label: str | None
) -> None:
    chip = _chip(tmp_path / f"{name}.txt", positions, label)
    out = tmp_path / "report.json"
    result = _analyze_json(chip, data_for(positions), out)
    assert result.exit_code == 0, result.output
    payload = json.loads(out.read_text())
    assert payload["input"]["build"] == positions
    assert payload["input"]["build_source"] == "seeds"
    genes = _genes(out)
    assert "HARMGENE" not in genes, "false pathogenic finding from the other build"
    assert "TRUEGENE" in genes, "real finding lost"
    if label is not None:
        assert "Build mismatch" in " ".join(result.output.split())


@pytest.mark.parametrize(
    ("name", "positions", "prefix"),
    [
        ("hg19_chr_prefixed", GRCH37, "chr"),
        ("grch38_bare_contigs", GRCH38, ""),
    ],
)
def test_full_size_vcf_resolves_from_contig_lengths(
    tmp_path: Path, data_for, name: str, positions: str, prefix: str
) -> None:
    vcf = _vcf(tmp_path / f"{name}.vcf", positions, lengths=positions, prefix=prefix)
    out = tmp_path / "report.json"
    result = _analyze_json(vcf, data_for(positions), out)
    assert result.exit_code == 0, result.output
    payload = json.loads(out.read_text())
    assert payload["input"]["build"] == positions
    assert payload["input"]["build_source"] == "contig_lengths"
    genes = _genes(out)
    assert "HARMGENE" not in genes
    assert "TRUEGENE" in genes


# ── The run stops, and says why (small inputs) ─────────────────────


def test_contig_lengths_contradicting_the_header_stop(tmp_path: Path, data_for) -> None:
    vcf = _vcf(tmp_path / "x.vcf", GRCH37, lengths=GRCH37, assembly=GRCH38, filler=_SMALL)
    out = tmp_path / "report.json"
    result = _analyze_json(vcf, data_for(GRCH37), out)
    assert result.exit_code != 0
    flat = " ".join(result.output.split())
    assert "header says GRCh38 but its contig lengths are GRCh37" in flat
    assert "--build grch37 or --build grch38" in flat
    assert not out.exists()


def test_vcf_without_lengths_assembly_or_seeds_stops(tmp_path: Path, data_for) -> None:
    vcf = tmp_path / "bare.vcf"
    vcf.write_text(
        "##fileformat=VCFv4.2\n##contig=<ID=1>\n"
        '##FORMAT=<ID=GT,Number=1,Type=String,Description="Genotype">\n'
        "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tS1\n"
        + "".join(
            f"1\t{_FILLER_START + 10 * n}\t.\tA\tG\t50\tPASS\t.\tGT\t0/1\n" for n in range(_SMALL)
        )
    )
    out = tmp_path / "report.json"
    result = _analyze_json(vcf, data_for(GRCH37), out)
    assert result.exit_code != 0
    assert "no contig lengths, no assembly" in " ".join(result.output.split())
    assert not out.exists()


# ── A late stop leaves nothing behind on any output path ───────────


@pytest.fixture
def lifted(tmp_path: Path) -> Path:
    """GRCh37 contig lengths kept from the source, records at GRCh38 positions."""
    return _vcf(tmp_path / "lifted.vcf", GRCH38, lengths=GRCH37, filler=_SMALL)


def _assert_late_stop(result) -> None:
    assert result.exit_code != 0
    flat = " ".join(result.output.split())
    assert "contig lengths say GRCh37 but its known-SNP positions say GRCh38" in flat
    assert "annotation pass" in flat


@pytest.mark.parametrize("suffix", [".json", ".html"])
def test_late_stop_writes_no_report(tmp_path: Path, data_for, lifted: Path, suffix: str):
    out = tmp_path / f"report{suffix}"
    _assert_late_stop(_analyze_json(lifted, data_for(GRCH37), out))
    assert not out.exists()


def test_late_stop_writes_no_annotated_vcf(tmp_path: Path, data_for, lifted: Path):
    vcf_out = tmp_path / "annotated.vcf"
    result = _invoke("analyze", str(lifted), "--data-dir", str(data_for(GRCH37)),
                     "--no-update", "--vcf-out", str(vcf_out))  # fmt: skip
    _assert_late_stop(result)
    assert not vcf_out.exists()
    assert "TRUEGENE" not in result.output and "HARMGENE" not in result.output


def test_late_stop_writes_no_diff(tmp_path: Path, data_for, lifted: Path):
    data = data_for(GRCH37)
    baseline = tmp_path / "baseline.json"
    good = _vcf(tmp_path / "good.vcf", GRCH37, lengths=GRCH37, filler=_SMALL)
    assert _analyze_json(good, data, baseline).exit_code == 0
    out = tmp_path / "diff.json"
    _assert_late_stop(_analyze_json(lifted, data, out, "--diff", str(baseline)))
    assert not out.exists()


def test_late_stop_writes_no_plink_files(tmp_path: Path, data_for, lifted: Path):
    prefix = tmp_path / "out"
    result = _invoke("export", "plink", str(lifted), "-o", str(prefix),
                     "--data-dir", str(data_for(GRCH37)))  # fmt: skip
    _assert_late_stop(result)
    assert sorted(p.name for p in tmp_path.iterdir() if p.name.startswith("out")) == []


def test_late_stop_prints_no_extract_table(tmp_path: Path, data_for, lifted: Path):
    result = _invoke("extract", str(lifted), "--snps", "rs4680",
                     "--data-dir", str(data_for(GRCH37)))  # fmt: skip
    _assert_late_stop(result)
    assert "rs4680" not in result.output.split("Error:")[0]
