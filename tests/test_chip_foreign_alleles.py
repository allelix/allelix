"""A chip call whose alleles are not its own rsID's gets no ClinVar finding.

One locus holds two rsIDs: the chip's own rsA (identity G/A, a Benign G>A
ClinVar row) and rsB (a Pathogenic G>C row). A probe for a G/A site reads G
or A on its design strand, so a ``CC`` call there is most likely a
minus-strand ``GG``, not rsB's C. ClinVar abstains for a chip call unless
every called base is one of its own rsID's identity alleles at that build
and locus, and counts it at a P/LP locus. Nothing is complemented, VCF input
keeps its own REF/ALT, and a call whose rsID has no identity evidence is not
judged.
"""

from __future__ import annotations

import json

import pytest
from click.testing import CliRunner
from test_annotation_parity_and_named_disclosures import _clinvar, _identity, _vcf

from allelix.cli import main
from allelix.reports.json_report import SCHEMA_VERSION

BUILDS = ("GRCh37", "GRCh38")
RSA, RSB = "rs3999980601", "rs3999980602"
POS = 1000601
CONFIG = (
    "[sources]\nclinvar = true\npharmgkb = false\nsnpedia = false\ngwas = false\n"
    "gnomad = false\nalphamissense = false\ncadd = false\nrsid_identity = true\n"
)


def _data(tmp_path, *, identity_rows=None, rsa_alt="A", rsa_sig="Benign"):
    data = tmp_path / "data"
    data.mkdir()
    (data / "config.toml").write_text(CONFIG)
    for build in BUILDS:
        _clinvar(
            data,
            build,
            [
                (RSA, "1", POS, "G", "A", "GENEA", rsa_sig, rsa_sig, 1, 1),
                (RSB, "1", POS, "G", "C", "GENEB", "Pathogenic", "Pathogenic", 1, 1),
            ],
        )
    if identity_rows is None:
        identity_rows = [
            (RSA, "1", POS, "G", rsa_alt, POS, "G", rsa_alt, 0),
            (RSB, "1", POS, "G", "C", POS, "G", "C", 1),
        ]
    _identity(data, identity_rows)
    return data


def _chip(tmp_path, call, *, build, rsid=RSA):
    path = tmp_path / f"chip_{call}.txt"
    path.write_text(
        "# This data file generated by 23andMe at: synthetic\n"
        f"# Reference human assembly {build}\n"
        "# rsid\tchromosome\tposition\tgenotype\n"
        f"{rsid}\t1\t{POS}\t{call}\n"
    )
    return path


def _analyze(tmp_path, data, source, build, *extra):
    out = tmp_path / f"{source.stem}.{build}.json"
    result = CliRunner(env={"COLUMNS": "500"}).invoke(
        main,
        [
            "analyze",
            str(source),
            "--build",
            build.lower(),
            "--data-dir",
            str(data),
            "--no-update",
            "--output",
            str(out),
            *extra,
        ],
    )
    assert result.exit_code == 0, (result.output, result.exception)
    return json.loads(out.read_text()), result.output


def _clinvar_rows(report):
    return [
        (a["rsid"], a["genotype_match"], a["significance"])
        for a in report["annotations"]
        if a["source"] == "clinvar"
    ]


@pytest.mark.parametrize("build", BUILDS)
@pytest.mark.parametrize("call", ["CC", "AC", "CA", "TT", "GT"])
def test_call_outside_its_own_rsids_alleles_gets_no_clinvar_finding(tmp_path, build, call):
    data = _data(tmp_path)
    report, output = _analyze(tmp_path, data, _chip(tmp_path, call, build=build), build)
    assert _clinvar_rows(report) == [], output
    assert report["input"]["probe_classes"]["foreign_allele_calls_at_plp_loci"] == 1


@pytest.mark.parametrize("build", BUILDS)
def test_terminal_says_the_call_was_not_matched(tmp_path, build):
    data = _data(tmp_path)
    _report, output = _analyze(
        tmp_path, data, _chip(tmp_path, "CC", build=build), build, "--show-unchecked"
    )
    assert "not one of its own rsID" in output, output


@pytest.mark.parametrize("build", BUILDS)
@pytest.mark.parametrize("call", ["GG", "AA", "AG"])
def test_call_within_its_own_rsids_alleles_is_matched_as_before(tmp_path, build, call):
    # Here rsA's own G>A row is Pathogenic: a call of its own alleles still
    # gets it wherever it carries A, and never rsB's C row.
    data = _data(tmp_path, rsa_sig="Pathogenic")
    report, output = _analyze(tmp_path, data, _chip(tmp_path, call, build=build), build)
    expected = [(RSA, call, "clinvar_pathogenic")] if "A" in call else []
    assert _clinvar_rows(report) == expected, output
    assert report["input"]["probe_classes"]["foreign_allele_calls_at_plp_loci"] == 0


@pytest.mark.parametrize("build", BUILDS)
def test_own_multiallelic_rsid_supports_every_listed_allele(tmp_path, build):
    # rsA itself lists G>A and G>C: a C call is its own allele, and rsB's
    # Pathogenic C row at the locus is matched as before.
    rows = [
        (RSA, "1", POS, "G", "A", POS, "G", "A", 0),
        (RSA, "1", POS, "G", "C", POS, "G", "C", 0),
        (RSB, "1", POS, "G", "C", POS, "G", "C", 1),
    ]
    data = _data(tmp_path, identity_rows=rows)
    report, output = _analyze(tmp_path, data, _chip(tmp_path, "CC", build=build), build)
    assert (RSB, "CC", "clinvar_pathogenic") in _clinvar_rows(report), output
    assert report["input"]["probe_classes"]["foreign_allele_calls_at_plp_loci"] == 0


@pytest.mark.parametrize("build", BUILDS)
def test_rsid_without_identity_evidence_is_judged_by_its_own_clinvar_rows(tmp_path, build):
    # Only rsB is in the identity table, but ClinVar's own G>A row of rsA is
    # evidence of rsA's alleles there: CC is counted and gets none of
    # rsB's rows. Before 2.6.1 this case was not judged and got rsB's
    # Pathogenic finding (R1-01).
    rows = [(RSB, "1", POS, "G", "C", POS, "G", "C", 1)]
    data = _data(tmp_path, identity_rows=rows)
    report, output = _analyze(tmp_path, data, _chip(tmp_path, "CC", build=build), build)
    assert report["input"]["probe_classes"]["foreign_allele_calls_at_plp_loci"] == 1
    assert _clinvar_rows(report) == [], output


@pytest.mark.parametrize("build", BUILDS)
def test_vcf_record_keeps_its_own_ref_and_alt(tmp_path, build):
    # A VCF record states its REF and ALT: it is not a chip call and is
    # matched by them as before.
    data = _data(tmp_path)
    source = _vcf(tmp_path / "in.vcf", [(RSA, "1", POS, "G", "C", "1/1", ".")])
    report, output = _analyze(tmp_path, data, source, build)
    assert [g for _r, g, s in _clinvar_rows(report) if s == "clinvar_pathogenic"] == ["CC"], output
    assert report["input"]["probe_classes"] is None


