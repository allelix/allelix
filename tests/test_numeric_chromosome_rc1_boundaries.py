@pytest.mark.parametrize("code", PAR)
@pytest.mark.parametrize("length", [2699520, 155270560, 156040895, 16571])
@pytest.mark.parametrize("build", [None, "GRCh37", "GRCh38"])
def test_par_length_neither_supplies_nor_contradicts_build_evidence(code, length, build):
    declared = {} if build is None else dict(LENGTHS[build])
    control = contig_length_verdict(declared)
    actual = contig_length_verdict({**declared, code: length})
    assert actual == control


@pytest.mark.parametrize("build", ["GRCh37", "GRCh38"])
@pytest.mark.parametrize(
    "code,canonical", [("23", "X"), ("chr23", "X"), ("24", "Y"), ("CHR24", "Y")]
)
def test_full_sex_chromosome_length_still_votes_and_rejects_conflicts(build, code, canonical):
    length = LENGTHS[build][canonical]
    assert contig_length_verdict({code: length}).build == build
    assert contig_length_verdict({code: length + 1}).status == "unsupported"
    other = "GRCh38" if build == "GRCh37" else "GRCh37"
    assert contig_length_verdict({"1": LENGTHS[other]["1"], code: length}).status == "mixed"


