def _source(path, reader, rows):
    """Rows are ID, chromosome, position, two base letters (or --)."""
    if reader == "vcf":
        return _vcf(
            path,
            [(c, None) for _, c, _, _ in rows],
            [(c, p, r or ".", "G", "A", ".", "PASS", ".", "GT", "0/1") for r, c, p, _ in rows],
        )
    headers = {
        "decodeme": "Name,Variation,Chromosome,Position,Strand,YourCode\n",
        "illumina": "RSID\tCHROMOSOME\tPOSITION\tRESULT\n",
        "famfinder": "# Family Tree DNA - FamFinder\n"
        "RSID\tCHROMOSOME\tPOSITION\tALLELE1\tALLELE2\n",
        "ancestry": "#AncestryDNA raw data download\n"
        "rsid\tchromosome\tposition\tallele1\tallele2\n",
        "myhappygenes": "# MyHappyGenes\n"
        "SNP Name\tChr\tPosition\tAllele1 - Forward\tAllele2 - Forward\n",
        "23andme": "# This data file generated by 23andMe at: synthetic\n"
        "# rsid\tchromosome\tposition\tgenotype\n",
        "myheritage": "# MyHeritage\nRSID,CHROMOSOME,POSITION,RESULT\n",
        "livingdna": "# Living DNA\n# rsid\tchromosome\tposition\tgenotype\n",
        "ftdna": "RSID,CHROMOSOME,POSITION,RESULT\n",
    }
    text = headers[reader]
    for rsid, chrom, pos, gt in rows:
        if reader == "decodeme":
            text += f"{rsid},G/A,{chrom},{pos},+,{gt}\n"
        elif reader in {"myheritage", "ftdna"}:
            text += f'"{rsid}","{chrom}","{pos}","{gt}"\n'
        elif reader in {"famfinder", "ancestry", "myhappygenes"}:
            text += f"{rsid}\t{chrom}\t{pos}\t{gt[0]}\t{gt[1]}\n"
        else:
            text += f"{rsid}\t{chrom}\t{pos}\t{gt}\n"
    path.write_text(text)
    return path


# Expected chromosome part of a generated ID in released 2.6.2, independent
# of the new lookup name or the PLINK chromosome column. Literal XY keeps case.
def _legacy_id_chrom(reader, chrom):
    if reader == "ancestry":
        return {"23": "X", "24": "Y", "25": "X", "26": "MT"}.get(chrom, chrom)
    if reader not in {"vcf", "decodeme", "illumina", "famfinder"}:
        return chrom
    bare = chrom[3:] if chrom[:3].lower() == "chr" else chrom
    if bare.upper() in {"M", "MT"}:
        return "MT"
    if bare.upper() in {"X", "Y"}:
        return bare.upper()
    return bare


@pytest.mark.parametrize("reader", READERS)
@pytest.mark.parametrize("build", ["grch37", "grch38"])
@pytest.mark.parametrize(
    "codes",
    [
        ("23", "24", "25", "26", "XY", "chr23", "chr25", "chrxy"),
        ("1", "chr1", "X", "chrX", "y", "M", "chrUn_SYNTH", "0"),
    ],
    ids=["numeric-and-par", "prior-normalization-controls"],
)
def test_generated_ids_follow_each_readers_released_convention(tmp_path, reader, build, codes):
    data = tmp_path / "empty"
    _config(data, set())
    source = _source(
        tmp_path / "source.txt",
        reader,
        [("", chrom, POS_X + i, "GA") for i, chrom in enumerate(codes)],
    )
    calls = list(detect_parser(source).parse(source))
    assert len(calls) == len(codes), "all synthetic unnamed rows must parse"
    assert all(not v.rsid for v in calls)
    rows = _export_plink(source, data, tmp_path / "out", build)
    # The pre-existing GRCh37 UCSC-mito guard drops the VCF spelling M.
    retained = [
        (i, chrom)
        for i, chrom in enumerate(codes)
        if not (reader == "vcf" and build == "grch37" and chrom == "M")
    ]
    assert len(rows) == len(retained)
    pair = "G:A" if reader == "vcf" else ".:."
    expected = {
        str(POS_X + i): f"{_legacy_id_chrom(reader, chrom)}:{POS_X + i}:{pair}"
        for i, chrom in retained
    }
    assert {row[3]: row[1] for row in rows} == expected


@pytest.mark.parametrize("build", ["grch37", "grch38"])
@pytest.mark.parametrize("code", ["23", "25", "XY", "chrxy"])
def test_generated_id_duplicate_suffixes_keep_the_released_base(tmp_path, build, code):
    data = tmp_path / "empty"
    _config(data, set())
    base = f"{_legacy_id_chrom('vcf', code)}:{POS_X}:G:A"
    source = _vcf(
        tmp_path / "duplicates.vcf",
        [(code, None)],
        [
            (code, POS_X, ".", "G", "A", ".", "PASS", ".", "GT", "0/1"),
            (code, POS_X, ".", "G", "A", ".", "PASS", ".", "GT", "0/1"),
            (code, POS_X, ".", "G", "A", ".", "PASS", ".", "GT", "0/1"),
        ],
    )
    rows = _export_plink(source, data, tmp_path / "out", build)
    assert [row[1] for row in rows] == [base, base + ":2", base + ":3"]


@pytest.mark.parametrize("reader", RAW_READERS)
@pytest.mark.parametrize("build", ["GRCh37", "GRCh38"])
@pytest.mark.parametrize("code,canonical", [("23", "X"), ("chrM", "MT")])
@pytest.mark.parametrize("reverse", [False, True])
def test_extract_cli_chooses_placed_duplicate_for_raw_readers(
    tmp_path, reader, build, code, canonical, reverse
):
    data = tmp_path / "data"
    _config(data, {"rsid_identity", "gnomad"} if build == "GRCh38" else {"rsid_identity"})
    _identity(data, [(RS_X, canonical, POS_X, "G", "A", POS_X, "G", "A", 0)])
    if build == "GRCh38":
        _gnomad_site(data, RS_X, canonical, POS_X, "G", "A", 0.1)
    records = [(RS_X, "1", 5000, "AA"), (RS_X, code, POS_X, "GA")]
    if reverse:
        records.reverse()
    source = _source(tmp_path / "source.txt", reader, records)
    assert len(list(detect_parser(source).parse(source))) == 2
    result = CliRunner().invoke(
        main,
        [
            "extract",
            str(source),
            "--snps",
            RS_X,
            "--build",
            build.lower(),
            "--data-dir",
            str(data),
        ],
    )
    assert result.exit_code == 0, (result.output, result.exception)
    lines = [line for line in result.output.splitlines() if RS_X in line]
    assert len(lines) == 1, result.output
    cells = [part.strip() for part in lines[0].split("│")]
    assert "3,000,001" in cells and "G/A" in cells, result.output


@pytest.mark.parametrize(
    "code,canonical",
    [
        ("23", "X"),
        ("24", "Y"),
        ("25", "X"),
        ("26", "MT"),
        ("XY", "X"),
        ("chrX", "X"),
        ("y", "Y"),
        ("M", "MT"),
        ("chr1", "1"),
    ],
)
@pytest.mark.parametrize("no_call", [False, True])
@pytest.mark.parametrize("ranked", [False, True])
def test_extract_choice_prefers_placement_even_for_a_no_call(code, canonical, no_call, ranked):
    other = Variant(RS_X, "2", 5000, "A", "A", record_index=0)
    allele1, allele2 = ("-", "-") if no_call else ("G", "A")
    placed = Variant(RS_X, code, POS_X, allele1, allele2, record_index=1)
    rank = {"2": 0, canonical: 1} if ranked else {}
    assert _extract_choice([other, placed], {(canonical, POS_X): "G"}, rank) is placed


@pytest.mark.parametrize("build", ["GRCh37", "GRCh38"])
def test_extract_preserves_padded_site_and_usable_then_file_order_rules(build):
    padded = Variant(
        RS_X,
        "X",
        POS_X - 1,
        "CG",
        "CA",
        ref="CG",
        input_alt="CA",
        ref_from_input=True,
        build=build,
        record_index=1,
    )
    trimmed = Variant(
        RS_X,
        "X",
        POS_X,
        "G",
        "A",
        ref="G",
        input_alt="A",
        ref_from_input=True,
        build=build,
        record_index=2,
    )
    missing = Variant(RS_X, "X", POS_X, "-", "-", ref="G", record_index=0)
    places = {("X", POS_X): "G"}
    assert _extract_choice([missing, trimmed, padded], places, {"X": 0}) is padded
    assert _extract_choice([trimmed, padded], {}, {}) is padded
