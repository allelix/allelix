"""Comparing unrelated chip calls must not scan the other file per call."""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

import allelix.compare as comparison
from allelix.parsers.twentythreeandme import TwentyThreeAndMeParser
from allelix.parsers.vcf import VcfParser


def _calls(tmp_path, name, size, offset, vcf):
    identifiers = range(offset, offset + size)
    if vcf:
        path = tmp_path / f"{name}.vcf"
        path.write_text(
            "##fileformat=VCFv4.2\n##contig=<ID=1,length=248956422>\n"
            "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tS\n"
            + "".join(
                f"1\t{i + 100}\trs{900000000 + i}\tG\tA\t.\tPASS\t.\tGT\t0/1\n"
                for i in identifiers
            )
        )
        return list(VcfParser().parse(path))
    path = tmp_path / f"{name}.txt"
    path.write_text(
        "# This data file generated by 23andMe at: synthetic\n"
        "# reference human assembly build 38\n"
        "# rsid\tchromosome\tposition\tgenotype\n"
        + "".join(f"rs{900000000 + i}\t1\t{i + 100}\tAG\n" for i in identifiers)
    )
    return list(TwentyThreeAndMeParser().parse(path))


def _work(left, right):
    # Count executed Python lines at the public comparison boundary, not wall time.
    # This permits sorting/indexing and does not require a particular helper or index.
    filename = str(Path(comparison.__file__).resolve())
    count = 0

    def trace(frame, event, arg):
        nonlocal count
        if frame.f_code.co_filename == filename:
            if event == "line":
                count += 1
            return trace
        return None

    previous = sys.gettrace()
    try:
        sys.settrace(trace)
        result = comparison.compare_variants(left, right, build1="GRCh38", build2="GRCh38")
    finally:
        sys.settrace(previous)
    return result, count


@pytest.mark.parametrize("right_vcf", [False, True])
@pytest.mark.parametrize("overlap", [False, True])
@pytest.mark.parametrize("swap", [False, True])
def test_unmatched_chip_calls_scale_without_cartesian_work(tmp_path, right_vcf, overlap, swap):
    counts = []
    for size in (128, 512):
        offset = size // 2 if overlap else size
        left = _calls(tmp_path, f"left-{size}", size, 0, False)
        right = _calls(tmp_path, f"right-{size}", size, offset, right_vcf)
        if swap:
            left, right = right, left
        result, work = _work(left, right)
        shared = size // 2 if overlap else 0
        assert result.shared == result.concordant == shared
        assert result.file1_only == result.file2_only == size - shared
        assert not result.chip_not_compared
        counts.append(work)
    assert counts[0] > 0, "The comparison work must actually be observed"
    assert counts[1] <= 8 * counts[0], (
        f"Four times as many calls must stay below quadratic work; observed line events: {counts}"
    )
