"""Tracking ploidy must not add raw errors for input coordinates."""

import pytest
from click.testing import CliRunner
from validated_call_helpers import BUILDS, RSID, call, setup

from allelix.cli import main


@pytest.mark.parametrize("build", BUILDS)
@pytest.mark.parametrize("file_format", ["vcf", "23andme"])
@pytest.mark.parametrize("position", [-1, 0])
def test_coordinate_handling_does_not_leak_counter_overflow(
    tmp_path, build, file_format, position
):
    data = tmp_path / "data"
    setup(data, build)
    if file_format == "vcf":
        source = call(tmp_path / "input.vcf", position)
    else:
        source = tmp_path / "input.txt"
        source.write_text(
            "# This data file generated by 23andMe\n"
            "# rsid\tchromosome\tposition\tgenotype\n"
            f"{RSID}\t1\t{position}\tAG\n"
        )
    result = CliRunner().invoke(
        main,
        [
            "analyze",
            str(source),
            "--build",
            build.lower(),
            "--data-dir",
            str(data),
            "--no-update",
            "--output",
            str(tmp_path / "report.json"),
        ],
    )
    # Accept the prior behavior or a clean input error, never a raw exception.
    assert result.exit_code in (0, 1, 2)
    assert result.exception is None or isinstance(result.exception, SystemExit), (
        type(result.exception).__name__,
        str(result.exception),
    )
    assert "Traceback" not in result.output
