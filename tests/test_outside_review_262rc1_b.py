def test_b02_explanation_matches_the_at_or_below_rule(tmp_path):
    """FAILS on rc1: with plausibility.heterozygous_max_af = 0.2, a heterozygous call whose
    gnomAD AF is exactly 0.2 is flagged suspicious ("?" and the HTML warning), and the
    terminal legend and HTML "Reading This Report" say the variant is "rarer ... than
    Allelix's limit", which it is not. The hover text and panel row say "at or below".

    Passes on base: 2.6.1 has no such sentence (its "? suspicious: gnomAD reports no
    carriers" legend is wrong for non-default limits in another way, fixed by 2.6.2).
    """
    cfg = CONFIG + "\n[plausibility]\nheterozygous_max_af = 0.2\n"
    data, chips, _vcf = _rich_fixture(tmp_path / "fx", cfg)
    report, _ = _analyze(tmp_path, data, chips["GRCh38"], "GRCh38", "json")
    (row,) = [a for a in report["annotations"] if a["rsid"] == "rs3999300003"]
    assert (row["allele_frequency"], row["plausibility"]) == (0.2, "suspicious")
    terminal, _ = _analyze(tmp_path, data, chips["GRCh38"], "GRCh38", "terminal")
    assert re.search(r"rs3999300003 .* AG \?", terminal)
    page, _ = _analyze(tmp_path, data, chips["GRCh38"], "GRCh38", "html")
    text = _flat(htmllib.unescape(re.sub(r"<[^>]+>", " ", page)))
    strict = "rarer in the population (gnomAD) than Allelix"
    assert strict not in _flat(terminal), "terminal legend: 'rarer than' for an AF at the limit"
    assert strict not in text, "HTML Reading This Report: 'rarer than' for an AF at the limit"
    # The README section says the same next to its own table row "at or below".
    import allelix

    readme = (Path(allelix.__file__).resolve().parents[1] / "README.md").read_text("utf-8")
    section = readme.split("### Plausibility flag", 1)[1].split("\n### ", 1)[0]
    assert strict not in _flat(section), "README: 'rarer than' next to the 'at or below' row"
