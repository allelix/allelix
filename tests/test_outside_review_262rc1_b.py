def _stamp(conn, name, count, tag):
    conn.execute(
        "INSERT INTO database_versions (name,source_url,version,downloaded_at,record_count,"
        "local_version_tag) VALUES (?, 'test://synthetic', 'synthetic', '2001-01-01', ?, ?)",
        (name, count, tag),
    )


def _gnomad(data, rows):
    """rows: chrom, pos, ref, alt, rsid, af (GRCh38)."""
    with contextlib.closing(sqlite3.connect(data / "gnomad.sqlite")) as conn:
        conn.executescript(GNOMAD_SCHEMA)
        rows = [*rows, ("3", 9999, "G", "A", "rs3999399999", 0.4)]  # keeps the cache ready
        conn.executemany(
            "INSERT INTO gnomad_frequencies (chrom,pos,ref,alt,rsid,af) VALUES (?,?,?,?,?,?)", rows
        )
        _stamp(conn, "gnomad", len(rows), f"sv:{GNOMAD_SCHEMA_VERSION}")
        conn.commit()


def _cadd(data, rows):
    """rows: chrom, pos, ref, alt, phred."""
    with contextlib.closing(sqlite3.connect(data / "cadd.sqlite")) as conn:
        conn.executescript(CADD_SCHEMA)
        conn.executemany(
            "INSERT INTO cadd_scores (chrom,pos,ref,alt,phred) VALUES (?,?,?,?,?)", rows
        )
        _stamp(conn, "cadd", len(rows), f"sv:{CADD_SCHEMA_VERSION}")
        conn.commit()


def _chip(path, calls, build):
    path.write_text(
        "# This data file generated by 23andMe at: synthetic\n"
        f"# Reference human assembly {build}\n"
        "# rsid\tchromosome\tposition\tgenotype\n"
        + "".join(f"{rsid}\t{chrom}\t{pos}\t{call}\n" for rsid, chrom, pos, call in calls)
    )
    return path


def _analyze(tmp_path, data, source, build, surface, *extra, command="analyze"):
    """Run in-process; returns (parsed report or console text, console text)."""
    out = tmp_path / f"{source.stem}-{build}-{command}.{surface}"
    args = [command, str(source), "--data-dir", str(data), "--no-update", "--build", build.lower()]
    if surface != "terminal":
        args += ["--output", str(out)]
    result = CliRunner(env={"COLUMNS": "2000"}).invoke(main, [*args, *extra])
    assert result.exit_code == 0, (result.output, result.exception)
    if surface == "json":
        return json.loads(out.read_text()), result.output
    if surface == "html":
        return out.read_text(encoding="utf-8"), result.output
    return result.output, result.output


def _flat(text):
    return " ".join(text.split())


