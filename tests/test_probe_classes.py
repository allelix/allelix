"""Array calls ClinVar never matches, counted and disclosed (ADR-0051).

A vendor probe without an rsID (``i5000123``) is not locus-matched, and a
``D`` / ``I`` call names no base, so neither is assessed against ClinVar.
The report counts them where ClinVar's aggregate is Pathogenic or Likely
pathogenic, and counts every D/I call. All genotypes and ClinVar rows are
synthetic.
"""

