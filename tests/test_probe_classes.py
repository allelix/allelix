_SINGLE = "criteria_provided,_single_submitter"

# (rsid, chrom, pos, ref, alt, aggregate); rsIDs in the unused 900951xxx range.
_ROWS = [
    ("rs900951001", "2", 1000, "G", "A", "Pathogenic"),
    ("rs900951002", "2", 2000, "G", "A", "Uncertain significance"),
    ("rs900951003", "3", 3000, "CT", "C", "Likely pathogenic"),
    ("rs900951004", "3", 4000, "CT", "C", "Conflicting classifications of pathogenicity"),
    ("rs900951005", "3", 5000, "C", "CTT", "Pathogenic/Likely pathogenic"),
    ("rs900951006", "2", 6000, "G", "A", "Pathogenic"),
]

_CALLS = [
    # i-probes: at a P/LP locus (counted), at a VUS locus, a no-call at a
    # P/LP locus, and one where ClinVar has nothing.
    ("i900951001", "2", 1000, "AG"),
    ("i900951002", "2", 2000, "AG"),
    ("i900951003", "2", 6000, "--"),
    ("i900951004", "2", 9000, "AG"),
    # D/I calls: two at P/LP rsIDs (counted), one at a Conflicting rsID,
    # one at an rsID ClinVar does not hold.
    ("rs900951003", "3", 3000, "DI"),
    ("rs900951005", "3", 5000, "II"),
    ("rs900951004", "3", 4000, "DD"),
    ("rs900951099", "3", 9000, "DI"),
    # An rs-named SNV call at the P/LP locus the first i-probe shares.
    ("rs900951001", "2", 1000, "AG"),
]


def _clinvar(data: Path, rows: list[tuple[str, str, int, str, str, str]]) -> None:
    for build in ("GRCh37", "GRCh38"):
        with contextlib.closing(sqlite3.connect(data / clinvar_db_filename(build))) as conn:
            conn.executescript(CLINVAR_SCHEMA)
            conn.executemany(
                "INSERT INTO clinvar_variants (rsid, chromosome, position, ref, alt, "
                "clinical_significance, condition, gene, review_status, allele_id, aggregate, "
                "submitters_same, submitters_total) "
                "VALUES (?, ?, ?, ?, ?, 'Pathogenic', 'Test condition', 'GENE', ?, ?, ?, 1, 1)",
                [
                    (rsid, chrom, pos, ref, alt, _SINGLE, i, aggregate)
                    for i, (rsid, chrom, pos, ref, alt, aggregate) in enumerate(rows, 1)
                ],
            )
            conn.execute(
                "INSERT INTO database_versions VALUES (?, 'test://', '1', '2026-10-10', ?, "
                "NULL, ?)",
                (clinvar_record_name(build), len(rows), f"iv:{CLINVAR_INTERPRETER_VERSION}"),
            )
            conn.commit()


def _array(path: Path, calls: list[tuple[str, str, int, str]]) -> Path:
    # A 23andMe banner, so --format 23andme is a choice, not a forced mismatch.
    lines = [
        "# This data file generated by 23andMe at: Mon Jan 01 00:00:00 2001",
        "# rsid\tchromosome\tposition\tgenotype",
    ]
    lines += [f"{rsid}\t{chrom}\t{pos}\t{gt}" for rsid, chrom, pos, gt in calls]
    path.write_text("\n".join(lines) + "\n")
    return path


def _analyze(data: Path, input_path: Path, out: Path, *extra: str) -> str:
    result = CliRunner(env={"COLUMNS": "300"}).invoke(
        main,
        [
            "analyze",
            str(input_path),
            "--build",
            "grch37",
            "--no-update",
            "--data-dir",
            str(data),
            "--output",
            str(out),
            *extra,
        ],
    )
    assert result.exit_code == 0, result.output
    return result.output


@pytest.fixture
def data(tmp_path: Path) -> Path:
    d = tmp_path / "data"
    d.mkdir()
    _clinvar(d, _ROWS)
    return d


class TestClinVarCounts:
    def test_counts_from_one_run(self, tmp_path: Path, data: Path) -> None:
        array = _array(tmp_path / "a.txt", _CALLS)
        clinvar = ClinVarAnnotator(data, builds=("GRCh37",))
        with clinvar:
            run_analysis(array, TwentyThreeAndMeParser(), [clinvar], build_override="GRCh37")
        assert clinvar.run_counts() == {
            "unrecognised_rows": 0,
            "trimmed_matches": 0,
            "i_probes_at_plp_loci": 1,
            "di_calls_at_plp_rsids": 2,
            "ref_mismatches": 0,
        }

    def test_the_single_call_path_counts_too(self, tmp_path: Path, data: Path) -> None:
        clinvar = ClinVarAnnotator(data, builds=("GRCh37",))
        variants = list(TwentyThreeAndMeParser().parse(_array(tmp_path / "a.txt", _CALLS)))
        with clinvar:
            for v in variants:
                clinvar.annotate(v)
        counts = clinvar.run_counts()
        assert (counts["i_probes_at_plp_loci"], counts["di_calls_at_plp_rsids"]) == (1, 2)

    def test_an_annotator_counts_nothing_by_default(self, data: Path) -> None:
        assert PharmGKBAnnotator(data).run_counts() == {}


class TestReport:
    def test_json_input_block(self, tmp_path: Path, data: Path) -> None:
        out = tmp_path / "r.json"
        _analyze(data, _array(tmp_path / "a.txt", _CALLS), out, "--format", "23andme")
        block = json.loads(out.read_text())["input"]
        assert block["array_quality"] == {
            "di_calls": 4,
            "unreadable_genotypes": 0,
            "not_genotyped": 0,
            "wrong_column_rows": 0,
        }
        assert block["probe_classes"] == {"i_probes_at_plp_loci": 1, "di_calls_at_plp_rsids": 2}

    def test_console_and_html_say_so(self, tmp_path: Path, data: Path) -> None:
        html = tmp_path / "r.html"
        output = _analyze(data, _array(tmp_path / "a.txt", _CALLS), html, "--format", "23andme")
        expected = [
            "1 vendor probe(s) without an rsID (such as i5000123) sit where ClinVar "
            "classifies the variant as Pathogenic or Likely pathogenic.",
            "4 call(s) are written as D or I (a deletion or an insertion), which Allelix "
            "cannot match to ClinVar; 2 of them at rsIDs ClinVar classifies as Pathogenic "
            "or Likely pathogenic.",
        ]
        page = html.read_text()
        for text in expected:
            assert text in output
            assert text in page

    def test_vcf_input_has_neither(self, tmp_path: Path, data: Path) -> None:
        vcf = tmp_path / "s.vcf"
        vcf.write_text(
            "##fileformat=VCFv4.2\n"
            '##FORMAT=<ID=GT,Number=1,Type=String,Description="Genotype">\n'
            "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tS1\n"
            "2\t1000\trs900951001\tG\tA\t50\tPASS\t.\tGT\t0/1\n"
        )
        out = tmp_path / "r.json"
        _analyze(data, vcf, out)
        block = json.loads(out.read_text())["input"]
        assert (block["array_quality"], block["probe_classes"]) == (None, None)


class TestProbeClassesNeedClinVar:
    def test_none_without_clinvar(self) -> None:
        assert _probe_classes(None, {}, "GRCh37") is None

    def test_none_when_clinvar_does_not_serve_the_build(self, data: Path) -> None:
        clinvar = ClinVarAnnotator(data, builds=("GRCh38",))
        assert _probe_classes(clinvar, clinvar.run_counts(), "GRCh37") is None

    def test_lines_without_probe_classes_give_the_total_only(self) -> None:
        assert array_quality_lines(ArrayInputStats(di_calls=3), None) == [
            "3 call(s) are written as D or I (a deletion or an insertion), which Allelix "
            "cannot match to ClinVar."
        ]
        assert array_quality_lines(ArrayInputStats(), {"i_probes_at_plp_loci": 0}) == []
        assert array_quality_lines(None, None) == []


class _CountingParser(TwentyThreeAndMeParser):
    """A parser that keeps its own counts (ADR-0051: JSON records them)."""

    def __init__(self) -> None:
        self._stats = ArrayInputStats()

    def input_stats(self) -> ArrayInputStats:
        return self._stats

    def parse(self, file_path: Path) -> Iterator[Variant]:
        self._stats = ArrayInputStats(unreadable_genotypes=5, wrong_column_rows=2)
        yield from super().parse(file_path)


def test_the_parsers_own_counts_are_kept(tmp_path: Path, data: Path) -> None:
    array = _array(tmp_path / "a.txt", _CALLS)
    with ClinVarAnnotator(data, builds=("GRCh37",)) as clinvar:
        result = run_analysis(array, _CountingParser(), [clinvar], build_override="GRCh37")
    assert result.array_quality == ArrayInputStats(
        di_calls=4, unreadable_genotypes=5, wrong_column_rows=2
    )
