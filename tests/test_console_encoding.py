"""Output to a console or pipe that is not UTF-8 degrades instead of crashing.

`analyze` to a cp1252 pipe or redirect (Windows' legacy encoding) crashed
with UnicodeEncodeError on a character the stream cannot encode, such as the
plausibility marker "○". At CLI start-up, a stdout or stderr that is not
UTF-8 and would raise is switched to replace such a character. Reports and
other files are written as UTF-8 and are unaffected. Synthetic data only.
"""

from __future__ import annotations

import contextlib
import io
import os
import sqlite3
import subprocess
import sys
from pathlib import Path

import pytest

from allelix.databases._versions import CLINVAR_INTERPRETER_VERSION
from allelix.databases.schema import CLINVAR_SCHEMA

_REPO = Path(__file__).resolve().parents[1]

_GENOME = (
    "# This data file generated by 23andMe at: Mon Jun 01 00:00:00 2020\n"
    "# We are using reference human assembly build 37 (also known as Annotation Release 104).\n"
    "# rsid\tchromosome\tposition\tgenotype\n"
    "rs1801133\t1\t11856378\tAG\n"
    "rs4680\t22\t19951271\tAG\n"
)


@pytest.fixture
def inputs(tmp_path):
    data = tmp_path / "data"
    data.mkdir()
    for build in ("GRCh37", "GRCh38"):
        with contextlib.closing(sqlite3.connect(data / f"clinvar.{build}.sqlite")) as conn:
            conn.executescript(CLINVAR_SCHEMA)
            conn.execute(
                "INSERT INTO clinvar_variants (rsid, chromosome, position, ref, alt, "
                "clinical_significance, condition, gene, review_status, allele_id) "
                "VALUES ('rs1801133', '1', 11856378, 'G', 'A', 'Pathogenic', 'x', 'MTHFR', "
                "'criteria provided, single submitter', 1)"
            )
            conn.execute(
                "INSERT INTO database_versions (name, source_url, version, downloaded_at, "
                "record_count, remote_signal, local_version_tag) "
                "VALUES (?, 'test://', '20260101', '2026-01-01', 1, 'md5:0', ?)",
                (f"clinvar.{build}", f"iv:{CLINVAR_INTERPRETER_VERSION}"),
            )
            conn.commit()
    genome = tmp_path / "genome.txt"
    genome.write_text(_GENOME)
    return data, genome


def _allelix(*args: str, encoding: str) -> subprocess.CompletedProcess[bytes]:
    env = {**os.environ, "PYTHONPATH": str(_REPO), "PYTHONIOENCODING": encoding}
    code = (
        "import sys; from allelix.cli import main; sys.argv = ['allelix', *sys.argv[1:]]; main()"
    )
    return subprocess.run(
        [sys.executable, "-c", code, *args], capture_output=True, env=env, timeout=120, check=False
    )


@pytest.mark.parametrize("encoding", ["cp1252", "ascii"])
def test_analyze_to_a_legacy_pipe_does_not_crash(inputs, encoding):
    data, genome = inputs

    result = _allelix(
        "analyze", str(genome), "--data-dir", str(data), "--no-update", encoding=encoding
    )

    assert result.returncode == 0, result.stderr.decode(encoding, "replace")
    assert b"UnicodeEncodeError" not in result.stderr
    assert b"rs1801133" in result.stdout


def test_a_report_file_is_still_utf8(inputs, tmp_path):
    data, genome = inputs
    out = tmp_path / "r.json"

    result = _allelix(
        "analyze",
        str(genome),
        "--data-dir",
        str(data),
        "--no-update",
        "--output",
        str(out),
        encoding="cp1252",
    )

    assert result.returncode == 0, result.stderr
    out.read_bytes().decode("utf-8")


def _replace_unencodable_output(stream: object) -> None:
    from allelix.cli import _replace_unencodable_output as replace

    replace(stream)


def _stream(encoding: str, errors: str = "strict") -> io.TextIOWrapper:
    return io.TextIOWrapper(io.BytesIO(), encoding=encoding, errors=errors)


def test_a_strict_legacy_stream_replaces_what_it_cannot_encode():
    stream = _stream("cp1252")

    _replace_unencodable_output(stream)
    stream.write("○ ✓ café")
    stream.flush()

    assert stream.errors == "replace"
    assert stream.buffer.getvalue() == "? ? café".encode("cp1252")  # type: ignore[attr-defined]


@pytest.mark.parametrize(
    ("encoding", "errors"),
    [
        ("utf-8", "strict"),
        ("UTF8", "strict"),
        ("cp1252", "ignore"),
        ("cp1252", "backslashreplace"),
    ],
)
def test_a_utf8_stream_or_a_chosen_error_mode_is_left_alone(encoding, errors):
    stream = _stream(encoding, errors)

    _replace_unencodable_output(stream)

    assert stream.errors == errors


def test_a_stream_that_cannot_be_reconfigured_is_left_alone():
    class Plain:
        encoding = "cp1252"
        errors = "strict"

    _replace_unencodable_output(Plain())  # no reconfigure(): nothing to do, no error
