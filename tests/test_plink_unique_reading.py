"""PLINK uses the unique forward or complement reading of a coding pair."""

import contextlib
import re
import sqlite3
from collections import Counter
from itertools import product
from pathlib import Path

import pytest
from click.testing import CliRunner
from test_annotation_parity_and_named_disclosures import _identity
from test_plink_record_coding import _decode_one_sample_bed, create_cache

from allelix.cli import main
from allelix.exporters.plink import export_plink, plink_record_key
from allelix.models import Variant

COMPLEMENT = dict(zip("ACGT", "TGCA", strict=True))
CALLS = [(a, b, False) for a, b in product("ACGT", repeat=2)] + [(a, a, True) for a in "ACGT"]


@pytest.mark.parametrize("pair", ("AG", "AC", "CT", "GT"))
@pytest.mark.parametrize("a,b,haploid", CALLS)
@pytest.mark.parametrize("build", ("GRCh37", "GRCh38"))
@pytest.mark.parametrize("record_keyed", (False, True))
def test_unique_reading_is_written_as_the_pair_alleles(
    tmp_path, pair, a, b, haploid, build, record_keyed
):
    variant = Variant("rs3999980201", "1", 1000201, a, b, build=build, haploid=haploid)
    original = (variant.allele1, variant.allele2, variant.haploid)
    coding = tuple(pair)
    direct = {a, b} <= set(pair)
    reverse = {COMPLEMENT[a], COMPLEMENT[b]} <= set(pair)
    # A biallelic non-palindromic pair and its complement are disjoint:
    # both readings cannot fit a valid nonempty call in this scope.
    assert not (direct and reverse)
    expected = (a, b) if direct else (COMPLEMENT[a], COMPLEMENT[b])
    if direct == reverse:
        expected = (".", ".")
    prefix = tmp_path / "calls"
    kwargs = (
        {"record_alleles": {plink_record_key(variant): coding}}
        if record_keyed
        else {"ref_alt_map": {variant.rsid: coding}}
    )
    counts = export_plink(iter([variant]), prefix, build, **kwargs)
    assert _decode_one_sample_bed(prefix) == Counter({tuple(sorted(expected)): 1})
    assert counts.written == 1
    assert counts.allele_mismatches == int(direct == reverse)
    assert Path(str(prefix) + ".bim").read_text().split()[4:6] == list(pair)
    assert (variant.allele1, variant.allele2, variant.haploid) == original


@pytest.mark.parametrize("build", ("GRCh37", "GRCh38"))
@pytest.mark.parametrize("reverse_order", (False, True))
@pytest.mark.parametrize("haploid", (False, True))
def test_cli_counts_complemented_calls_and_preserves_direct_calls(
    tmp_path, build, reverse_order, haploid
):
    data = tmp_path / "data"
    cache = create_cache(data)
    rows = [
        ("rs3999980201", 1000201, "TT"),
        ("rs3999980202", 1000202, "CC"),
        ("rs3999980203", 1000203, "AA"),
    ]
    _identity(data, [(rs, "1", pos, "G", "A", pos, "G", "A", 0) for rs, pos, _ in rows])
    with contextlib.closing(sqlite3.connect(cache)) as conn:
        conn.execute("DELETE FROM gnomad_frequencies")
        conn.executemany(
            "INSERT INTO gnomad_frequencies (chrom,pos,ref,alt,rsid,af) VALUES (?,?,?,?,?,?)",
            [("1", pos, "G", "A", rs, 0.2) for rs, pos, _ in rows],
        )
        conn.commit()
    if reverse_order:
        rows.reverse()
    source = tmp_path / "synthetic.txt"
    source.write_text(
        "# This data file generated by 23andMe\n"
        + f"# Reference human assembly {build}\n"
        + "# rsid\tchromosome\tposition\tgenotype\n"
        + "".join(f"{rs}\t1\t{pos}\t{call[:1] if haploid else call}\n" for rs, pos, call in rows)
    )
    prefix = tmp_path / "export"
    result = CliRunner().invoke(
        main,
        [
            "export",
            "plink",
            str(source),
            "--build",
            build.lower(),
            "--data-dir",
            str(data),
            "--output-prefix",
            str(prefix),
        ],
    )
    assert result.exit_code == 0, result.output
    assert _decode_one_sample_bed(prefix) == Counter({("A", "A"): 2, ("G", "G"): 1})
    assert re.search(
        r"(?:\b2\s+(?:\S+\s+){0,4}complement\w*|complement\w*[^\n\d]*\b2\b)",
        result.output,
        re.I,
    ), result.output


@pytest.mark.parametrize("pair", ("AT", "CG"))
@pytest.mark.parametrize("shape", ("first", "second", "heterozygous"))
@pytest.mark.parametrize("build", ("GRCh37", "GRCh38"))
def test_existing_palindromic_fallback_stays_outside_unique_pair_coding(
    tmp_path, pair, shape, build
):
    a, b = pair if shape == "heterozygous" else (pair[shape == "second"],) * 2
    variant = Variant("rs3999980201", "1", 1000201, a, b, build=build)
    prefix = tmp_path / "palindromic"
    counts = export_plink(iter([variant]), prefix, build, {variant.rsid: tuple(pair)})
    assert _decode_one_sample_bed(prefix) == Counter({tuple(sorted((a, b))): 1})
    assert counts.allele_mismatches == 0
