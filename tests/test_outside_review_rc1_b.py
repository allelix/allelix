# ── R1-05 (minor, new in 2.6.1): one D/I row of an rsID list is named twice ──

RS_L = "rs3999261031"
POS_L = 1261031


def test_r1_05_di_row_of_an_rsid_list_is_named_once(tmp_path):
    """One D/I row of an rsID and genotype list at a P/LP rsID is one site that could
    not be checked. RC1 names it twice (``di_call`` and ``unplaced``), so the console
    says "2 ... site(s) could not be checked", and the ``unplaced`` text says the
    rsID-keyed sources are not affected, which ADR-0070 denies for a D/I call.
    Fails on RC1, passes on 2.6.0.
    """
    data = tmp_path / "data"
    _config(data)
    for build in BUILDS:
        _clinvar(data, build, [(RS_L, "1", POS_L, "CTT", "C", "GENEL", "Pathogenic",
                                "Pathogenic")])  # fmt: skip
    _identity(
        data,
        [
            (RS_L, "1", POS_L, "CTT", "C", POS_L, "CTT", "C", 0),
            ("rs3999261032", "1", POS_L + 5, "A", "G", POS_L + 5, "A", "G", 0),
        ],
    )
    source = tmp_path / "list.txt"
    source.write_text(f"{RS_L}\tDI\nrs3999261032\tAG\nrs3999261033\tAG\n")
    report, output = _analyze(tmp_path, data, source, None)
    entries = [e for e in report.get("high_value_unchecked") or [] if e["rsid"] == RS_L]
    assert len(entries) == 1, ([(e["reason"], e["message"]) for e in entries], output)


# ── R1-06 (minor, new in 2.6.1): the foreign-allele notice claims another ──
# ── variant is at the position when none is ──────────────────────────────

RS_F = "rs3999261041"
POS_F = 1261041


@pytest.mark.parametrize("build", BUILDS)
def test_r1_06_foreign_allele_text_claims_another_variant_that_is_not_there(tmp_path, build):
    """ClinVar holds only rsF's own G>A Pathogenic row at the position. A ``CC`` call
    is abstained (correctly: it may be ``GG`` on the other strand), but the notice
    says "another variant at that position would have been taken for it", and the
    Note says "another variant at that position would be mistaken for theirs":
    there is no other variant. Fails on RC1; 2.6.0 has no such notice (passes).
    """
    data = tmp_path / "data"
    _config(data)
    _clinvar(data, build, [(RS_F, "1", POS_F, "G", "A", "GENEF", "Pathogenic", "Pathogenic")])
    _identity(data, [(RS_F, "1", POS_F, "G", "A", POS_F, "G", "A", 0)])
    source = _chip(tmp_path / "chip.txt", [(RS_F, "1", POS_F, "CC")], build=build)
    report, output = _analyze(tmp_path, data, source, build)
    texts = [e["message"] for e in report.get("high_value_unchecked") or []]
    assert not [t for t in texts if "another variant" in t], texts
    assert "another variant at that position" not in output, output


# ── R1-07 (minor, new in 2.6.1): the HTML banner says the report says nothing ──
# ── about a 23andMe i-probe it does report (SNPedia) ──────────────────────

RS_P, PROBE_P = "rs3999261051", "i3999261050"
POS_P = 1261050


def test_r1_07_html_banner_says_nothing_is_reported_about_a_probe_snpedia_reports(tmp_path):
    """A 23andMe ``i`` probe ``DI`` call at a ClinVar P/LP locus is named in the HTML
    banner "High-value sites not checked ... so the report says nothing about them",
    while the same report shows SNPedia's finding for that probe's own page.
    Fails on RC1; 2.6.0 named no probe (passes).
    """
    import html as html_lib
    import re

    from allelix.databases.snpedia_parser import _PARSER_VERSION

    data = tmp_path / "data"
    data.mkdir()
    on = {"clinvar", "rsid_identity", "snpedia"}
    (data / "config.toml").write_text(
        "[sources]\n" + "".join(f"{s} = {'true' if s in on else 'false'}\n" for s in SOURCES)
    )
    _clinvar(data, "GRCh37", [(RS_P, "1", POS_P, "CTT", "C", "GENEP", "Pathogenic",
                               "Pathogenic")])  # fmt: skip
    _identity(data, [(RS_P, "1", POS_P, "CTT", "C", POS_P, "CTT", "C", 0)])
    with contextlib.closing(sqlite3.connect(data / "snpedia.sqlite")) as conn:
        conn.executescript(
            "CREATE TABLE snpedia_genotypes (rsid TEXT NOT NULL, allele1 TEXT NOT NULL, "
            "allele2 TEXT NOT NULL, magnitude REAL, repute TEXT, summary TEXT, gene TEXT, "
            "orientation TEXT, scraped_at TEXT);"
            "CREATE TABLE database_versions (name TEXT PRIMARY KEY, source_url TEXT NOT NULL, "
            "version TEXT, downloaded_at TEXT NOT NULL, record_count INTEGER NOT NULL, "
            "remote_signal TEXT, local_version_tag TEXT);"
        )
        conn.execute(
            "INSERT INTO snpedia_genotypes VALUES (?, 'D', 'I', 4.0, 'Bad', "
            "'carrier of a synthetic deletion', 'GENEP', 'plus', '2026-10-10T00:00:00')",
            (PROBE_P,),
        )
        conn.execute(
            "INSERT INTO database_versions VALUES ('snpedia', 'test://snpedia', 'test', "
            "'2026-10-10T00:00:00Z', 1, '', ?)",
            (f"pv:{_PARSER_VERSION}",),
        )
        conn.commit()
    source = _chip(tmp_path / "chip.txt", [(PROBE_P, "1", POS_P, "DI")], build="GRCh37")
    out = tmp_path / "report.html"
    result = CliRunner(env={"COLUMNS": "500"}).invoke(
        main,
        ["analyze", str(source), "--build", "grch37", "--data-dir", str(data), "--no-update",
         "--output", str(out)],
    )  # fmt: skip
    assert result.exit_code == 0, result.output
    raw = re.sub(r"<(script|style)\b[^>]*>.*?</\1>", "", out.read_text(), flags=re.S | re.I)
    visible = html_lib.unescape(re.sub(r"<[^>]+>", " ", raw))
    banner = visible[visible.find("High-value sites not checked") :][:600]
    if PROBE_P in banner and "carrier of a synthetic deletion" in visible:
        assert "says nothing about them" not in banner, banner
