# ── synthetic caches and inputs (same shapes as the repository's own tests) ──


def _clinvar(data: Path, build: str, rows) -> None:
    """Rows: rsid, chrom, pos, ref, alt, gene, classification, aggregate."""
    data.mkdir(exist_ok=True)
    with contextlib.closing(sqlite3.connect(data / clinvar_db_filename(build))) as conn:
        conn.executescript(CLINVAR_SCHEMA)
        for i, (rsid, chrom, pos, ref, alt, gene, sig, aggregate) in enumerate(rows):
            conn.execute(
                "INSERT INTO clinvar_variants (rsid,chromosome,position,ref,alt,gene,"
                "clinical_significance,condition,review_status,allele_id,aggregate,"
                "submitters_same,submitters_total) VALUES (?,?,?,?,?,?,?,'Synthetic condition',"
                "'criteria provided, single submitter',?,?,1,1)",
                (rsid, chrom, pos, ref, alt, gene, sig, 900261000 + i, aggregate),
            )
        conn.execute(
            "INSERT INTO database_versions (name,source_url,version,downloaded_at,"
            "record_count,local_version_tag) VALUES (?, 'test://synthetic', 'synthetic', "
            "'2001-01-01', ?, ?)",
            (clinvar_record_name(build), len(rows), f"iv:{CLINVAR_INTERPRETER_VERSION}"),
        )
        conn.commit()


def _identity(data: Path, rows) -> None:
    """Rows: rsid, chrom, pos37, ref37, alt37, pos38, ref38, alt38, palindromic."""
    data.mkdir(exist_ok=True)
    write_identity_db(
        rows,
        data / RSID_IDENTITY_DB_FILENAME,
        version="synthetic",
        source_url="test://identity",
        downloaded_at="2001-01-01",
    )


def _config(data: Path, *, identity: bool = True) -> None:
    data.mkdir(exist_ok=True)
    on = {"clinvar", "rsid_identity"} if identity else {"clinvar"}
    (data / "config.toml").write_text(
        "[sources]\n" + "".join(f"{s} = {'true' if s in on else 'false'}\n" for s in SOURCES)
    )


def _chip(path: Path, calls, *, build: str, kind: str = "23andme") -> Path:
    if kind == "23andme":
        path.write_text(
            "# This data file generated by 23andMe at: synthetic\n"
            f"# Reference human assembly {build}\n"
            "# rsid\tchromosome\tposition\tgenotype\n"
            + "".join(f"{rsid}\t{chrom}\t{pos}\t{gt}\n" for rsid, chrom, pos, gt in calls)
        )
    else:
        path.write_text(
            "#AncestryDNA raw data download\nrsid\tchromosome\tposition\tallele1\tallele2\n"
            + "".join(
                f"{rsid}\t{chrom}\t{pos}\t{gt[0]}\t{gt[1]}\n" for rsid, chrom, pos, gt in calls
            )
        )
    return path


def _analyze(tmp_path: Path, data: Path, source: Path, build: str | None):
    out = tmp_path / "report.json"
    args = ["analyze", str(source), "--data-dir", str(data), "--no-update", "--output", str(out)]
    if build is not None:
        args += ["--build", build.lower()]
    result = CliRunner(env={"COLUMNS": "500"}).invoke(main, args)
    assert result.exit_code == 0, (result.output, result.exception)
    return json.loads(out.read_text()), result.output


def _clinvar_findings(report):
    return [
        (a["rsid"], a["genotype_match"], a["significance"])
        for a in report["annotations"]
        if a["source"] == "clinvar"
    ]


def _named(report):
    return [(e["rsid"], e["reason"]) for e in report.get("high_value_unchecked") or []]


# ── R1-01 (P1, pre-existing): the guard still fires when the call's rsID has no ──
# ── SNV row in the identity table ─────────────────────────────────────────

RSA, RSB = "rs3999261001", "rs3999261002"
POS_A = 1261001


@pytest.mark.parametrize("build", BUILDS)
@pytest.mark.parametrize("identity_case", ["rsid_absent", "identity_off", "indel_only"])
def test_r1_01_call_of_another_rsid_still_gets_its_pathogenic_row(tmp_path, build, identity_case):
    """A ``CC`` chip call for rsA (G/A in ClinVar itself) must not be reported as rsB's
    Pathogenic G>C finding.

    RC1 abstains only when the identity table holds an SNV row of rsA at the
    locus. When it does not (rsA missing from the table, the table switched off, or
    rsA indel-only there), ClinVar still matches the call to rsB's row, although
    ClinVar's own rows say rsA's alleles there are G and A. Fails on RC1 and 2.6.0.
    """
    data = tmp_path / "data"
    _config(data, identity=identity_case != "identity_off")
    _clinvar(
        data,
        build,
        [
            (RSA, "1", POS_A, "G", "A", "GENEA", "Benign", "Benign"),
            (RSB, "1", POS_A, "G", "C", "GENEB", "Pathogenic", "Pathogenic"),
        ],
    )
    rows = [(RSB, "1", POS_A, "G", "C", POS_A, "G", "C", 1)]
    if identity_case == "indel_only":
        rows.append((RSA, "1", POS_A, "G", "GT", POS_A, "G", "GT", 0))
    if identity_case != "identity_off":
        _identity(data, rows)
    source = _chip(tmp_path / "chip.txt", [(RSA, "1", POS_A, "CC")], build=build)
    report, output = _analyze(tmp_path, data, source, build)
    assert not [f for f in _clinvar_findings(report) if f[2] == "clinvar_pathogenic"], (
        _clinvar_findings(report),
        output,
    )


RSG_A, RSG_B = "rs3999261061", "rs3999261062"
POS_G = 1261061


def test_r1_01b_gnomad_ref_lets_another_rsids_row_match_a_chip_call(tmp_path):
    """GRCh38: rsA is a common G/A SNP that neither ClinVar nor the identity table
    (restricted to the annotators' rsIDs) holds; gnomAD has it at the locus. gnomAD
    fills REF G (``_populate_ref_from_gnomad``, after the identity step that sets
    ``foreign_alleles``), so ClinVar's REF check passes and the ``CC`` call takes
    rsB's Pathogenic G>C row, reported under rsA's own ID. Fails on RC1 and 2.6.0.
    """
    from allelix.databases._versions import GNOMAD_SCHEMA_VERSION
    from allelix.databases.schema import GNOMAD_SCHEMA

    data = tmp_path / "data"
    data.mkdir()
    on = {"clinvar", "rsid_identity", "gnomad"}
    (data / "config.toml").write_text(
        "[sources]\n" + "".join(f"{s} = {'true' if s in on else 'false'}\n" for s in SOURCES)
    )
    _clinvar(data, "GRCh38", [(RSG_B, "1", POS_G, "G", "C", "GENEB", "Pathogenic",
                               "Pathogenic")])  # fmt: skip
    _identity(data, [(RSG_B, "1", POS_G, "G", "C", POS_G, "G", "C", 0)])
    with contextlib.closing(sqlite3.connect(data / "gnomad.sqlite")) as conn:
        conn.executescript(GNOMAD_SCHEMA)
        conn.execute(
            "INSERT INTO gnomad_frequencies (chrom,pos,ref,alt,rsid,af) VALUES ('1',?,?,?,?,?)",
            (POS_G, "G", "A", RSG_A, 0.3),
        )
        conn.execute(
            "INSERT INTO database_versions (name,source_url,version,downloaded_at,"
            "record_count,local_version_tag) VALUES ('gnomad', 'test://synthetic', "
            "'synthetic', '2001-01-01', 1, ?)",
            (f"sv:{GNOMAD_SCHEMA_VERSION}",),
        )
        conn.commit()
    source = _chip(tmp_path / "chip.txt", [(RSG_A, "1", POS_G, "CC")], build="GRCh38")
    report, output = _analyze(tmp_path, data, source, "GRCh38")
    assert not [f for f in _clinvar_findings(report) if f[2] == "clinvar_pathogenic"], (
        _clinvar_findings(report),
        output,
    )


# ── R1-02 (P1, new in 2.6.1): the call's own rsID's P/LP allele is hidden ────
# ── when the identity table does not list that allele ─────────────────────

RSO = "rs3999261003"
POS_O = 1261003


@pytest.mark.parametrize("build", BUILDS)
@pytest.mark.parametrize("kind", ["23andme", "ancestrydna"])
def test_r1_02_own_rsids_pathogenic_allele_is_hidden(tmp_path, build, kind):
    """A ``GT`` call at rsO, whose own ClinVar row is G>T Pathogenic, is that finding.

    The identity table (a pinned dbSNP snapshot) lists rsO as G/A only. RC1 marks the
    call ``foreign_alleles`` and ClinVar does not match it, although the matching
    row is the call's own rsID (no other rsID is at the locus, and G/T fits no
    strand reading of G/A, so nothing is ambiguous). 2.6.0 reported it. Fails on
    RC1, passes on 2.6.0.
    """
    data = tmp_path / "data"
    _config(data)
    _clinvar(data, build, [(RSO, "1", POS_O, "G", "T", "GENEO", "Pathogenic", "Pathogenic")])
    _identity(data, [(RSO, "1", POS_O, "G", "A", POS_O, "G", "A", 0)])
    source = _chip(tmp_path / "chip.txt", [(RSO, "1", POS_O, "GT")], build=build, kind=kind)
    report, output = _analyze(tmp_path, data, source, build)
    assert (RSO, "GT", "clinvar_pathogenic") in _clinvar_findings(report), (
        _clinvar_findings(report),
        _named(report),
        output,
    )


# ── R1-03 (P2, pre-existing): a chip call at a P/LP position whose rsID ────
# ── neither ClinVar nor the identity table holds is neither checked nor named ──

RS_OLD, RS_NEW = "rs3999261011", "rs3999261012"
POS_N = 1261011


@pytest.mark.parametrize("build", BUILDS)
def test_r1_03_unknown_rsid_call_at_a_plp_position_is_not_named(tmp_path, build):
    """An ``AA`` call under a merged/unknown rsID at the exact position of a ClinVar
    Pathogenic G>A row is not checked by ClinVar (no REF, rsID unknown), and 2.6.1
    names a vendor probe in exactly that situation, but not this call: it is not
    counted, not named, nothing is said. Fails on RC1 and 2.6.0.
    """
    data = tmp_path / "data"
    _config(data)
    _clinvar(data, build, [(RS_NEW, "1", POS_N, "G", "A", "GENEN", "Pathogenic", "Pathogenic")])
    _identity(data, [(RS_NEW, "1", POS_N, "G", "A", POS_N, "G", "A", 0)])
    source = _chip(
        tmp_path / "chip.txt",
        [(RS_OLD, "1", POS_N, "AA"), ("i3999261013", "1", POS_N, "AA")],
        build=build,
    )
    report, output = _analyze(tmp_path, data, source, build)
    named = {rsid for rsid, _reason in _named(report)}
    # Control: the vendor probe at the same position is named (RC1).
    assert RS_OLD in named, (named, output)


