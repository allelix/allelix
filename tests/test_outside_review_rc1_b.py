@pytest.mark.parametrize("indel", INDELS, ids=lambda i: i[1])
def test_r1_04_vendor_probe_di_call_at_chip_coordinate_is_not_named(tmp_path, indel):
    """A 23andMe ``i`` probe ``DI`` call for a ClinVar Pathogenic indel is named only
    when the probe's position equals ClinVar's row position. At the chip coordinate
    (the first changed base, as the repository's own fixture writes these calls) it
    is not named, while an rsID D/I call at the same coordinate is. Fails on RC1
    (and on 2.6.0, which names no vendor probe at all).
    """
    rsid, gene, chrom, chip_pos, clinvar_pos, ref, alt = indel
    data = tmp_path / "data"
    _config(data)
