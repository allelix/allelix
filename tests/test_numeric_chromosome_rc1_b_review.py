from test_annotation_parity_and_named_disclosures import _clinvar, _identity, _vcf

from allelix.cli import main

if TYPE_CHECKING:
    from pathlib import Path

SOURCES = (
    "clinvar",
    "pharmgkb",
    "snpedia",
    "gwas",
    "gnomad",
    "cadd",
    "alphamissense",
    "rsid_identity",
)


def _config(enabled=()):
    return "[sources]\n" + "".join(f"{n} = {str(n in enabled).lower()}\n" for n in SOURCES)


def _rows(output: str) -> list[str]:
    return [" ".join(line.replace("│", " ").split()) for line in output.splitlines()]


def _chip(path: Path, reader: str, rows) -> Path:
    if reader == "myhappygenes":
        text = "# MyHappyGenes\nSNP Name\tChr\tPosition\tAllele1 - Forward\tAllele2 - Forward\n"
        text += "".join(f"{r}\t{c}\t{p}\t{g[0]}\t{g[1]}\n" for r, c, p, g in rows)
    else:
        assert reader == "23andme"
        text = (
            "# This data file generated by 23andMe at: synthetic\n"
            "# rsid\tchromosome\tposition\tgenotype\n"
        )
        text += "".join(f"{r}\t{c}\t{p}\t{g}\n" for r, c, p, g in rows)
    path.write_text(text)
    return path


UNKNOWN_ROWS = [
    ("rs9263100001", "1", 3000001, "GA"),
    ("rs9263100002", "0", 5001, "GA"),
    ("rs9263100003", "chr0", 5002, "GA"),
    ("rs9263100004", "chrUn_gl000220", 5003, "GA"),
    ("rs9263100005", "chrGL000192.1", 5004, "GA"),
]


# ---------------------------------------------------------------------------
# B-01: CHANGELOG says "`0` and other contigs are unchanged, in lookups and in
# outputs". For the readers that keep the file's chromosome name (23andMe,
# MyHappyGenes, MyHeritage, LivingDNA, FTDNA CSV, Genes for Good, AncestryDNA),
# 2.6.3rc1's `stats` and `compare` per-chromosome tables strip the chr prefix
# from unknown contigs and merge `chr0` into `0`. 2.6.2 listed them as written.
# ---------------------------------------------------------------------------


@pytest.mark.parametrize("reader", ["myhappygenes", "23andme"])
def test_b01_stats_lists_unknown_contigs_as_2_6_2_did(tmp_path, reader):
    data = tmp_path / "data"
    data.mkdir()
    (data / "config.toml").write_text(_config())
    src = _chip(tmp_path / "chip.txt", reader, UNKNOWN_ROWS)
    result = CliRunner().invoke(
        main, ["stats", str(src), "--build", "grch38", "--data-dir", str(data)]
    )
    assert result.exit_code == 0, result.output
    rows = _rows(result.output)
    # 2.6.2: each name as the file writes it, one call each
    for name in ("0", "chr0", "chrUn_gl000220", "chrGL000192.1"):
        assert f"{name} 1" in rows, (name, result.output)


@pytest.mark.parametrize("reader", ["myhappygenes", "23andme"])
def test_b01_compare_lists_unknown_contigs_as_2_6_2_did(tmp_path, reader):
    src = _chip(tmp_path / "chip.txt", reader, UNKNOWN_ROWS)
    result = CliRunner().invoke(
        main, ["compare", str(src), str(src), "--build1", "grch38", "--build2", "grch38"]
    )
    assert result.exit_code == 0, result.output
    rows = _rows(result.output)
    for name in ("0", "chr0", "chrUn_gl000220", "chrGL000192.1"):
        assert any(r.startswith(f"{name} 1 0 0 0 0") for r in rows), (name, result.output)


# ---------------------------------------------------------------------------
# B-02: a VCF whose header declares the pseudo-autosomal contig (`XY` or `25`)
# with a length other than X's full length now stops with "unsupported
# assembly" under --build auto, although every other contig matches GRCh38.
# 2.6.2 ignored that contig and ran on GRCh38.
# ---------------------------------------------------------------------------

GRCH38_LENGTHS = {
    "1": 248956422, "2": 242193529, "3": 198295559, "4": 190214555, "5": 181538259,
    "6": 170805979, "7": 159345973, "8": 145138636, "9": 138394717, "10": 133797422,
    "11": 135086622, "12": 133275309, "13": 114364328, "14": 107043718, "15": 101991189,
    "16": 90338345, "17": 83257441, "18": 80373285, "19": 58617616, "20": 64444167,
    "21": 46709983, "22": 50818468, "X": 156040895, "Y": 57227415,
}  # fmt: skip


@pytest.mark.parametrize("par_name", ["XY", "25"])
def test_b02_par_contig_length_does_not_stop_the_build_decision(tmp_path, par_name):
    data = tmp_path / "data"
    data.mkdir()
    (data / "config.toml").write_text(_config(("clinvar", "rsid_identity")))
    _clinvar(
        data,
        "GRCh38",
        [("rs9263000023", "X", 40100001, "G", "A", "SYN", "Pathogenic", "Pathogenic", 1, 1)],
    )
    _identity(data, [("rs9263000023", "X", 40000001, "G", "A", 40100001, "G", "A", 0)])
    src = _vcf(
        tmp_path / "plink_like.vcf", [("rs9263000023", "X", 40100001, "G", "A", "0/1", ".")]
    )
    header = "".join(f"##contig=<ID={c},length={n}>\n" for c, n in GRCH38_LENGTHS.items())
    header += f"##contig=<ID={par_name},length=2781479>\n"  # GRCh38 PAR1 end
    src.write_text(src.read_text().replace("#CHROM", header + "#CHROM", 1))
    out = tmp_path / "r.json"
    result = CliRunner().invoke(
        main, ["analyze", str(src), "--data-dir", str(data), "--no-update", "--output", str(out)]
    )
    assert result.exit_code == 0, result.output
    report = json.loads(out.read_text())
    assert report["input"]["build"] == "GRCh38"
    assert [a["rsid"] for a in report["annotations"]] == ["rs9263000023"]


# ---------------------------------------------------------------------------
# B-03 (pre-existing): `extract` prefers an rsID's call at its placement over a
# call elsewhere, but for the readers that keep the file's chromosome name it
# compares the file's spelling with the placement. Written `23` (or `chrX`,
# `x`), the X call is not "at its placement" and a call at a stale locus is
# printed instead. The same file with `X` prints the placed call.
# ---------------------------------------------------------------------------


@pytest.mark.parametrize("reader", ["myhappygenes", "23andme"])
@pytest.mark.parametrize("spelling", ["23", "chrX", "x"])
def test_b03_extract_choice_does_not_depend_on_chromosome_spelling(tmp_path, reader, spelling):
    data = tmp_path / "data"
    data.mkdir()
    (data / "config.toml").write_text(_config(("rsid_identity",)))
    _identity(data, [("rs9263000023", "X", 40000001, "G", "A", 40100001, "G", "A", 0)])
    shown = {}
    for label, chrom in (("letters", "X"), ("coded", spelling)):
        src = _chip(
            tmp_path / f"{label}.txt",
            reader,
            [("rs9263000023", "1", 5000, "GG"), ("rs9263000023", chrom, 40000001, "GA")],
        )
        result = CliRunner().invoke(
            main,
            [
                "extract",
                str(src),
                "--snps",
                "rs9263000023",
                "--build",
                "grch37",
                "--data-dir",
                str(data),
            ],
        )
        assert result.exit_code == 0, result.output
        (row,) = [r for r in _rows(result.output) if r.startswith("rs9263000023 ")]
        shown[label] = row.split()[2:4]  # position, genotype
    assert shown["letters"] == ["40,000,001", "G/A"]
    assert shown["coded"] == shown["letters"], shown
