"""A D/I code beside a base is still unchecked, including by ClinVar.

Synthetic chip envelopes accept AD, DA, AI and IA. The known base must
not make a source interpret a call that is simultaneously reported as
unchecked. P/LP counting and naming must survive the exclusion. Ordinary
base calls and VCF half calls remain interpretable under their contracts.
"""

from __future__ import annotations

import json

import pytest
from click.testing import CliRunner
from test_probe_classes import _clinvar

from allelix.annotators.clinvar import ClinVarAnnotator
from allelix.cli import main
from allelix.models import Variant

RSID = "rs900951001"
BUILDS = ("GRCh37", "GRCh38")
MIXED = ("AD", "DA", "AI", "IA")


@pytest.fixture
def data(tmp_path):
    directory = tmp_path / "data"
    directory.mkdir()
    _clinvar(directory, [(RSID, "2", 1000, "G", "A", "Pathogenic")])
    return directory


def _annotate(annotator, call, mode):
    if mode == "single":
        return annotator.annotate(call)
    return list(annotator.batch_annotate([call]))


@pytest.mark.parametrize("build", BUILDS)
@pytest.mark.parametrize("gt", MIXED)
@pytest.mark.parametrize("with_ref", (False, True))
@pytest.mark.parametrize("mode", ("single", "batch"))
def test_mixed_base_and_code_is_counted_but_not_annotated(data, build, gt, with_ref, mode):
    call = Variant(RSID, "2", 1000, *gt, build=build, ref="G" if with_ref else None)
    assert call.is_di_call
    with ClinVarAnnotator(data, builds=(build,)) as annotator:
        findings = _annotate(annotator, call, mode)
        assert annotator.run_counts()["di_calls_at_plp_rsids"] == 1
        assert RSID in annotator.di_calls_at_plp()
        assert findings == []


@pytest.mark.parametrize("build", BUILDS)
@pytest.mark.parametrize("mode", ("single", "batch"))
@pytest.mark.parametrize("half", (False, True))
def test_base_and_vcf_half_calls_keep_the_known_alt(data, build, mode, half):
    call = Variant(
        RSID,
        "2",
        1000,
        "-" if half else "G",
        "A",
        build=build,
        ref="G",
        ref_from_input=half,
        input_alt="A" if half else None,
    )
    with ClinVarAnnotator(data, builds=(build,)) as annotator:
        findings = _annotate(annotator, call, mode)
        assert len(findings) == 1
        assert findings[0].source == "clinvar"
        assert annotator.run_counts()["di_calls_at_plp_rsids"] == 0


def _chip(path, gt, kind):
    if kind == "23andme":
        text = (
            "# This data file generated by 23andMe at: synthetic\n"
            "# rsid\tchromosome\tposition\tgenotype\n"
            f"{RSID}\t2\t1000\t{gt}\n"
        )
    else:
        text = (
            "#AncestryDNA raw data download\n"
            "rsid\tchromosome\tposition\tallele1\tallele2\n"
            f"{RSID}\t2\t1000\t{gt[0]}\t{gt[1]}\n"
        )
    path.write_text(text)
    return path


@pytest.mark.parametrize("build", BUILDS)
@pytest.mark.parametrize("gt", MIXED)
@pytest.mark.parametrize("kind", ("23andme", "ancestry"))
@pytest.mark.parametrize("surface", ("json", "html"))
def test_mixed_code_reports_are_unchecked_not_a_finding(tmp_path, data, build, gt, kind, surface):
    path = _chip(tmp_path / "calls.txt", gt, kind)
    output = tmp_path / f"report.{surface}"
    result = CliRunner(env={"COLUMNS": "300"}).invoke(
        main,
        [
            "analyze",
            str(path),
            "--build",
            build.lower(),
            "--no-update",
            "--data-dir",
            str(data),
            "--min-magnitude",
            "0",
            "--show-unchecked",
            "--output",
            str(output),
        ],
    )
    assert result.exit_code == 0, result.output
    console = " ".join(result.output.split())
    assert "cannot check against its sources" in console
    assert RSID in console
    if surface == "json":
        report = json.loads(output.read_text())
        assert report["input"]["array_quality"]["di_calls"] == 1
        assert report["input"]["probe_classes"]["di_calls_at_plp_rsids"] == 1
        named = [item for item in report["high_value_unchecked"] if item["rsid"] == RSID]
        assert len(named) == 1 and named[0]["reason"] == "di_call"
        assert [
            w["count"] for w in report["report_warnings"] if w["code"] == "di_calls_not_checked"
        ] == [1]
        assert report["annotations"] == []
    else:
        page = " ".join(output.read_text().split())
        assert "cannot check against its sources" in page
        assert RSID in page
        assert "ClinVar classifies this allele as Pathogenic" not in page
    assert "Test condition" not in console
