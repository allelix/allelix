"""Compare observations by their allele identity, independent of row order."""

from __future__ import annotations

import gzip
import re

import pytest
from click.testing import CliRunner

from allelix.cli import main
from allelix.compare import compare_variants
from allelix.parsers.twentythreeandme import TwentyThreeAndMeParser
from allelix.parsers.vcf import VcfParser

RSID = "rs900260345"


def _row(ref="G", alt="A", gt="0/1", *, rsid=RSID, pos=100):
    return f"1\t{pos}\t{rsid}\t{ref}\t{alt}\t.\tPASS\t.\tGT\t{gt}\n"


def _vcf(tmp_path, name, rows, build="GRCh38", compressed=False):
    length = 249250621 if build == "GRCh37" else 248956422
    text = (
        f"##fileformat=VCFv4.2\n##contig=<ID=1,length={length}>\n"
        "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tS\n" + "".join(rows)
    )
    path = tmp_path / (name + (".vcf.gz" if compressed else ".vcf"))
    if compressed:
        path.write_bytes(gzip.compress(text.encode(), mtime=0))
    else:
        path.write_text(text)
    return path, list(VcfParser().parse(path))


def _chip(tmp_path, name, genotype, build="GRCh38", pos=100):
    path = tmp_path / f"{name}.txt"
    path.write_text(
        "# This data file generated by 23andMe at: synthetic\n"
        f"# reference human assembly build {build[-2:]}\n"
        f"# rsid\tchromosome\tposition\tgenotype\n{RSID}\t1\t{pos}\t{genotype}\n"
    )
    return path, list(TwentyThreeAndMeParser().parse(path))


def _compare(left, right, build="GRCh38"):
    return compare_variants(left, right, build1=build, build2=build)


@pytest.mark.parametrize("build", ["GRCh37", "GRCh38"])
@pytest.mark.parametrize("orders", [(False, False), (False, True), (True, False), (True, True)])
@pytest.mark.parametrize("different_call", [False, True])
@pytest.mark.parametrize("compressed", [False, True])
def test_each_named_split_record_has_its_own_partner(
    tmp_path, build, orders, different_call, compressed
):
    a = [_row(), _row(alt="T", gt="1/1")]
    b = [_row(gt="1/1" if different_call else "0/1"), _row(alt="T", gt="1/1")]
    _, left = _vcf(tmp_path, "left", a[::-1] if orders[0] else a, build, compressed)
    _, right = _vcf(tmp_path, "right", b[::-1] if orders[1] else b, build, compressed)
    result = _compare(left, right, build)
    assert (result.file1_total, result.file2_total, result.shared_named) == (2, 2, 2)
    assert (result.shared, result.concordant, result.discordant) == (
        2,
        1 if different_call else 2,
        int(different_call),
    )
    assert result.file1_only == result.file2_only == 0


@pytest.mark.parametrize("build", ["GRCh37", "GRCh38"])
@pytest.mark.parametrize("named", [False, True])
@pytest.mark.parametrize("shape", ["prefix", "suffix", "both"])
@pytest.mark.parametrize("gt", ["0/1", "0|1", "1/1", "1", "./."])
def test_padded_and_trimmed_observations_compare_the_same(tmp_path, build, named, shape, gt):
    ref, alt, pos = {
        "prefix": ("CG", "CA", 99),
        "suffix": ("GC", "AC", 100),
        "both": ("CGC", "CAC", 99),
    }[shape]
    rsid = RSID if named else "."
    _, left = _vcf(tmp_path, "left", [_row(ref, alt, gt, rsid=rsid, pos=pos)], build)
    _, right = _vcf(tmp_path, "right", [_row(gt=gt, rsid=rsid)], build)
    result = _compare(left, right, build)
    assert result.shared == 1
    assert result.no_call == int(gt == "./.")
    assert result.concordant == int(gt != "./.")
    assert result.discordant == 0
    assert result.file1_only == result.file2_only == 0


@pytest.mark.parametrize("build", ["GRCh37", "GRCh38"])
@pytest.mark.parametrize(
    "left,right",
    [
        (_row("A", "C", "1/1"), _row("G", "C", "1/1")),
        (_row(alt="A,T"), _row(alt="A,C")),
        (_row(alt="A,T", gt="1/2"), _row(alt="T,A", gt="2/1")),
        (_row(alt="A", gt="./."), _row(alt="T", gt="./.")),
    ],
)
def test_a_different_literal_pair_is_not_shared_even_if_the_call_matches(
    tmp_path, build, left, right
):
    _, a = _vcf(tmp_path, "left", [left], build)
    _, b = _vcf(tmp_path, "right", [right], build)
    result = _compare(a, b, build)
    assert (result.shared, result.file1_only, result.file2_only) == (0, 1, 1)
    assert result.concordant == result.discordant == result.no_call == 0


@pytest.mark.parametrize("build", ["GRCh37", "GRCh38"])
@pytest.mark.parametrize("reverse", [False, True])
@pytest.mark.parametrize("swap", [False, True])
def test_split_and_merged_records_do_not_invent_a_partner(tmp_path, build, reverse, swap):
    rows = [_row(alt="A"), _row(alt="T")]
    _, split = _vcf(tmp_path, "split", rows[::-1] if reverse else rows, build)
    _, merged = _vcf(tmp_path, "merged", [_row(alt="A,T", gt="1/2")], build)
    a, b = (merged, split) if swap else (split, merged)
    result = _compare(a, b, build)
    assert result.shared == 0
    assert (result.file1_total, result.file2_total) == ((1, 2) if swap else (2, 1))
    assert (result.file1_only, result.file2_only) == ((1, 2) if swap else (2, 1))


@pytest.mark.parametrize("reverse", [False, True])
@pytest.mark.parametrize("swap", [False, True])
@pytest.mark.parametrize("gt", ["0/1", "1/2", "2", "./."])
def test_merged_multiallelic_record_keeps_all_literal_alts(tmp_path, reverse, swap, gt):
    rows = [_row(alt="A,T", gt=gt), _row(alt="C", pos=200)]
    _, a = _vcf(tmp_path, "left", rows[::-1] if reverse else rows)
    _, b = _vcf(tmp_path, "right", rows[::-1])
    if swap:
        a, b = b, a
    result = _compare(a, b)
    assert result.shared == 2
    assert result.no_call == int(gt == "./.")
    assert result.concordant == 2 - int(gt == "./.")


@pytest.mark.parametrize("build", ["GRCh37", "GRCh38"])
@pytest.mark.parametrize("reverse", [False, True])
@pytest.mark.parametrize("swap", [False, True])
@pytest.mark.parametrize("padding", [False, True])
def test_chip_uses_the_unique_explaining_record_not_the_last_rsid(
    tmp_path, build, reverse, swap, padding
):
    matching = _row("CA", "CC", "0/1", pos=99) if padding else _row("A", "C")
    rows = [matching, _row("A", "G")]
    _, vcf = _vcf(tmp_path, "vcf", rows[::-1] if reverse else rows, build)
    _, chip = _chip(tmp_path, "chip", "AC", build)
    a, b = (vcf, chip) if swap else (chip, vcf)
    result = _compare(a, b, build)
    assert (result.shared, result.concordant, result.discordant) == (1, 1, 0)
    assert (result.file1_only, result.file2_only) == ((1, 0) if swap else (0, 1))


@pytest.mark.parametrize("reason,genotype", [("none", "CG"), ("multiple", "AA")])
@pytest.mark.parametrize("reverse", [False, True])
@pytest.mark.parametrize("swap", [False, True])
def test_chip_without_a_unique_explanation_is_not_compared(
    tmp_path, reason, genotype, reverse, swap
):
    # Neither CG nor its complement fits A>C or A>G. AA fits both pairs,
    # regardless of which genotype the VCF records happen to carry.
    rows = [_row("A", "C"), _row("A", "G")]
    vpath, vcf = _vcf(tmp_path, "vcf", rows[::-1] if reverse else rows)
    cpath, chip = _chip(tmp_path, "chip", genotype)
    a, b = (vcf, chip) if swap else (chip, vcf)
    result = _compare(a, b)
    assert result.shared == 0
    assert result.concordant == result.discordant == result.no_call == 0
    paths = (vpath, cpath) if swap else (cpath, vpath)
    cli = CliRunner().invoke(
        main, ["compare", *(str(p) for p in paths), "--build1", "grch38", "--build2", "grch38"]
    )
    assert cli.exit_code == 0, cli.output
    text = re.sub(r"\s+", " ", cli.output.lower())
    assert "not compared" in text and re.search(r"\b1\b", text), text
    if reason == "none":
        assert re.search(r"no (?:matching|compatible|explaining)|none", text), text
    else:
        assert re.search(r"multiple|ambiguous|more than one", text), text


@pytest.mark.parametrize("genotype", ["AG", "AA", "A", "--", "DI"])
@pytest.mark.parametrize("swap", [False, True])
def test_chip_to_chip_stays_identifier_based(tmp_path, genotype, swap):
    _, a = _chip(tmp_path, "left", genotype, "GRCh37", 100)
    _, b = _chip(tmp_path, "right", genotype, "GRCh38", 200)
    if swap:
        a, b = b, a
    result = compare_variants(a, b)
    assert result.shared_named == 1
    assert result.concordant == int(genotype != "--")
    assert result.no_call == int(genotype == "--")


def test_unique_chip_match_keeps_existing_opposite_strand_comparison(tmp_path):
    _, chip = _chip(tmp_path, "chip", "CT")
    _, vcf = _vcf(tmp_path, "vcf", [_row("G", "A")])
    result = _compare(chip, vcf)
    assert (result.shared, result.strand_flip_match, result.discordant) == (1, 1, 0)


@pytest.mark.parametrize("build", ["GRCh37", "GRCh38"])
@pytest.mark.parametrize("gt", ["1/2", "2|1", "0/2", "./."])
def test_multiallelic_padding_preserves_literal_alt_order(tmp_path, build, gt):
    _, a = _vcf(tmp_path, "padded", [_row("CG", "CA,CT", gt, pos=99)], build)
    _, b = _vcf(tmp_path, "trimmed", [_row("G", "A,T", gt)], build)
    result = _compare(a, b, build)
    assert result.shared == 1
    assert result.no_call == int(gt == "./.")
    assert result.concordant == int(gt != "./.")


@pytest.mark.parametrize("swap", [False, True])
def test_chip_partner_uses_declared_alleles_even_when_genotypes_disagree(tmp_path, swap):
    _, chip = _chip(tmp_path, "chip", "AC")
    _, vcf = _vcf(tmp_path, "vcf", [_row("A", "C", "1/1"), _row("A", "G")])
    a, b = (vcf, chip) if swap else (chip, vcf)
    result = _compare(a, b)
    assert (result.shared, result.discordant, result.concordant) == (1, 1, 0)
    assert (result.file1_only, result.file2_only) == ((1, 0) if swap else (0, 1))


def test_repeat_shift_is_not_left_aligned(tmp_path):
    _, a = _vcf(tmp_path, "left", [_row("AT", "A", "1/1", pos=100)])
    _, b = _vcf(tmp_path, "right", [_row("TA", "T", "1/1", pos=101)])
    result = _compare(a, b)
    assert (result.shared, result.file1_only, result.file2_only) == (0, 1, 1)


def test_named_pair_can_still_match_across_builds(tmp_path):
    _, a = _vcf(tmp_path, "left", [_row(pos=100)], "GRCh37")
    _, b = _vcf(tmp_path, "right", [_row(pos=200)], "GRCh38")
    result = compare_variants(a, b, build1="GRCh37", build2="GRCh38")
    assert (result.shared_named, result.concordant) == (1, 1)
