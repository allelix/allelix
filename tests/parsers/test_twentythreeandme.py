class TestGrch36Label:
    def test_a_build_36_label_without_known_snps_runs_on_grch36(self, tmp_path: Path) -> None:
        """No known-SNP position checks the label, yet GRCh36 is not a stop: it
        turns position lookups off (ADR-0025), as --build grch36 does."""
        from allelix.reports._pipeline import decide_file_build

        f = _write(
            tmp_path,
            "# This data file generated by 23andMe at: Mon Jan 01 00:00:00 2001\n"
            "# We are using reference human assembly build 36.\n"
            "# rsid\tchromosome\tposition\tgenotype\n"
            "rs3999990501\tMT\t1001\tA\n"
            "rs3999990502\tMT\t1002\tG\n",
        )
        parser = TwentyThreeAndMeParser()
        decision = decide_file_build(parser, f, parser.get_metadata(f), override=None)
        assert (decision.build, decision.source) == ("GRCh36", "file_label")


