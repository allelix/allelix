class TestV5Preamble:
    """Current v5 exports put file_id, signature and timestamp lines before the banner."""

    def test_can_parse(
        self, parser: TwentyThreeAndMeParser, mock_23andme_v5_preamble_path: Path
    ) -> None:
        assert parser.can_parse(mock_23andme_v5_preamble_path) is True

    def test_registry_detects_23andme(self, mock_23andme_v5_preamble_path: Path) -> None:
        from allelix.parsers import detect_parser

        assert detect_parser(mock_23andme_v5_preamble_path).name == "23andme"

    def test_no_other_parser_claims_it(self, mock_23andme_v5_preamble_path: Path) -> None:
        from allelix.parsers import PARSERS

        claimants = [
            p.name
            for p in PARSERS
            if p.name != "23andme" and p.can_parse(mock_23andme_v5_preamble_path)
        ]
        assert claimants == []

    def test_parse_yields_rows(
        self, parser: TwentyThreeAndMeParser, mock_23andme_v5_preamble_path: Path
    ) -> None:
        variants = list(parser.parse(mock_23andme_v5_preamble_path))
        assert len(variants) == 12
        by_id = {v.rsid: v for v in variants}
        assert (by_id["rs1801133"].allele1, by_id["rs1801133"].allele2) == ("A", "G")
        assert by_id["i3000043"].position == 33951693
        assert by_id["rs9001001"].is_no_call
        # One-letter Y call: only the read allele is pinned here, so a change
        # to how haploid calls are represented does not break this test.
        assert by_id["rs9001004"].chromosome == "Y"
        assert by_id["rs9001004"].allele1 == "A"

    def test_metadata_reads_build_after_preamble(
        self, parser: TwentyThreeAndMeParser, mock_23andme_v5_preamble_path: Path
    ) -> None:
        assert parser.get_metadata(mock_23andme_v5_preamble_path)["build"] == "GRCh37"
