@pytest.fixture
def parser() -> TwentyThreeAndMeParser:
    return TwentyThreeAndMeParser()


def _write(tmp_path: Path, contents: str, name: str = "f.txt") -> Path:
    f = tmp_path / name
    f.write_text(contents, encoding="utf-8")
    return f


