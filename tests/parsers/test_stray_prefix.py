"""A few characters typed before a known banner's ``#`` no longer stop detection.

Seen in uploads: characters (a digit, backticks and tabs; one letter) typed
before the first ``#`` of a 23andMe v5 preamble or an AncestryDNA banner.
At most ``STRAY_PREFIX_MAX`` characters on the first non-blank line are
dropped, with a notice; what follows still has to be the reader's banner.

Placeholder header values and invented rows (rs3999990900 range) only.
"""

from __future__ import annotations

import gzip
import json
import zipfile
from typing import TYPE_CHECKING

import pytest
from click.testing import CliRunner

from allelix.cli import main
from allelix.parsers import ParserNotFoundError, detect_parser
from allelix.parsers._helpers import STRAY_PREFIX_MAX

if TYPE_CHECKING:
    from pathlib import Path

_23ANDME = [
    "# file_id: 00000000-0000-0000-0000-000000000000",
    "# signature: PLACEHOLDER-SIGNATURE",
    "# timestamp: 2001-01-01 00:00:00",
    "#",
    "# This data file is generated by 23andMe.",
    "#",
    "# rsid\tchromosome\tposition\tgenotype",
    "rs3999990901\t1\t1000101\tAG",
    "rs3999990902\t1\t1000202\tCC",
    "rs3999990903\t2\t2000303\tCT",
]
_ANCESTRY = [
    "#AncestryDNA raw data download",
    "#",
    "rsid\tchromosome\tposition\tallele1\tallele2",
    "rs3999990911\t1\t1000101\tA\tG",
    "rs3999990912\t1\t1000202\tC\tC",
]
CASES = [
    ("23andme", "1`\t\t``\t`", _23ANDME, 3),
    ("ancestrydna", "X", _ANCESTRY, 2),
]
ENDINGS = [("lf", "\n"), ("crlf", "\r\n"), ("cr", "\r")]


def _write(tmp_path: Path, lines: list[str], newline: str, wrap: str) -> Path:
    data = newline.join([*lines, ""]).encode()
    if wrap == "gzip":
        path = tmp_path / "f.txt.gz"
        path.write_bytes(gzip.compress(data))
    elif wrap == "zip":
        path = tmp_path / "f.zip"
        with zipfile.ZipFile(path, "w") as z:
            z.writestr("f.txt", data)
    else:
        path = tmp_path / "f.txt"
        path.write_bytes(data)
    return path


@pytest.mark.parametrize("wrap", ["plain", "gzip", "zip"])
@pytest.mark.parametrize(("ending", "newline"), ENDINGS, ids=[e for e, _ in ENDINGS])
@pytest.mark.parametrize(("reader", "prefix", "lines", "rows"), CASES, ids=[c[0] for c in CASES])
def test_characters_before_a_known_banner_are_dropped(
    tmp_path: Path,
    reader: str,
    prefix: str,
    lines: list[str],
    rows: int,
    ending: str,
    newline: str,
    wrap: str,
) -> None:
    path = _write(tmp_path, [prefix + lines[0], *lines[1:]], newline, wrap)
    parser = detect_parser(path)
    assert parser.name == reader
    assert sum(1 for _ in parser.parse(path)) == rows


def test_more_than_the_limit_is_not_dropped(tmp_path: Path) -> None:
    lines = ["X" * (STRAY_PREFIX_MAX + 1) + _ANCESTRY[0], *_ANCESTRY[1:]]
    with pytest.raises(ParserNotFoundError):
        detect_parser(_write(tmp_path, lines, "\n", "plain"))


def test_what_follows_must_still_be_a_banner(tmp_path: Path) -> None:
    lines = ["X# placeholder comment", "rsid\tchromosome\tposition\tgenotype", *_23ANDME[7:]]
    with pytest.raises(ParserNotFoundError):
        detect_parser(_write(tmp_path, lines, "\n", "plain"))


def test_only_the_first_line_is_touched(tmp_path: Path) -> None:
    """A later line is a row; nothing in it is dropped."""
    lines = [*_23ANDME[:7], "X#\t1\t1000101\tAG", *_23ANDME[7:]]
    path = _write(tmp_path, lines, "\n", "plain")
    parser = detect_parser(path)
    rsids = [v.rsid for v in parser.parse(path)]
    assert rsids[0] == "X#"


def test_the_dropped_characters_are_a_report_warning(
    tmp_path: Path, clinvar_data_dir: Path
) -> None:
    path = _write(tmp_path, ["X" + _ANCESTRY[0], *_ANCESTRY[1:]], "\r\n", "plain")
    out = tmp_path / "r.json"
    result = CliRunner().invoke(
        main,
        [
            "analyze", str(path), "--build", "grch37", "--no-update",
            "--data-dir", str(clinvar_data_dir), "--output", str(out),
        ],
        env={"COLUMNS": "300"},
    )  # fmt: skip
    assert result.exit_code == 0, result.output
    assert "1 character(s) before the first '#' on its first line were ignored" in result.output
    codes = [w["code"] for w in json.loads(out.read_text())["report_warnings"]]
    assert codes.count("input_stray_characters") == 1
