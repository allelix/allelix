"""Files whose source Allelix cannot identify are rejected, not read.

Each shape here is a vendor's column layout with no header that names the
vendor: a 23andMe-style table under a converter's or a person's own comment
lines, or a bare column line. Allelix does not read them (owner decision,
2026-10-17): it cannot tell which strand such a file is on, and reading one
on the other strand gives wrong ClinVar results. Every shape must get "doesn't
recognise the format" with no traceback and no report, with LF, CRLF and
CR-only line endings, plain and gzipped.

Placeholder header text and invented rows (the rs3999990000 range) only.
"""

from __future__ import annotations

import gzip
from typing import TYPE_CHECKING

import pytest
from click.testing import CliRunner

from allelix.cli import main
from allelix.parsers import ParserNotFoundError, detect_parser

if TYPE_CHECKING:
    from pathlib import Path

_COL = "# rsid\tchromosome\tposition\tgenotype"
_ROWS4 = [
    "rs3999990601\t1\t1000101\tAG",
    "rs3999990602\t1\t1000202\tCC",
    "rs3999990603\t2\t2000303\tCT",
    "rs3999990604\t3\t3000404\t--",
    "rs3999990605\tX\t4000505\tA",
]
_ROWS5 = [
    "rs3999990611\t1\t1000101\tA\tG",
    "rs3999990612\t1\t1000202\tC\tC",
    "rs3999990613\t2\t2000303\tC\tT",
    "rs3999990614\t3\t3000404\t0\t0",
]

SHAPES = [
    ("no-header-4-columns", _ROWS4),
    ("no-header-5-columns", _ROWS5),
    ("column-comment-only", [_COL, *_ROWS4]),
    ("bare-column-line", ["rsid\tchromosome\tposition\tgenotype", *_ROWS4]),
    ("bare-column-line-capital-genotype", ["rsid\tchromosome\tposition\tGenotype", *_ROWS4]),
    ("bare-5-column-line", ["rsid\tchromosome\tposition\tallele1\tallele2", *_ROWS5]),
    (
        "unknown-vendor-banner",
        [
            "# PLACEHOLDER GENETICS file generated at: Mon Jan 01 00:00:00 2001",
            "#",
            "# This file contains raw genotype data.",
            "#",
            _COL,
            *_ROWS4,
        ],
    ),
    (
        "converter-comment-with-build",
        [
            "# Converted to 23andMe-style raw genotype format.",
            "# Reference build: GRCh38",
            _COL,
            *_ROWS4,
        ],
    ),
    ("one-comment-line", ["# Placeholder imputed file", _COL, *_ROWS4]),
    ("another-comment-line", ["# This file contains raw DNA data.", _COL, *_ROWS4]),
    (
        "masked-service-banner",
        [
            "# Placeholder for Placeholder v1.2.1: filtered, placeholder genotype calls. For "
            "more information, go to: https://example.invalid/readme",
            "#",
            _COL,
            *_ROWS4,
        ],
    ),
    (
        "converted-genomestudio-comment",
        ["# Converted from Placeholder/GenomeStudio raw genotype export.", _COL, *_ROWS4],
    ),
    (
        "test-generator-banner",
        ["# This data file generated by placeholder-test-generator", _COL, *_ROWS4],
    ),
]

ENDINGS = [("lf", "\n"), ("crlf", "\r\n"), ("cr", "\r")]


def _write(tmp_path: Path, case: str, lines: list[str], newline: str, gz: bool) -> Path:
    data = newline.join([*lines, ""]).encode()
    if gz:
        path = tmp_path / f"{case}.txt.gz"
        path.write_bytes(gzip.compress(data))
    else:
        path = tmp_path / f"{case}.txt"
        path.write_bytes(data)
    return path


@pytest.mark.parametrize("gz", [False, True], ids=["plain", "gzip"])
@pytest.mark.parametrize(("ending", "newline"), ENDINGS, ids=[e for e, _ in ENDINGS])
@pytest.mark.parametrize(("case", "lines"), SHAPES, ids=[s[0] for s in SHAPES])
def test_no_parser_claims_an_unidentified_file(
    tmp_path: Path, case: str, lines: list[str], ending: str, newline: str, gz: bool
) -> None:
    path = _write(tmp_path, case, lines, newline, gz)
    with pytest.raises(ParserNotFoundError, match="doesn't recognise the format"):
        detect_parser(path)


@pytest.mark.parametrize("gz", [False, True], ids=["plain", "gzip"])
@pytest.mark.parametrize(("case", "lines"), SHAPES, ids=[s[0] for s in SHAPES])
def test_analyze_rejects_it_cleanly_and_writes_no_report(
    tmp_path: Path, case: str, lines: list[str], gz: bool
) -> None:
    path = _write(tmp_path, case, lines, "\r\n", gz)
    out = tmp_path / "report.json"
    result = CliRunner().invoke(
        main,
        ["analyze", str(path), "--no-update", "--data-dir", str(tmp_path), "--output", str(out)],
        env={"COLUMNS": "300"},
    )
    assert result.exit_code != 0
    assert "doesn't recognise the format" in result.output
    assert "Traceback" not in result.output
    assert isinstance(result.exception, SystemExit)
    assert not out.exists()


class TestNothingIsLeftOfTheGenericReader:
    """What existed only for the generic reader is gone, so it cannot be half-used."""

    def test_no_reader_by_shape_is_installed(self) -> None:
        import importlib.util

        assert importlib.util.find_spec("allelix.parsers.generic") is None

    def test_metadata_has_no_unused_build(self) -> None:
        from allelix.parsers.base import GenotypeMetadata

        assert "unused_build" not in GenotypeMetadata.__annotations__

    def test_the_build_decision_has_no_unused_label(self) -> None:
        import inspect

        from allelix.utils.build_detect import BuildDecision, decide_build

        assert "unused_label" not in BuildDecision._fields
        assert "unused_label" not in inspect.signature(decide_build).parameters

    def test_build_evidence_has_no_unused_label(self, tmp_path: Path) -> None:
        from allelix.parsers.twentythreeandme import TwentyThreeAndMeParser
        from allelix.reports._pipeline import run_analysis

        path = tmp_path / "f.txt"
        path.write_text(
            "# This data file generated by 23andMe at: Mon Jan 01 00:00:00 2001\n"
            "# We are using reference human assembly build 37.\n" + "\n".join(_ROWS4) + "\n"
        )
        result = run_analysis(path, TwentyThreeAndMeParser(), [], build_override="GRCh37")
        assert result.build_diagnostics is not None
        assert "file_label_unused" not in result.build_diagnostics.evidence()

    def test_no_console_line_for_counts_no_reader_sets(self) -> None:
        """No 2.5 reader counts unreadable calls, converter-filled rows or wrong-width
        rows; JSON keeps the zero counts (ADR-0051), the console says nothing."""
        from allelix.parsers.base import ArrayInputStats
        from allelix.reports import array_quality_lines

        stats = ArrayInputStats(unreadable_genotypes=2, not_genotyped=3, wrong_column_rows=4)
        assert array_quality_lines(stats, None) == []
