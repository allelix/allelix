"""Vendor header shapes from uploads that once failed with "No parser recognized".

Each case is a vendor header shape users' files have had, with obvious
placeholder values, and invented rows (the rs39999904xx range). The tests
show that the shape is now recognised by its vendor's reader, with LF and
CRLF line endings. They do not show that any real file analyses: only
header shapes were known. Shapes with no vendor header are rejected
(``test_unidentified_files_rejected.py``).
"""

from __future__ import annotations

from typing import TYPE_CHECKING

import pytest

from allelix.parsers import detect_parser

if TYPE_CHECKING:
    from pathlib import Path

_COL = "# rsid\tchromosome\tposition\tgenotype"
_ROWS = [
    "rs3999990401\t1\t1000101\tAG",
    "rs3999990402\t1\t1000202\tCC",
    "rs3999990403\t2\t2000303\tCT",
    "rs3999990404\t3\t3000404\t--",
    "rs3999990405\tX\t4000505\tA",
    "rs3999990406\t5\t5000606\tGG",
]
_V5 = [
    "# file_id: 00000000-0000-0000-0000-000000000000",
    "# signature: PLACEHOLDER-SIGNATURE",
    "# timestamp: 2001-01-01 00:00:00",
    "#",
    "# This data file is generated by 23andMe.",
    "#",
    _COL,
]

# (case, header lines, reader). "assumed" in a case name: only the first
# line of that shape was known, and the rest follows the format's envelope.
CASES = [
    ("23andme-v5-preamble-assumed", _V5, "23andme"),
    (
        "23andme-v5-banner-assumed",
        ["# This data file is generated by 23andMe.", "#", _COL],
        "23andme",
    ),
    (
        "genes-for-good-banner-assumed",
        [
            "# Genes for Good v1.2.1: filtered, placeholder genotype calls. For more "
            "information, go to: https://example.invalid/readme",
            "# This data file generated by PLINK on: 01/01/00",
            "#",
            _COL,
        ],
        "genesforgood",
    ),
]


@pytest.mark.parametrize("newline", ["\n", "\r\n"], ids=["lf", "crlf"])
@pytest.mark.parametrize(("case", "header", "reader"), CASES, ids=[c[0] for c in CASES])
def test_reported_header_shape_is_recognised(
    tmp_path: Path, case: str, header: list[str], reader: str, newline: str
) -> None:
    path = tmp_path / f"{case}.txt"
    path.write_bytes(newline.join([*header, *_ROWS, ""]).encode())
    parser = detect_parser(path)
    assert parser.name == reader
    assert sum(1 for _ in parser.parse(path)) == len(_ROWS)


@pytest.mark.parametrize("newline", ["\n", "\r\n"], ids=["lf", "crlf"])
def test_myheritage_spreadsheet_save_with_a_comma_line_is_recognised(
    tmp_path: Path, newline: str
) -> None:
    path = tmp_path / "resaved.csv"
    lines = [
        "#,,,",
        "MyHeritage DNA raw data.,,,",
        "RSID,CHROMOSOME,POSITION,RESULT",
        *('"' + row.replace("\t", '","') + '"' for row in _ROWS),
        "",
    ]
    path.write_bytes(newline.join(lines).encode())
    parser = detect_parser(path)
    assert parser.name == "myheritage"
    assert sum(1 for _ in parser.parse(path)) == len(_ROWS)
