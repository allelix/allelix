@pytest.mark.usefixtures("require_unreadable_files")
def test_an_unreadable_diff_baseline_is_refused_by_the_option_check(tmp_path, analyze_inputs):
    """Control: click's own --diff check refuses an unreadable file as a usage
    error, before any of the command runs."""
    data, genome, calls = analyze_inputs
    baseline = tmp_path / "baseline.json"
    baseline.write_text("{}")
    baseline.chmod(0)
    try:
        result = CliRunner().invoke(
            main, ["analyze", str(genome), "--data-dir", str(data), "--diff", str(baseline)]
        )
    finally:
        baseline.chmod(0o644)
    assert result.exit_code == 2, result.output
    assert "is not readable" in " ".join(result.output.split())
    assert calls == []


def test_report_format_overrides_an_unknown_extension(tmp_path, analyze_inputs):
    """Control: --report-format still names the format for any file name."""
    data, genome, calls = analyze_inputs
    out = tmp_path / "r.txt"
    result = CliRunner().invoke(
        main,
        [
            "analyze",
            str(genome),
            "--data-dir",
            str(data),
            "--output",
            str(out),
            "--report-format",
            "json",
        ],
    )
    assert result.exit_code == 0, result.output
    assert out.exists()
    assert calls == ["prepare", "refresh"]
