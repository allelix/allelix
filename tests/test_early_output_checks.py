@pytest.fixture
def analyze_inputs(tmp_path, monkeypatch):
    data = tmp_path / "data"
    data.mkdir()
    for build in ("GRCh37", "GRCh38"):
        _clinvar_cache(data / f"clinvar.{build}.sqlite", build, "md5:" + "0" * 32)
    genome = tmp_path / "genome.txt"
    genome.write_text(_CHIP)
    calls: list[str] = []
    monkeypatch.setattr(_helpers, "_prepare_caches", lambda *a, **k: calls.append("prepare"))
    monkeypatch.setattr(
        _helpers, "_maybe_refresh_databases", lambda *a, **k: calls.append("refresh")
    )
    return data, genome, calls


def test_r07_unknown_output_extension_is_refused_before_the_update_step(tmp_path, analyze_inputs):
    """ADR-0056: every requested report destination is validated before cache
    setup or refresh. `--output report.txt` (no --report-format) is refused only
    after the update step (network probes, cache rebuilds) and the whole analysis."""
    data, genome, calls = analyze_inputs
    result = CliRunner().invoke(
        main,
        ["analyze", str(genome), "--data-dir", str(data), "--output", str(tmp_path / "r.txt")],
    )
    assert result.exit_code != 0
    assert "Cannot infer report format" in result.output, result.output
    assert calls == [], f"the update step ran before the destination was refused: {calls}"


def test_r07_unreadable_diff_baseline_is_refused_before_the_update_step(tmp_path, analyze_inputs):
    data, genome, calls = analyze_inputs
