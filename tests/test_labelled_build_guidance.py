"""An unchecked build label gives a concrete override without changing the stop."""

from __future__ import annotations

import re

import pytest
from click.testing import CliRunner

from allelix.cli import main
from allelix.parsers import detect_parser
from allelix.utils.build_detect import NO_SEEDS, decide_build

COMMANDS = ("analyze", "methylation", "pharmacogenomics", "stats", "extract", "plink")


def _input(tmp_path, kind, build):
    path = tmp_path / ("mock.txt" if kind == "chip" else "mock.vcf")
    if kind == "chip":
        path.write_text(
            "# This data file generated by 23andMe\n"
            f"# We are using reference human assembly build {build[-2:]}\n"
            "# rsid\tchromosome\tposition\tgenotype\n"
            "rs900260256\t1\t12345\tAG\n"
        )
    else:
        # No contig lengths and no seed rsIDs: only the written label is evidence.
        path.write_text(
            f"##fileformat=VCFv4.2\n##contig=<ID=1,assembly={build}>\n"
            '##FORMAT=<ID=GT,Number=1,Type=String,Description="Genotype">\n'
            "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\tFORMAT\tMOCK\n"
            "1\t12345\trs900260256\tA\tG\t.\tPASS\t.\tGT\t0/1\n"
        )
    assert detect_parser(path).get_metadata(path)["build"] == build
    return path


def _run(tmp_path, data, command, path, override):
    args = (["export", "plink"] if command == "plink" else [command]) + [str(path)]
    args += ["--data-dir", str(data)]
    if override:
        args += ["--build", override.lower()]
    output = tmp_path / "report.json"
    if command in COMMANDS[:3]:
        args += ["--no-update", "--output", str(output)]
    elif command == "extract":
        args += ["--snps", "rs900260256"]
    elif command == "plink":
        args += ["--output-prefix", str(tmp_path / "export")]
    return CliRunner().invoke(main, args), output


@pytest.mark.parametrize("command", COMMANDS)
@pytest.mark.parametrize("kind", ["chip", "vcf"])
@pytest.mark.parametrize("build", ["GRCh37", "GRCh38"])
def test_unchecked_label_names_the_specific_override(
    tmp_path, clinvar_data_dir, command, kind, build
):
    path = _input(tmp_path, kind, build)
    result, output = _run(tmp_path, clinvar_data_dir, command, path, None)
    assert result.exit_code == 1, result.output
    assert not output.exists()
    assert not (tmp_path / "export.bed").exists()
    text = " ".join(result.output.lower().split())
    assert build.lower() in text
    assert "no known-snp" in text
    # Do not make a user choose among three builds after identifying their label.
    choices = set(re.findall(r"--build\s+(grch\d+)", text))
    assert choices == {build.lower()}, result.output


@pytest.mark.parametrize("command", COMMANDS)
@pytest.mark.parametrize("kind", ["chip", "vcf"])
@pytest.mark.parametrize("build", ["GRCh37", "GRCh38"])
def test_the_suggested_override_already_runs_the_file(
    tmp_path, clinvar_data_dir, command, kind, build
):
    path = _input(tmp_path, kind, build)
    result, _ = _run(tmp_path, clinvar_data_dir, command, path, build)
    assert result.exit_code == 0, result.output
    assert "forced with --build" in result.output


def test_old_array_label_keeps_its_existing_safe_exception():
    decision = decide_build(
        file_name="mock.txt",
        kind="array",
        override=None,
        file_label="GRCh36",
        default=None,
        lengths=None,
        seeds=NO_SEEDS,
    )
    assert decision.build == "GRCh36"
